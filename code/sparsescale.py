#!/usr/bin/env python3
"""РЕШАЮЩИЙ СКАН: падает ли подавление на элемент с ростом слоя.

Точная факторизация (`sparsecancel.py`, проверена против прямого
перечисления до 1e-14) даёт подавление сектора

    |Z| / число конфигураций  <=  ( max_{M12} |G| / 2^{a_2} )^{a_3}

Два вердикта «выживает» в прошлом прогоне оказались АРТЕФАКТОМ: они
стояли ровно при `hbar` = 0.39 и 0.78, где `k_4/hbar` близко к `4pi/3` и
`2pi/3`, то есть целочисленная фаза принимает всего ТРИ значения и часть
конфигураций выравнивается. А 0.39 и 0.78 — края прежнего окна, которые
по построению и есть резонансы знаменателя `|2cos(k_d/2 hbar)|`.

ЗДЕСЬ решается судьба архитектуры. Подавление идёт как `q^{a_3}`, где
`q = max|G|/2^{a_2}`, то есть ЛИНЕЙНО по `N` в показателе. А число
конфигураций сектора растёт как `2^{a_2 a_3}`, то есть КВАДРАТИЧНО.
Значит:

  если `q` НЕ падает с `a_2` — подавление линейно по `N`, а преимущество
    сектора по счёту квадратично, и погашение его не убивает.
    АРХИТЕКТУРА ПРОВАЛИВАЕТСЯ;
  если `q ~ c^{a_2}` с `c < 1` — суммарное подавление `c^{a_2 a_3}`,
    квадратично по `N`, и тогда может соперничать со счётом.

Скан по `a_2` при малом `a_1` (чтобы сумма по `M12` оставалась точной) и
при `hbar` СТРОГО внутри окна, в стороне от резонансов.

КОНТРОЛЬ: пустая `M12` даёт `q = |cos(k_4/2 hbar)|^{a_2}` аналитически —
это проверяемая точка, и она же показывает, как выглядело бы
экспоненциальное падение.

  python3 sparsescale.py
"""
import math

import numpy as np

K4 = 4.0 / math.sqrt(6.0)
W = {0: -1.0, 1: 9.0, 2: -16.0, 3: 8.0}


def gmax(a1, a2, hbar):
    """max и среднее |G|/2^a2 по всем M12."""
    sub = np.arange(1 << a2)
    pc = np.array([bin(t).count('1') for t in sub], dtype=float)
    best, acc = 0.0, []
    for m12 in range(1 << (a1 * a2)):
        rows = [(m12 >> (i * a2)) & ((1 << a2) - 1) for i in range(a1)]
        ph = -pc.copy()
        for s in rows:
            ov = np.array([bin(s & int(t)).count('1') for t in sub])
            ph += np.vectorize(lambda m: W.get(int(m), 0.0))(ov)
        g = abs(np.exp(1j * K4 * ph / hbar).sum()) / (1 << a2)
        acc.append(g)
        if g > best:
            best = g
    return best, float(np.mean(acc))


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('КОНТРОЛЬ: пустая M12 -> q = |cos(k_4/2 hbar)|^{a_2}')
    for hb in (0.55, 0.62):
        c = abs(math.cos(K4 / (2 * hb)))
        print(f'  hbar = {hb}: |cos| = {c:.5f}, значит при пустой M12 '
              f'q падал бы как {c:.3f}^a_2 — вот как выглядит '
              f'экспоненциальное падение')
    print()
    print('=' * 78)
    print('СКАН ПО a_2 ПРИ a_1 = 2, hbar строго внутри окна')
    print(f"{'hbar':>7}{'a_2':>5}{'max q':>11}{'средн. q':>11}"
          f"{'ln(max q)/a_2':>16}{'что это значит':>26}")
    for hb in (0.55, 0.62):
        rows = []
        for a2 in (2, 3, 4, 5, 6, 7):
            mx, mn = gmax(2, a2, hb)
            rows.append((a2, mx, mn))
            lg = math.log(max(mx, 1e-300)) / a2
            print(f'{hb:>7.2f}{a2:>5}{mx:>11.6f}{mn:>11.6f}{lg:>16.5f}',
                  flush=True)
        R = np.array(rows)
        # падает ли max q экспоненциально по a_2?
        sl = np.polyfit(R[:, 0], np.log(np.maximum(R[:, 1], 1e-300)), 1)[0]
        print(f'  -> наклон ln(max q) по a_2 = {sl:+.5f}')
        if sl < -0.05:
            print('     max q падает экспоненциально: суммарное подавление '
                  'квадратично по N')
        else:
            print('     max q НЕ падает: подавление линейно по N, а счёт '
                  'сектора квадратичен')
        print()
    print('=' * 78)
    print('''ЧТЕНИЕ. Наклон около нуля означает, что самый выживающий вклад
сектора подавляется лишь как `q^{a_3}` с `q` порядка единицы — то есть
exp(-const * N). А сектор побивает многообразный по счёту множителем
exp(const * N²). Линейное подавление не закрывает квадратичный разрыв, и
тогда вечерняя архитектура 8 октября опровергнута ЧИСЛОМ, а не мнением.''')


if __name__ == '__main__':
    main()

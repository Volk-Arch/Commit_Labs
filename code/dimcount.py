#!/usr/bin/env python3
"""НАСКОЛЬКО ЖЁСТКО ОГРАНИЧЕНИЕ ПО ПОРЯДКОВОЙ РАЗМЕРНОСТИ.

weight.py показал: любой вес из локальных величин имеет p <= 3/2 (обилия
растут как N^{3/2}), а энтропия p = 2. Разрыв в показателе не
закрывается выбором весов - значит менять надо не вес, а ПРОСТРАНСТВО
КОНФИГУРАЦИЙ.

Порядок размерности <= d есть пересечение d линейных порядков, значит
таких не больше (n!)^d, то есть ln <= d n ln n. И тогда три масштаба
ложатся в ряд:
    n ln n      <<      n^{3/2}      <<      n^2
  энтропия при        локальный            полная
   dim <= d             вес                энтропия
Локальный вес сидит РОВНО МЕЖДУ: против полной энтропии бессилен, против
энтропии при ограниченной размерности достаточен. Это не измерение, это
оценка - но она объясняет все девять попыток одной строкой.

Здесь мерим то, чего оценка не даёт: насколько ограничение жёсткое на
самом деле, то есть какая ДОЛЯ порядков имеет dim <= 2, и как она падает.

КОНТРОЛЬ: числа порядков обязаны совпасть с известными (1, 2, 5, 16, 63,
318 неизоморфных на n = 1..6). Если нет - перечислитель не тот, и доли
ничего не значат.
"""
import math
import sys

import numpy as np

from compose2 import posets
from compose2 import dim_le_2

KNOWN = {1: 1, 2: 2, 3: 5, 4: 16, 5: 63, 6: 318, 7: 2045}


def main():
    print(__doc__)
    nmax = int(sys.argv[1]) if len(sys.argv) > 1 else 6
    print(f"{'n':>3}{'порядков':>11}{'известно':>10}{'dim<=2':>9}"
          f"{'доля':>9}{'ln(всего)/n²':>14}{'ln(dim2)/(n ln n)':>19}")
    for n in range(2, nmax + 1):
        P = list(posets(n))
        tot = len(P)
        d2 = sum(1 for R in P if dim_le_2(R))
        kn = KNOWN.get(n, 0)
        ok = '' if tot == kn else '  <-- РАСХОЖДЕНИЕ'
        a = math.log(max(tot, 1)) / (n * n)
        b = (math.log(max(d2, 1)) / (n * math.log(n))
             if n > 1 else float('nan'))
        print(f'{n:>3}{tot:>11}{kn:>10}{d2:>9}{d2 / tot:>9.3f}'
              f'{a:>14.3f}{b:>19.3f}{ok}', flush=True)
    print('\nЧТЕНИЕ: доля dim<=2 обязана быстро падать (ограничение жёсткое),')
    print('а два последних столбца - прикидки показателей: полная энтропия')
    print('насыщается к постоянной от n², ограниченная - от n ln n.')


if __name__ == '__main__':
    main()

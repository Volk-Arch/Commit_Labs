#!/usr/bin/env python3
"""ДОЛЯ, А НЕ СРЕДНЕЕ: ЧТО СМЕШИВАНИЕ НЕ СПАСАЕТ.

ratmix2.py: смесь врага совпала с целью ТОЧНО (0.0 сигм, проверено
подстановкой), но веса вышли 47.1, 15.7, 10.0 - это КОНУС, а не смесь
вероятностей, и 80 столбцов в 9-мерном пространстве его положительно
натягивают. Моя же арифметика бьёт в обратную сторону: разрешив смеси, я
дал врагу не две ручки, а восемьдесят.

Отсюда структурное утверждение, которое и объясняет все восемь закрытий:
никакой КОНЕЧНЫЙ список АНСАМБЛЕВЫХ СРЕДНИХ не исключает семейство,
замкнутое относительно смешивания, как только достижимые векторы
положительно натягивают пространство этих величин.

Но в этом же и выход. Смесь состоит из ТЕХ ЖЕ конфигураций: если
свойство выполняется у засева почти в каждой конфигурации и у врага
почти ни в одной, смешивание не помогает по определению. Это поправка к
прежнему выводу «правило не может быть предикатом»: предикат имитируем,
если спрашивать «СУЩЕСТВУЕТ ли», и не имитируем, если спрашивать
«КАКОВА ДОЛЯ».

Проверка: для КАЖДОЙ отдельной (k, delta) - насколько её собственный
вектор отношений далёк от засева. Если ни одна не близка, то и никакая
их смесь не содержит близких конфигураций.

Сетка взята С ЗАПАСОМ за прежние границы (k до 64, delta от 0.25),
потому что трижды за день граница сетки делала из артефакта «вывод».

КОНТРОЛЬ: независимый засев против цели обязан дать хи2 порядка 9.
"""
import math

import numpy as np

from sectors import sprinkle_d
from lkdeg import layered
from ratios import nm, MMAX


def rats(mk, rep):
    V = np.array([nm(mk())[0] for _ in range(rep)])
    R = V[:, 1:] / np.maximum(V[:, :1], 1.0)
    return R.mean(axis=0), R.std(axis=0) / math.sqrt(rep)


def main():
    print(__doc__)
    rs = np.random.default_rng(3162277)
    n = 1000
    tgt, terr = rats(lambda: sprinkle_d(n, 4, rs), 10)
    print(f'цель (засев d=4, N={n}): '
          + ' '.join(f'{v:.4f}' for v in tgt))

    ctl, cerr = rats(lambda: sprinkle_d(n, 4, rs), 10)
    s = (ctl - tgt) / np.hypot(terr, cerr)
    chi0 = float((s ** 2).sum())
    print(f'КОНТРОЛЬ, независимый засев: хи2 = {chi0:.1f} при {MMAX} '
          f'условиях => {"ОК" if chi0 < 25 else "СБОЙ"}')

    rows = []
    for k in (3, 4, 6, 9, 13, 18, 25, 34, 48, 64):
        for dl in (0.25, 0.5, 1.0, 1.5, 2.0, 3.0, 5.0, 8.0):
            q = dl * k / n
            if q >= 1.0:
                continue
            r, e = rats(lambda: layered(n, k, q, rs), 4)
            sg = (r - tgt) / np.hypot(terr, e)
            rows.append((float((sg ** 2).sum()), k, dl, r))
    rows.sort()
    print(f'\nвсего отдельных (k, delta): {len(rows)}')
    print('пять НАИЛУЧШИХ по хи2 (у каждой - своя подгонка обеих ручек):')
    for chi, k, dl, r in rows[:5]:
        print(f'  k={k:>3} delta={dl:>4}:  хи2={chi:>9.1f}   '
              + ' '.join(f'{v:.3f}' for v in r[:5]) + ' ...')
    kk = [r[1] for r in rows[:5]]
    dd = [r[2] for r in rows[:5]]
    print(f'\nлучшие на границах сетки? k: {sorted(set(kk))}, '
          f'delta: {sorted(set(dd))}')
    print(f'  (границы сетки: k 3..64, delta 0.25..8)')
    print(f'\nИТОГ: контроль {chi0:.1f}, наилучший ОДИНОЧНЫЙ враг '
          f'{rows[0][0]:.1f} на {MMAX} условиях')
    print('ЧТЕНИЕ: если наилучший одиночный враг далёк, то и смесь не')
    print('содержит конфигураций, похожих на засев - смешивание не спасает.')


if __name__ == '__main__':
    main()

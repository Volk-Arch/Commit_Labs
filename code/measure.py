#!/usr/bin/env python3
"""ЗАДАЧА МЕРЫ: меняется ли иерархия счёта при мере роста — пункт 5.

Однородная мера на помеченных порядках ПРИНЯТА, а не выведена, и на ней
стоит каждый счётный аргумент проекта, включая иерархию
`e^{0.173 N²}` (плотный слоистый) против `e^{d N lnN}` (многообразный).
Если мера другая — иерархия другая, и «подавляющее большинство непохожих
порядков» может оказаться артефактом выбора меры.

У простейшей динамики роста — транзитивной перколяции Райдаута–Соркина —
мера выводится в ЗАМКНУТОМ виде. Пары `i < j` включаются независимо с
вероятностью `p`, затем берётся транзитивное замыкание. Замыкание графа
`G` равно порядку `P` тогда и только тогда, когда `links(P) ⊆ G ⊆ P`:
все СВЯЗИ обязаны присутствовать (вывести их нельзя), а НЕсвязи порядка
произвольны (добавление замыкания не меняет). Биномиальная сумма по
необязательным отношениям складывается в единицу, и остаётся

    Pr(P) = p^{L} (1-p)^{M - R},    M = N(N-1)/2

где `L` — число связей, `R` — число отношений. И `L` равно ровно `N_0` —
числу отношений с пустым интервалом, которое уже считается.

КОНТРОЛИ:
  1. `sum_P Pr(P) = 1` ТОЧНО — нетривиальная проверка самого вывода;
  2. `p -> 1`: выживает только цепь (`R = M`);
  3. `p -> 0`: выживает только пустой порядок.

  python3 measure.py
"""
import math

import numpy as np
from scipy.optimize import brentq
from scipy.special import gamma

from ensemble import enumerate_orders


def c2(d):
    return gamma(d + 1) * gamma(d / 2) * gamma(d) / (
        4.0 * gamma(d) * gamma(3 * d / 2))


def mmdim(r):
    try:
        return brentq(lambda d: 2 * c2(d) - r, 0.4, 30.0)
    except Exception:
        return float('nan')


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    PS = (0.05, 0.15, 0.3, 0.5, 0.7, 0.9)
    for n in (6, 7):
        d = enumerate_orders(n)
        rel = d['rel'].astype(float)
        N0 = d['N0'].astype(float)
        hgt = d['hgt'].astype(float)
        S = d['S2']
        M = n * (n - 1) // 2
        npair = float(M)
        print(f'=== N = {n}, порядков {len(rel)} ===')
        print('КОНТРОЛЬ 1: сумма Pr(P) обязана быть ровно 1')
        for p in PS:
            lp = N0 * math.log(p) + (M - rel) * math.log1p(-p)
            tot = np.exp(lp).sum()
            print(f'  p = {p:.2f}: sum Pr = {tot:.10f}  '
                  f'{"ВЕРНО" if abs(tot-1) < 1e-8 else "НЕВЕРНО"}')
        print()
        print('КОНТРОЛЬ 2 и 3: пределы по p')
        for p in (0.999, 0.001):
            lp = N0 * math.log(p) + (M - rel) * math.log1p(-p)
            w = np.exp(lp - lp.max()); w /= w.sum()
            k = int(np.argmax(w))
            print(f'  p = {p}: самый вероятный порядок имеет отношений '
                  f'{rel[k]:.0f} из {M}, вес {w[k]:.6f}')
        print()
        print('СРАВНЕНИЕ МЕР')
        print(f"{'мера':>14}{'энтропия':>11}{'экв. порядков':>15}"
              f"{'доля r':>9}{'d Мирхейма':>12}{'высота':>8}{'<S>/N²':>9}")
        wu = np.ones(len(rel))
        rows = [('однородная', wu)]
        for p in PS:
            lp = N0 * math.log(p) + (M - rel) * math.log1p(-p)
            rows.append((f'перколяция {p:.2f}', np.exp(lp - lp.max())))
        for nm, w in rows:
            w = w / w.sum()
            ent = -(w[w > 0] * np.log(w[w > 0])).sum()
            r = (w * rel).sum() / npair
            print(f'{nm:>14}{ent:>11.4f}{math.exp(ent):>15.1f}'
                  f'{r:>9.4f}{mmdim(r):>12.2f}{(w*hgt).sum():>8.2f}'
                  f'{(w*S).sum()/n**2:>9.4f}', flush=True)
        print()
    print('=' * 78)
    print('''ЧТЕНИЕ. «экв. порядков» = `exp(энтропия)` — эффективное число
порядков при данной мере. У однородной это полное число. Если у
перколяции оно МНОГО меньше, мера сильно сужает ансамбль, и счётные
оценки на однородной мере завышены. А столбец `d Мирхейма` говорит,
смещает ли мера вес к размерности 4: если при каком-то `p` она идёт к 4,
а у однородной сидит около 2 — мера роста УЖЕ отбирает нужное, и задача
отбора частично решается самой динамикой.''')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ЧТО ПРЕДСКАЗЫВАЕТ НЕПРЕРЫВНАЯ ТЕОРИЯ: недостача площади при
фиксированном объёме.

ЗАЧЕМ. Якобсон и Виссер: уравнение Эйнштейна равносильно тому, что
энтропия стационарна при фиксированном объёме в малых ромбах. В простой
форме — недостача площади границы при фиксированном объёме внутри равна
энергии внутри. Чтобы проверять это счётом, надо сперва знать, какую
именно недостачу предсказывает непрерывная геометрия. Коэффициент есть у
Вана (PRD 100, 064020), но формулу дословно выудить не удалось — считаю
сам, и это надёжнее.

УСТРОЙСТВО. В конформно-плоской метрике `ds² = a(eta)²(-deta²+dx²)`
световые конусы ПЛОСКИЕ, поэтому:

  * талия ромба (где сходятся конусы) есть плоская двумерная сфера
    координатного радиуса `(eta2-eta1)/2` при `eta_w = (eta1+eta2)/2`,
    и её ФИЗИЧЕСКАЯ площадь равна `4 pi r² a(eta_w)²`;
  * физический объём берётся точным одномерным интегралом по «линзе»
    (как в `exact.py`), проверенным до 0.000 % на плоском;
  * собственное время есть `∫ a deta` по оси.

ПЛОСКИЙ ЗАКОН. При `a = 1`: `V = (pi/24) tau⁴`, площадь талии
`A = 4 pi (tau/2)² = pi tau²`, поэтому

    A_плоское(V) = pi (24 V/pi)^(1/2) = sqrt(24 pi V) ~ 8.683 sqrt(V)

НЕДОСТАЧА ПРИ ФИКСИРОВАННОМ ОБЪЁМЕ: `dA|_V = A - A_плоское(V)`.

ЧТО ПРОВЕРЯЕТСЯ:
  1. КОНТРОЛЬ: при `a = 1` недостача обязана быть машинным нулём;
  2. знак: у излучения (положительная плотность энергии) недостача
     обязана быть ОТРИЦАТЕЛЬНОЙ — круг на апельсине короче;
  3. пропорциональна ли `dA/A` величине `tau² R_uu`, и с каким
     коэффициентом. Это и есть предсказание для замера счётом.

  python3 predict.py
"""
import math

import numpy as np

from exact import lens, _XG, _WG


def a_of(e, kk, fam):
    e = np.asarray(e, dtype=float)
    return np.ones_like(e) if fam == 'flat' else kk * e


def volume(e1, e2, d, kk, fam):
    """Точный физический объём ромба: 1D интеграл по линзе с весом a⁴."""
    ec = 0.5 * (e1 + e2)
    cuts = sorted({e1, e2} | {t for t in (ec - d / 2, ec + d / 2)
                              if e1 < t < e2})
    V = 0.0
    for lo, hi in zip(cuts[:-1], cuts[1:]):
        et = 0.5 * (hi - lo) * _XG + 0.5 * (hi + lo)
        w = 0.5 * (hi - lo) * _WG
        V += float((lens(et - e1, e2 - et, d)
                    * a_of(et, kk, fam) ** 4 * w).sum())
    return V


def proper_time(e1, e2, kk, fam):
    """∫ a deta по оси (неподвижная пара, d = 0)."""
    et = 0.5 * (e2 - e1) * _XG + 0.5 * (e1 + e2)
    w = 0.5 * (e2 - e1) * _WG
    return float((a_of(et, kk, fam) * w).sum())


def waist_area(e1, e2, kk, fam):
    """Физическая площадь талии: 4 pi r² a(eta_w)², r = (e2-e1)/2."""
    r = 0.5 * (e2 - e1)
    aw = float(a_of(0.5 * (e1 + e2), kk, fam))
    return 4.0 * math.pi * r * r * aw * aw


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    K = 8.683  # sqrt(24 pi) — считаем точно ниже
    K = math.sqrt(24.0 * math.pi)
    print(f'плоский закон: A = {K:.6f} * sqrt(V)')
    print()
    print('КОНТРОЛЬ №1: плоское, недостача обязана быть нулём')
    print(f"{'tau':>8}{'V':>14}{'A':>12}{'A_пл(V)':>12}{'недостача':>13}")
    for tau in (4.0, 6.0, 9.0):
        e1, e2 = 10.0 - tau / 2, 10.0 + tau / 2
        V = volume(e1, e2, 0.0, 1.0, 'flat')
        A = waist_area(e1, e2, 1.0, 'flat')
        print(f'{tau:>8.1f}{V:>14.5f}{A:>12.5f}{K*math.sqrt(V):>12.5f}'
              f'{A - K*math.sqrt(V):>+13.2e}')
    print()
    print('ИЗЛУЧЕНИЕ a = eta. Неподвижная пара вокруг eta_w.')
    print('R_uu(сопутствующий) = 3/eta_w⁴,  t = eta_w²/2.')
    print(f"{'eta_w':>7}{'tau':>8}{'t планк':>9}{'V':>12}{'A':>11}"
          f"{'A_пл(V)':>11}{'dA/A':>11}{'tau²R_uu':>11}"
          f"{'dA/A / tau²R_uu':>17}")
    rows = []
    for ew in (5.0, 6.5, 8.0, 11.0):
        for frac in (0.10, 0.14, 0.20):
            de = frac * ew      # координатная протяжённость
            e1, e2 = ew - de / 2, ew + de / 2
            V = volume(e1, e2, 0.0, 1.0, 'frw')
            A = waist_area(e1, e2, 1.0, 'frw')
            tau = proper_time(e1, e2, 1.0, 'frw')
            Ruu = 3.0 / ew ** 4
            dev = (A - K * math.sqrt(V)) / A
            x = tau ** 2 * Ruu
            rows.append((x, dev))
            print(f'{ew:>7.1f}{tau:>8.3f}{ew**2/2:>9.1f}{V:>12.4f}{A:>11.4f}'
                  f'{K*math.sqrt(V):>11.4f}{dev:>+11.5f}{x:>11.5f}'
                  f'{dev/x:>17.4f}')
    R = np.array(rows)
    print()
    sl = float((R[:, 0] * R[:, 1]).sum() / (R[:, 0] ** 2).sum())
    res = R[:, 1] - sl * R[:, 0]
    print(f'  ПРЕДСКАЗАНИЕ: dA/A = ({sl:+.4f}) * tau² R_uu')
    print(f'  разброс отношения: от {(R[:,1]/R[:,0]).min():.4f} '
          f'до {(R[:,1]/R[:,0]).max():.4f}')
    print(f'  остаток после прямой: {np.abs(res).max()/np.abs(R[:,1]).max()*100:.1f} %'
          f' от размаха')
    print()
    print(f'  знак: {"ОТРИЦАТЕЛЬНЫЙ — недостача, как у круга на апельсине" if sl < 0 else "ПОЛОЖИТЕЛЬНЫЙ — избыток, это против ожидания"}')
    print()
    print('ПЕРЕВОД В СЧЁТ. tau² R_uu = sqrt(24 C_1/pi) * R_uu l², поэтому')
    print(f'  dA/A = ({sl:+.4f}) * sqrt(24/pi) * sqrt(C_1) * R_uu l²')
    print(f'       = ({sl*math.sqrt(24/math.pi):+.4f}) * sqrt(C_1) * R_uu l²')
    print()
    print('  Тот же закон sqrt(C_1), что у обилий цепей, — значит обе')
    print('  величины растут вместе, и отношение «недостача площади к')
    print('  плотности энергии» от размера интервала НЕ зависит. Это')
    print('  и есть то, что надо проверить счётом.')


if __name__ == '__main__':
    main()

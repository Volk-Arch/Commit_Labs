#!/usr/bin/env python3
"""ПРАВИЛО СУММЫ: семейство заперто на d=3, и это проверяемо.

Исправление собственного довода. Я написал (`csg-doc.md`), что число
связей есть наблюдаемая ФОРМЫ и потому неподвластно связям t_k. Это
НЕВЕРНО. Рождаясь с набором предшественников размера m, элемент
получает ровно m прямых связей — это максимальные элементы его
прошлого. Значит

    L = сумма по рождениям от m,   то есть   L ~ n^{1 + beta}

где beta — показатель среднего числа предшественников. А из
csg.py известно beta = 1/(a+1). Сверка с замером csg3:
  a=1: предсказание 1.500, замер 1.474
  a=2:               1.333         1.388
  a=3:               1.250         1.254
  a=4:               1.200         1.238
То есть L управляется связями, и прекрасно.

ПРАВИЛО СУММЫ. Ширина идёт как 1 - 1/(a+1) (по Дилворту ширина на
высоту даёт N, а высота есть 1/(a+1)). Значит

    W + L = (1 - 1/(a+1)) + (1 + 1/(a+1)) = 2   тождественно

А у d-мерного засева W + L = (1 - 1/d) + (2 - 2/d) = 3 - 3/d.
Равенство 3 - 3/d = 2 даёт РОВНО d = 3.

То же иначе: в семействе показатель числа предшественников вынужденно
равен показателю высоты (оба 1/(a+1)), а у засева они 1 - 2/d и 1/d,
и совпадают только при d = 3.

ПРЕДСКАЗАНИЕ, записанное до прогона: a = 2 обязано совпасть с засевом
d = 3 по ширине, связям, высоте И доле связанных. А с засевом d = 4
обязано разойтись по связям, как и вышло (9 сигм).

КОНТРОЛЬ: оба эталона (d=3 и d=4) мерятся тем же кодом в том же
прогоне; правило суммы печатается для всех.
"""
import math

import numpy as np

from csg import fit
from csg2 import grow_rc, observables
from csg3 import tune_r
from sectors import sprinkle_d


def exps(get, ns):
    o = {n: get(n) for n in ns}
    out = {}
    for k in ('L', 'W', 'H'):
        out[k] = fit(ns, [o[n][k] for n in ns])
    out['r'] = (o[ns[-1]]['r'], 0.0)
    return out


def main():
    print(__doc__)
    rs = np.random.default_rng(20261010)
    ns = [125, 250, 500, 1000]

    print('ЭТАЛОНЫ (тот же код, тот же прогон)')
    refs = {}
    for d in (3, 4):
        refs[d] = exps(lambda n, d=d: observables(sprinkle_d(n, d, rs)), ns)
        e = refs[d]
        print(f'  засев d={d}: r={e["r"][0]:.4f}  '
              f'W={e["W"][0]:.4f}±{e["W"][1]:.3f}  '
              f'L={e["L"][0]:.4f}±{e["L"][1]:.3f}  '
              f'H={e["H"][0]:.4f}±{e["H"][1]:.3f}  '
              f'| W+L={e["W"][0]+e["L"][0]:.3f} '
              f'(теория {3-3/d:.3f})')

    print('\nРОСТ, x подобрано под долю связанных соответствующего засева')
    for a, dmatch in ((2, 3), (3, 4)):
        tgt = refs[dmatch]['r'][0]
        lx = tune_r(a, rs, target=tgt)
        g = exps(lambda n, a=a, lx=lx: observables(grow_rc(n, a, lx, rs)),
                 ns)
        print(f'\n  a={a} (цель: засев d={dmatch}, r={tgt:.4f}); '
              f'x={math.exp(lx):.4g}')
        print(f'    r={g["r"][0]:.4f}  W={g["W"][0]:.4f}±{g["W"][1]:.3f}  '
              f'L={g["L"][0]:.4f}±{g["L"][1]:.3f}  '
              f'H={g["H"][0]:.4f}±{g["H"][1]:.3f}')
        print(f'    W+L={g["W"][0]+g["L"][0]:.3f}  '
              f'(правило семейства: 2.000)')
        for d in (3, 4):
            e = refs[d]
            ds = []
            for k in ('W', 'L', 'H'):
                s = math.sqrt(g[k][1] ** 2 + e[k][1] ** 2)
                ds.append(f'{k}={abs(g[k][0]-e[k][0])/max(s,1e-9):.1f}с')
            print(f'    против d={d}: ' + ', '.join(ds)
                  + f', доля связ. {g["r"][0]:.3f} против {e["r"][0]:.3f}')

    print('\nЧТЕНИЕ. Если a=2 сходится с d=3 по всем трём показателям, а')
    print('a=3 расходится с d=4 по связям — правило суммы подтверждено, и')
    print('семейство заперто на размерности три не перебором, а тождеством.')


if __name__ == '__main__':
    main()

"""Второй критерий: самый мелкий точный буст.
Буст g сохраняет Q; в каждой тени (сопряжении) он обязан быть вращением
определённой формы, иначе шар тени испортится. Значит cosh η = g₀₀ = a —
целое алгебраическое a > 1, у которого все сопряжённые лежат в [−1, 1].
Если a < 2, то все сопряжённые в [−2, 2], и по теореме Кронекера a = 2cos(2π/n).
Проверяем, при каких n остальные сопряжённые 2cos(2πj/n) (НОД(j,n)=1) лежат в [−1, 1].
Обычные решётки (поле Q) дают целое a ≥ 2."""
import math
ok = []
for n in range(3, 5001):
    js = [j for j in range(1, n // 2 + 1) if math.gcd(j, n) == 1 and 2 * j != n]
    vals = [2 * math.cos(2 * math.pi * j / n) for j in js]
    big = [v for v in vals if abs(v) > 1 + 1e-12]
    if len(big) == 1 and 1 < big[0] < 2: ok.append((n, big[0], len(js)))
print('n ≤ 5000, при которых a = 2cos(2π/n) годится:', [(n, round(a, 6), f'степень {d}') for n, a, d in ok])
TAU = (1 + 5 ** .5) / 2
print(f'τ = {TAU:.6f}, η = arccosh τ = {math.acosh(TAU):.4f};  следующее возможное: a ≥ 2, η ≥ {math.acosh(2):.4f}')

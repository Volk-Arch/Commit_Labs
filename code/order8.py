# ─────────────────── 8. ЛОКАЛЬНЫЕ размерности: взгляд изнутри
#
# Классическая размерность порядка (Душника–Миллера) для Минковского при d≥3 равна
# счётной БЕСКОНЕЧНОСТИ (Müller, arXiv:2303.11237). Это взгляд СНАРУЖИ: надо разложить
# всё множество на очереди, включая взаимно недоступные события на световых фронтах.
#
# Но есть определения ИЗНУТРИ, и они дают правильное многообразное число. Ниже — то,
# которое считается: размерность ловца.

def catcher_dimension(P, i, slab=0.03, lag=(0.20, 0.28), cap=12, maxc=300, rs=None):
    """Сколько нужно событий, ОДНОВРЕМЕННЫХ с p, чтобы p не смог от них ускользнуть:
    куда бы ни двинулся, попадёт в чей-то будущий конус.

    В плоскости нужно двое (слева и справа), в нашем мире — четверо (тетраэдр).
    Меньше — всегда есть щель. По Мюллеру это и есть размерность многообразия.

    Замерено на засеве: 1.70 ± 0.64 / 2.60 ± 1.14 / 4.12 ± 1.31 при истинных 2 / 3 / 4.
    Занижение — из-за конечной толщины среза: ловец чуть позже p имеет чуть меньший конус.

    ⚠ Ловцы обязаны быть НЕ РАНЬШЕ p. Ловец раньше имеет конус ШИРЕ, чем у p, и
    накрывает всё в одиночку — тогда ответ всегда 1 независимо от размерности."""
    r = rs if rs is not None else rng
    p = P[i]; dt = P[:, 0] - p[0]
    d2 = ((P[:, 1:] - p[1:])**2).sum(1)
    fut = (dt > 0) & (dt**2 > d2)
    tgt = np.flatnonzero(fut & (dt >= lag[0]) & (dt <= lag[1]))
    if len(tgt) < 30: return None
    cand = np.flatnonzero((dt >= 0) & (dt < slab) & (np.arange(len(P)) != i))
    if len(cand) < 8: return None
    if len(cand) > maxc: cand = r.choice(cand, maxc, replace=False)
    Q, C = P[tgt], P[cand]
    ddt = Q[None, :, 0] - C[:, None, 0]
    ddx = ((Q[None, :, 1:] - C[:, None, 1:])**2).sum(-1)
    cov = (ddt > 0) & (ddt**2 > ddx)
    need = np.ones(len(tgt), bool); k = 0
    while need.any() and k < cap:
        g = cov[:, need].sum(axis=1); b = int(g.argmax())
        if g[b] == 0: return None
        need &= ~cov[b]; k += 1
    return k if not need.any() else None


# ⊗ ЧТО НЕ РАБОТАЕТ, и почему — чтобы не пробовали заново.
#
# «Маяки» (триангуляция): сколько опорных событий нужно, чтобы событие определялось
# однозначно мощностями интервалов до них. НЕ РАБОТАЕТ: двух хватает при любой
# размерности (0.994 / 0.996 / 0.963 доля однозначных). Причина неисправима —
# мощность интервала это целое из тысяч возможных, и двух таких чисел довольно,
# чтобы различить тысячи событий независимо от геометрии. Меряется разрешение
# подписи, а не размерность.
#
# Хоризмотическая (через прямые связи): работает ЧАСТИЧНО. После двух соседей общими
# остаются 2.0 / 3.9 / 8.6 событий при d = 2 / 3 / 4 — чувствительность есть, но
# спуск размытый, точного числа не даёт.




# ────────────── 9. СУЖЕНИЕ: сколько позиций остаётся возможными
#
# Прогноз ВПЕРЁД не работает: AUC 0.565 в d=3, почти монетка. Из прошлого не выводится,
# куда встанет следующее событие. Но УСЛОВИЕ на будущее работает, и работает рывком.
#
# Замер чистым счётом, без машинного обучения: сколько элементов НЕОТЛИЧИМЫ от x, если
# известны k событий его будущего (кандидат тот, кто предшествует всем раскрытым).
#
#   d=4, из 2000 кандидатов:  k=0 → 1999,  k=1 → 139,  k=3 → 115,  k=13 → 100,  k=21 → 98
#
# ПЕРВОЕ ограничение режет в 14 раз. Следующие двадцать — меньше, чем первое.
# И до единицы не сходится НИКОГДА: 5% неопределённости держатся до конца.
#
# ⭐ РЕШАЕТ НЕ КОЛИЧЕСТВО, А ВЫБОР. Одно ближайшее событие будущего сужает до 159,
# одно дальнее — до 1381. Девятикратная разница при одинаковых затратах. Тринадцать
# дальних (446) хуже одного ближнего (159).
#
# ⭐ ПЛАТО ЛОКАЛЬНО, а не размыто. Выжившие кандидаты кучкуются рядом с истинным:
# перекрытие их прошлых с прошлым x равно 0.886 против типичных 0.6 у случайных
# несравнимых; разница глубин 7.5 при высоте 24. То есть ограничения работают и
# сводят кандидатов в окрестность — дальше мешает конечное разрешение, а не
# неоднозначность структуры.
#
# ⭐ ОПТИМАЛЬНОЙ СТРАТЕГИИ ВЫБОРА НЕТ. Жадный перебор (на каждом шаге брать событие,
# режущее сильнее всех) даёт 198/163/153/146/144 против 212/181/169/158/152 у простого
# «бери ближайшее» — улучшение около 7%. Достаточно спрашивать про ближайшее.
#
# ⚠ АСИММЕТРИЯ ОБРАТНАЯ той, что была записана в ранних хэндоффах. По этой мере
# ПРОШЛОЕ сужает СИЛЬНЕЕ будущего: 13 ближайших событий оставляют 53 кандидата из
# прошлого против 167 из будущего (d=4); 136 против 275 (d=3); 362 против 582 (d=2).
# Разрыв растёт с размерностью.
#
# Это НЕ противоречит замеру §5 (восстановление вынутого элемента, где будущее
# помогало), потому что там другая задача: вынутый элемент не оставил следов позади,
# поэтому прошлое о нём молчит. Правильная узкая формулировка: асимметрия есть у
# ВОССТАНОВЛЕНИЯ ВЫНУТОГО, а не у порядка вообще.


def narrowing(K, x, ks, mode='near', rs=None):
    """Сколько элементов неотличимы от x, если известны k событий его БУДУЩЕГО.
    mode: 'near' — ближайшие по глубине, 'far' — дальние, иначе случайные."""
    r = rs if rs is not None else rng
    Kb = np.ascontiguousarray(np.asarray(K, dtype=bool)); N = len(Kb)
    fut = np.flatnonzero(Kb[:, x])
    if len(fut) < max(ks): return None
    dep = proper_time(K)
    if mode == 'near':   order = fut[np.argsort(dep[fut])]
    elif mode == 'far':  order = fut[np.argsort(-dep[fut])]
    else:                order = r.permutation(fut)
    out = []
    for k in ks:
        if k == 0: out.append(N - 1); continue
        ok = Kb[order[:k], :].all(axis=0); ok[x] = False
        out.append(int(ok.sum()))
    return out


def narrowing_past(K, x, ks, mode='near', rs=None):
    """То же, но раскрываем ПРОШЛОЕ. Кандидат тот, за кем следуют все раскрытые.
    По этой мере прошлое сужает СИЛЬНЕЕ будущего — см. комментарий выше."""
    r = rs if rs is not None else rng
    Kb = np.ascontiguousarray(np.asarray(K, dtype=bool)); N = len(Kb)
    pst = np.flatnonzero(Kb[x])
    if len(pst) < max(ks): return None
    dep = proper_time(K)
    if mode == 'near':   order = pst[np.argsort(-dep[pst])]
    elif mode == 'far':  order = pst[np.argsort(dep[pst])]
    else:                order = r.permutation(pst)
    out = []
    for k in ks:
        if k == 0: out.append(N - 1); continue
        ok = Kb[:, order[:k]].all(axis=1); ok[x] = False
        out.append(int(ok.sum()))
    return out


# ─────────────────── 10. МЕТКА ШКАЛЫ: как сломать симметрию
#
# Формула не различает шкалы: восстановление ИНДИВИДУАЛЬНОЙ шкалы из порядка даёт
# R² = 0.16–0.23, а СУММЫ рангов — 0.999. Причина: работаем с рангами, а любое
# монотонное преобразование шкалы ранги не меняет. Метка стирается переходом к рангам,
# а не формулой.
#
# ⭐ НО СОВПАДЕНИЯ РАНГОВ монотонным преобразованием не убираются. Огрубление одной
# шкалы до m уровней делает её наблюдаемой (N=2500):
#
#   уровней:  симметрично    600     250     100      40
#   u:              0.161  0.525   0.883   0.971   0.991
#   v:              0.231  0.530   0.884   0.968   0.990
#   сумма:          0.999  0.999   1.000   1.000   1.000
#   различимость:   0.766  0.790   0.740   0.763   0.897  ← цена
#
# Метка проявляется ценой порчи структуры. Окно компромисса ~250 уровней.
#
# Следствие: симметрия шкал — не аксиома, а следствие того, что все шкалы одинаково
# тонки. Была бы одна грубее — стала бы наблюдаемой.

def marked_order(N, levels=None, rs=None):
    """Две шкалы, вторая огрублена до levels уровней (None — без огрубления).
    Совпадения по огрублённой означают, что события по ней НЕ разделены."""
    r = rs if rs is not None else rng
    u = r.permutation(N)
    v_raw = r.permutation(N)
    v = v_raw if levels is None else (v_raw * levels) // N
    R = (u[None, :] < u[:, None]) & (v[None, :] < v[:, None])
    return u, v, R.astype(np.float32)


def order_features(K):
    """Признаки для восстановления шкал — только из порядка, без координат."""
    C = np.ascontiguousarray(np.asarray(K, dtype=np.float32).T)
    past = C.sum(axis=0); fut = C.sum(axis=1)
    du = proper_time(np.asarray(K, dtype=np.float32)).astype(float)
    dd = proper_time(np.ascontiguousarray(C)).astype(float)
    btw = (C @ C).astype(np.int32)
    li = ((C > 0) & (btw == 0)).sum(axis=0).astype(float)
    lo = ((C > 0) & (btw == 0)).sum(axis=1).astype(float)
    n = len(K)
    return np.column_stack([past, fut, du, dd, li, lo,
                            past/n, fut/n, past*fut/n**2])


# ────── 11. ФИЛЬТР ЛОКАЛЕН, и лавина связности его не проходит
#
# ⭐ ДВА КРИТЕРИЯ ИЗ ТРЁХ РАБОТАЮТ НА КУСКАХ. Интервалы Александрова внутри большого
# засева d=2 (ориентиры целого: разм. 2.00, различ. 0.74, затухание 0.30):
#
#   кусок:      60..120   150..300   400..700   900..1500   целиком
#   размерность    2.00       2.01       2.01        2.02      2.00
#   различимость   0.78       0.75       0.72        0.73      0.74
#   затухание       --        0.45       0.26        0.27      0.30
#
# Размерность и различимость видны уже на 60 событиях. Затуханию нужна высота цепи —
# оно нелокально и начинает работать от ~300.
#
# ⭐ И ПОДДЕЛКА ЛОВИТСЯ НА КУСКЕ. Перколяция p=0.007 (целиком: 1.42 / 0.98 / 1.91):
#
#   кусок:      60..120   150..300   400..700   900..1600
#   размерность    3.27       3.60       3.58        2.85
#   различимость   0.43       0.46       0.52        0.73
#
# Причём выдаёт себя ТЕМ, ЧТО КУСОК НЕ ПОХОЖ НА ЦЕЛОЕ: у засева 2.00/2.01/2.01/2.02
# против 2.00 целиком; у перколяции 3.27/3.60/3.58/2.85 против 1.42. Самосогласованность
# по масштабам есть у настоящего множества и отсутствует у поддельного — и проверяется
# локально, без взгляда снаружи.
#
# ⚠ ЛАВИНА СВЯЗНОСТИ. Начать с полной несвязности и добавлять связи по одной с
# транзитивным замыканием: каждая добавленная порождает новых
#
#   добавлено:  50    400    800   1500   3000   6000  12000
#   новых:     1.0    2.4    8.8   28.1   46.3   24.6    8.6
#
# Порог есть, пик отдачи в 46 раз при доле связанных пар ~0.25. Но вырастает
# ПЕРКОЛЯЦИЯ, а она все критерии проваливает. СВЯЗНОСТЬ САМА ПО СЕБЕ НЕ СОЗДАЁТ
# СТРУКТУРУ: лавина есть, коллапс есть, мира нет.


def interval_of(K, lo, hi, rs=None, tries=120000):
    """Случайный интервал Александрова заданного размера — кусок мира."""
    r = rs if rs is not None else rng
    Kb = np.ascontiguousarray(np.asarray(K, dtype=bool)); N = len(Kb)
    for _ in range(tries):
        j = int(r.integers(1, N)); i = int(r.integers(0, j))
        if not Kb[j, i]: continue
        mid = np.flatnonzero(Kb[:, i] & Kb[j, :])
        if lo <= len(mid) < hi:
            return np.ascontiguousarray(Kb[np.ix_(mid, mid)].astype(np.float32))
    return None


def avalanche(N, n_add, snapshots, rs=None):
    """Из полной несвязности: добавляем связи по одной, замыкаем транзитивно.
    Возвращает (шаг, всего отношений, доля пар, средняя лавина на шаг)."""
    r = rs if rs is not None else rng
    P = np.zeros((N, N), dtype=bool); rec = []; av = []
    for step in range(1, n_add + 1):
        i = int(r.integers(0, N - 1)); j = int(r.integers(i + 1, N))
        if P[j, i]:
            av.append(0)
        else:
            A = P[i].copy(); A[i] = True
            B = P[:, j].copy(); B[j] = True
            new = np.outer(B, A) & ~P
            av.append(int(new.sum())); P |= new
        if step in snapshots:
            tot = int(P.sum())
            rec.append((step, tot, tot/(N*(N-1)/2), float(np.mean(av[-200:]))))
    return rec, P


# ────── 12. СТАТИСТИКА ЧАСТИЦ: обмен живёт в пространстве фаз
#
# Четыре дня искали фермион в структуре причинного порядка — правильно не нашли, там его
# нет. Обмен происходит НЕ в множестве событий, а в пространстве их расстановок.
#
# Событие несёт k фаз, то есть живёт в k-мерном кубе. Две неразличимые копии — две точки
# этого куба. Запрещена только ДИАГОНАЛЬ: совпали фазы во всех шкалах — это одно событие.
#
# ⭐ ЗАМЕР: можно ли перейти от (a,b) к (b,a), не задев диагональ?
#
#   k=1, 25 клеток:   НЕТ,  достижимо 300 из 600   — РОВНО ПОЛОВИНА
#   k=1, 49 клеток:   НЕТ,  достижимо 1176 из 2352 — ровно половина
#   k=2, 49 клеток:   ДА,   достижимо всё (2352)
#   k=2, 81 клетка:   ДА,   достижимо всё (6480)
#   k=3, 125 клеток:  ДА,   достижимо всё (15500)
#   k=4, 256 клеток:  ДА,   достижимо всё (65280)
#
# При k=1 пространство распадается надвое («первая левее» / «первая правее») — диагональ
# разделяет. При k≥2 коразмерность диагонали ≥2, и вокруг неё можно обойти.
#
# Отсюда (число классов путей взято из известной топологии, не пересчитывалось):
#   k=1   — статистики нет вовсе
#   k=2   — путей вокруг диагонали бесконечно много → континуум типов → ЭНИОНЫ
#   k≥3   — два класса → БОЗОНЫ и ФЕРМИОНЫ
#
# Это ровно то, что известно в физике: в двумерии статистика непрерывна, в трёх и выше
# типов ровно два.
#
# ⭐ И КОПИИ ЗАВОДЯТСЯ БЕСПЛАТНО. Доля событий получает копию фаз другого (N=2000, k=2):
#
#   доля дефектных:   0     0.02    0.05    0.12    0.30
#   пар близнецов:    0       41      96     237     590
#   размерность:   2.01     2.01    1.99    2.03    1.97
#   различимость: 0.758    0.744   0.777   0.736   0.757
#
# Тридцать процентов копий — структура не шелохнулась. Неразличимость СОВМЕСТИМА с
# многообразием. (Зажатие шкалы тоже даёт близнецов, но дороже: до ~150 уровней
# бесплатно, при 25 различимость едет с 0.758 до 0.885.)
#
# ⚠ ОГОВОРКА: это свойство ПРОСТРАНСТВА ФАЗ, а не причинного порядка. Из самого порядка
# статистика по-прежнему не выводится. Но вход тот же, что даёт размерность.


def can_swap(k, m=7):
    """Две неразличимые копии в k-мерном кубе фаз (сетка m^k). Конфигурация — пара
    разных клеток, ход — сдвиг одной копии в соседнюю без совпадения со второй.
    Возвращает (возможен ли обмен, сколько конфигураций достижимо)."""
    from collections import deque
    cells = np.array(np.unravel_index(np.arange(m**k), (m,)*k)).T
    idx = {tuple(c): i for i, c in enumerate(cells)}
    nbr = [[] for _ in range(len(cells))]
    for i, c in enumerate(cells):
        for d in range(k):
            for s in (-1, 1):
                q = c.copy(); q[d] += s
                if 0 <= q[d] < m: nbr[i].append(idx[tuple(q)])
    n = len(cells); start = (0, n-1); goal = (n-1, 0)
    seen = {start}; dq = deque([start])
    while dq:
        a, b = dq.popleft()
        if (a, b) == goal: return True, len(seen)
        for x in nbr[a]:
            if x != b and (x, b) not in seen: seen.add((x, b)); dq.append((x, b))
        for y in nbr[b]:
            if y != a and (a, y) not in seen: seen.add((a, y)); dq.append((a, y))
    return False, len(seen)


def with_twins(N, k, frac, rs=None):
    """Порядок, где доля frac событий — КОПИИ фаз других событий.
    Копии взаимозаменяемы, и структура этого не замечает."""
    r = rs if rs is not None else rng
    U = np.array([r.permutation(N) for _ in range(k)], dtype=np.int64)
    m = int(frac*N)
    if m > 0:
        src = r.choice(N, m, replace=False)
        dst = r.choice(np.setdiff1d(np.arange(N), src), m, replace=False)
        U[:, dst] = U[:, src]
    R = np.ones((N, N), dtype=bool)
    for u in U: R &= (u[None, :] < u[:, None])
    return R.astype(np.float32)


def count_twins(K, minlink=3):
    """Взаимозаменяемые пары СРЕДИ СВЯЗАННЫХ: одинаковое прошлое и будущее, непустые."""
    Kb = np.ascontiguousarray(np.asarray(K, dtype=bool))
    live = (Kb.sum(axis=1) >= minlink) & (Kb.sum(axis=0) >= minlink)
    sig = {}
    for i in np.flatnonzero(live):
        sig.setdefault((Kb[i].tobytes(), Kb[:, i].tobytes()), []).append(i)
    return sum(len(v)*(len(v)-1)//2 for v in sig.values())


# ────── 13. ОБМЕН В РЕАЛЬНОМ КУБЕ: порог по плотности
#
# §12 мерил обмен в ПУСТОМ кубе фаз. Здесь — с занятыми клетками: копия не может встать
# в клетку другого события (совпали все фазы = это одно событие).
#
# ⚠ СНАЧАЛА БЫЛ НЕВЕРНЫЙ ЗАМЕР, записан как предупреждение. Требование «порядок не
# меняется НИ НА ОДНОМ ШАГЕ» (копии двигаются только внутри своих ячеек между ближайшими
# соседями) дало 150/150 при точном совпадении фаз и 0/150 при сдвиге на один ранг.
# Условие слишком жёсткое: в физике важно, чтобы совпали НАЧАЛО И КОНЕЦ пути, а
# промежуточные состояния законны любые.
#
# ⭐ ПРАВИЛЬНЫЙ ЗАМЕР — порог по занятости куба:
#
#   занято:     0%    10%    20%    30%    40%    50%    60%    70%
#   k=2:      1.00   0.95   0.85   0.45   0.10   0.10   0.00   0.00
#   k=3:      1.00   1.00   0.90   0.95   0.70   0.75   0.20   0.00
#
# Порог ~30% в двумерии, ~60% в трёхмерии (больше измерений — больше обходных путей).
#
# ⭐ ГДЕ НАШ МИР: N событий в кубе N^k клеток → занятость N^(1-k).
# При N=1500, k=2 это <0.1%; при k=3 — одна двухмиллионная. ЗАПАС ЧЕТЫРЕ ПОРЯДКА.
# Куб фаз практически пуст, обмен свободно возможен.


def swap_with_obstacles(k, m, n_others, trials=20, rs=None):
    """Обмен двух копий в кубе фаз, где n_others клеток заняты другими событиями.
    Возвращает долю удачных обменов."""
    from collections import deque
    r = rs if rs is not None else rng
    cells = np.array(np.unravel_index(np.arange(m**k), (m,)*k)).T
    idx = {tuple(c): i for i, c in enumerate(cells)}
    nbr = [[] for _ in range(len(cells))]
    for i, c in enumerate(cells):
        for d in range(k):
            for s in (-1, 1):
                q = c.copy(); q[d] += s
                if 0 <= q[d] < m: nbr[i].append(idx[tuple(q)])
    n = len(cells); ok = 0
    for _ in range(trials):
        free = np.ones(n, bool)
        if n_others > 0:
            free[r.choice(n, min(n_others, n-2), replace=False)] = False
        fi = np.flatnonzero(free)
        if len(fi) < 2: continue
        a0, b0 = int(fi[0]), int(fi[-1])
        seen = {(a0, b0)}; dq = deque([(a0, b0)]); found = False
        while dq:
            a, b = dq.popleft()
            if (a, b) == (b0, a0): found = True; break
            for x in nbr[a]:
                if free[x] and x != b and (x, b) not in seen:
                    seen.add((x, b)); dq.append((x, b))
            for y in nbr[b]:
                if free[y] and y != a and (a, y) not in seen:
                    seen.add((a, y)); dq.append((a, y))
        ok += found
    return ok/max(trials, 1)


def winding(cells, traj, plane=(0, 1)):
    """Обмотка: суммарный поворот вектора между копиями, в единицах pi.

    В k=2 это ИНВАРИАНТ и он нечётен при обмене — замерено 40 путей, значения
    -17..15, все нечётные → бесконечно много классов → ЭНИОНЫ.
    В k=3 НЕ инвариант: один и тот же путь даёт разные значения в разных плоскостях
    (0 совпадений из 12) → разметки нет → остаются два класса → БОЗОНЫ и ФЕРМИОНЫ."""
    tot = 0.0; prev = None
    for a, b in traj:
        d = cells[b] - cells[a]
        ang = np.arctan2(float(d[plane[1]]), float(d[plane[0]]))
        if prev is not None:
            dd = ang - prev
            while dd > np.pi: dd -= 2*np.pi
            while dd < -np.pi: dd += 2*np.pi
            tot += dd
        prev = ang
    return tot/np.pi



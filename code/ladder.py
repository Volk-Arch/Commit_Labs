#!/usr/bin/env python3
"""Диагноз обратного знака: трубка — не груз, а ЛЕСТНИЦА.

delay.py дал при фиксированном V цепь ДЛИННЕЕ у трубки (+0.32), то есть
часы у массы идут БЫСТРЕЕ. Подозрение: цепь длиной m4*rho^(1/4)*tau, а
у трубки плотность на порядки выше фоновой, значит её внутренняя цепь
длиннее фоновой на том же промежутке собственного времени. Тогда любое
событие в будущем трубки наследует её высоту, и это чистая бухгалтерия
плотности, а не тяготение.

Считаем прямо: внутренняя высота трубки против высоты фона на том же
промежутке.
"""
import sys

import numpy as np

sys.path.insert(0, '/home/claude/code')
from weight import diamond, cone_rel
from delay import chain_tube, heights

T, RAD = 2.0, 0.02
print(f'ромб T={T}; высота фона против внутренней высоты трубки')
print(f"{'M':>6}{'выс. фона':>12}{'выс. трубки':>14}{'отношение':>12}"
      f"{'плотн. трубки':>15}{'плотн. фона':>13}")
for M in (120, 240, 480):
    hb, ht, rt = [], [], []
    for t in range(4):
        rs = np.random.default_rng(2101 + 31 * t)
        bg = diamond(T, rs)
        ob = chain_tube(M, RAD, T, rs)
        hb.append(heights(cone_rel(bg)).max())
        ht.append(heights(cone_rel(ob)).max())
    vol = (np.pi / 24) * T ** 4
    print(f'{M:>6}{np.mean(hb):>12.1f}{np.mean(ht):>14.1f}'
          f'{np.mean(ht)/np.mean(hb):>12.2f}'
          f'{M/(T-2*RAD):>15.1f}{len(bg)/vol:>13.1f}')

print('\nесли отношение много больше 1 — трубка есть лестница:')
print('событие в её будущем наследует её высоту, и «ход часов» растёт')
print('по плотности, а не по тяготению')

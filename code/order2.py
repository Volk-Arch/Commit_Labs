#!/usr/bin/env python3
"""ВТОРОЙ ПОРЯДОК — вычислить, а не выловить.

Защита применимости `tau² R_uu <= 0.8` ставилась ради того, чтобы
ВЫГНАТЬ второй порядок. Но первый порядок видит только одну комбинацию
компонент на данной быстроте (это геометрия: малый интервал чувствует
свёртку кривизны вдоль своей оси), а второй содержит квадратичную форму
по компонентам — вообще другую зависимость. Значит выгонялся не шум, а
канал.

И его НЕ НАДО набирать. Для конформно-плоских метрик точный интеграл

    1 + X_2 = < w_x tau_xq^4 w_y > / ( c_2 T^4 <w_x>^2 ),   w = a^4

верен во ВСЕХ порядках, а не только в первом: причинность плоская, и
кривизна входит единственным образом — весом. Поэтому второй порядок
вычисляется квадратурой.

ЧТО СЧИТАЕТСЯ. На сетке по `T` точный `X_2`, затем подгонка
`X_2 = A T² + C T⁴`. Первый коэффициент уже выведен
(`A = -0.0253 R_etaeta + 0.0192 R_xx` при покое). Второй `C`
регрессируется на квадратичные инварианты `u², u*vv, vv²` по десяти
комбинациям семейство-параметр.

РЕШАЮЩЕЕ: если `C` как форма от `(R_etaeta, R_xx)` НЕ пропорционален
первому порядку `A`, то добавление столбца `T⁴` в план разводит
компоненты само, без рычага по `v²` и без нового набора.

КОНТРОЛЬ: `flat` обязан дать и `A`, и `C` нулями — это нулевой уровень
метода, который вычитается из остальных.

  python3 order2.py
"""
import math

import numpy as np

from vcal2 import a_fun, uvv, x2_exact

NB = 4
TS = np.array([0.5, 0.8, 1.1, 1.4, 1.7, 2.0, 2.3])
CASES = (('flat', 0.0), ('lin', 0.18), ('lin', 0.30), ('exp', 0.18),
         ('exp', 0.30), ('quad', 0.04), ('quad', 0.08),
         ('root', 0.35), ('root', 0.60), ('exp', 0.40))


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    rs = np.random.default_rng(161803)
    N = 1400000
    print(f'точек {N}, блоков {NB}, T = {list(TS)}')
    print()
    print(f"{'семейство':>10}{'пар':>7}{'u':>9}{'vv':>9}"
          f"{'A (при T²)':>18}{'C (при T⁴)':>18}")
    rows = []
    for fam, par in CASES:
        ac = []
        for b in range(NB):
            x2 = np.array([x2_exact(fam, par, T, N, rs) for T in TS])
            D = np.column_stack([TS ** 2, TS ** 4])
            ac.append(np.linalg.lstsq(D, x2, rcond=None)[0])
        ac = np.array(ac)
        A, C = ac.mean(axis=0)
        eA, eC = ac.std(axis=0, ddof=1) / math.sqrt(NB)
        u, vv = uvv(fam, par)
        rows.append((fam, par, u, vv, A, eA, C, eC))
        print(f'{fam:>10}{par:>7.2f}{u:>9.4f}{vv:>9.4f}'
              f'{f"{A:+.5f}+-{eA:.5f}":>18}'
              f'{f"{C:+.5f}+-{eC:.5f}":>18}', flush=True)

    # нулевой уровень метода
    f0 = [r for r in rows if r[0] == 'flat'][0]
    A0, C0 = f0[4], f0[6]
    print()
    print(f'нулевой уровень (flat): A0 = {A0:+.5f}, C0 = {C0:+.5f} '
          f'— вычитается')
    print()
    print('=' * 76)
    print('РЕГРЕССИЯ ВТОРОГО ПОРЯДКА на квадратичные инварианты')
    R = [r for r in rows if r[0] != 'flat']
    X = np.array([[r[2] ** 2, r[2] * r[3], r[3] ** 2] for r in R])
    y = np.array([r[6] - C0 for r in R])
    w = 1.0 / np.array([r[7] for r in R]) ** 2
    p = np.linalg.solve(X.T @ (X * w[:, None]), (X * w[:, None]).T @ y)
    res = y - X @ p
    chi = (res ** 2 * w).sum()
    print(f'  C = {p[0]:+.4f} u² {p[1]:+.4f} u*vv {p[2]:+.4f} vv²'
          f'   chi² = {chi:.1f} на {len(R)-3} степеней')
    print()
    print('  В терминах компонент: u = (R_xx - R_ee/3)/2, '
          'vv = (R_xx + R_ee/3)/2')
    # C = p0 u² + p1 u vv + p2 vv²; подставим
    # u = (x - e/3)/2, vv = (x + e/3)/2, e = R_ee, x = R_xx
    cee = (p[0] - p[1] + p[2]) / 36.0
    cex = (-2 * p[0] + 2 * p[2]) / 12.0
    cxx = (p[0] + p[1] + p[2]) / 4.0
    print(f'  C = {cee:+.5f} R_ee² {cex:+.5f} R_ee*R_xx {cxx:+.5f} R_xx²')
    print()
    print('=' * 76)
    print('ЕСТЬ ЛИ НОВАЯ ИНФОРМАЦИЯ')
    # первый порядок при покое: A = -0.0253 R_ee + 0.0192 R_xx
    a1, b1 = -0.02539, 0.01908
    # пропорционален ли квадрат первого порядка форме C?
    sq = np.array([a1 * a1, 2 * a1 * b1, b1 * b1])
    cf = np.array([cee, cex, cxx])
    cos = abs(sq @ cf) / math.sqrt((sq @ sq) * (cf @ cf))
    print(f'  форма первого порядка в квадрате: '
          f'({sq[0]:+.2e}, {sq[1]:+.2e}, {sq[2]:+.2e})')
    print(f'  измеренная форма второго:         '
          f'({cf[0]:+.2e}, {cf[1]:+.2e}, {cf[2]:+.2e})')
    print(f'  косинус между формами = {cos:.4f}')
    print('  ->', 'ФОРМЫ РАЗНЫЕ: второй порядок несёт новую комбинацию'
          if cos < 0.99 else 'формы совпадают: новой информации нет')


if __name__ == '__main__':
    main()

"""ПОРЯДОК — одно правило, из которого выходит кинематика.

ПРАВИЛО. У события есть k ФАЗ. Одно событие раньше другого, если раньше ПО ВСЕМ фазам:

        e_i ≺ e_j   ⟺   ∀m:  φ_m(i) < φ_m(j)

Всё. Ни параметров, ни констант, ни размерности внутри. Если согласия по всем фазам нет —
события несравнимы, то есть «одновременны», и одно на другое повлиять не может.

ЧТО ПОДАЁМ: N событий и k шкал. Шкала — просто очередь, «кто за кем». Ни расстояний,
ни метрики, ни вещественных величин: только ранг.

ЧТО ВЫХОДИТ, без единой добавки:

    порядок → [ДОЛЯ СВЯЗАННЫХ ПАР]                    → РАЗМЕРНОСТЬ
            → [ДЛИННЕЙШАЯ ЦЕПЬ]                       → СОБСТВЕННОЕ ВРЕМЯ
            → [ЗНАКОПЕРЕМЕННЫЙ ПОДСЧЁТ ЦЕПЕЙ]         → ПОЛЕ
            → [ПЕРЕКРЫТИЕ ПРОШЛЫХ У ОДНОВРЕМЕННЫХ]    → РАЗЛИЧИМОСТЬ
            → [ПОЛОЖИТЕЛЬНОСТЬ ТЕМПОВ ФАЗ]            → СВЕТОВОЙ КОНУС

⭐ РАССТОЯНИЯ НЕТ. Размерность выпадает из одного скаляра — доли причинно связанных пар.
Проверено: истинные 2, 3, 4 → 1.99, 3.00, 4.00. Ни одной координаты в вычислении.

⭐ ВРЕМЯ НЕ ТЕЧЁТ, ОНО СЧИТАЕТСЯ. Собственное время = длина максимальной цепи. При
фиксированной плотности отношение цепь/T постоянно.

⭐ ПОЛЕ ЕСТЬ СУММА ПУТЕЙ. Запаздывающая функция Грина в 2D — половина причинной матрицы.
Масса добавляется разложением по цепям: каждая вставка стоит m²/ρ и один лишний элемент.
Ряд сворачивается и даёт ½·J₀(mτ) — совпало до третьего знака.

⭐ ИЗМЕРЕНИЕ = ВЫЧИТАНИЕ БИТА. Каждая независимая шкала оставляет РОВНО ПОЛОВИНУ связей:
доля пар идёт 1.0000, 0.4980, 0.2526, 0.1214, 0.0618 при k = 1..5, то есть 2^-(k-1) до
третьего знака. Размерность — это число вычтенных бит связности. Одномерие: связаны все.
Четырёхмерие: связана восьмая часть. ИЗМЕРЕНИЯ РАЗЪЕДИНЯЮТ, а не добавляют.

⭐ ПРЕДЕЛЬНАЯ СКОРОСТЬ НЕ ПОСТУЛИРУЕТСЯ. Траектория задаётся темпами изменения фаз (v_u, v_v).
В светоконусных координатах t=(u+v)/2, x=(u-v)/2, значит скорость = (v_u−v_v)/(v_u+v_v).
Она меньше единицы РОВНО ТОГДА, когда оба темпа положительны, то есть когда точка внутри
положительного октанта. Замерено: (1,1)→0.000, (1,0.3)→0.538, (1,0.02)→0.961,
(1,0)→1.000 и цепи уже нет, (1,−0.3)→1.857 и связи нет.
«Быстрее света» означает буквально «одна фаза пошла назад», и тогда события просто
НЕ СВЯЗАНЫ. Это не запрет, а отсутствие отношения.

⭐ ЗАМЕДЛЕНИЕ ВРЕМЕНИ — ТОЖЕ СЧЁТ. Длина цепи между концами траектории: 138, 116, 93, 78,
71, 49, 36, 24, 15 по мере разгона от 0 до 0.961. И она равна ИНТЕРВАЛУ: цепь ∝ √(du·dv),
линейная подгонка по девяти точкам даёт R² = 0.9974. Формулы Лоренца не использовались.

⭐ БЕЗМАССОВОЕ = ЗАМОРОЖЕННАЯ ФАЗА. Если один темп равен нулю, √(du·dv) = 0: тактов нет,
собственного времени нет. Не по запрету, а по арифметике.

⭐ ОДНОРОДНОСТЬ ОБЯЗАТЕЛЬНА. Если у разных событий разное число шкал и сравнивать их по
общим — ТРАНЗИТИВНОСТЬ ЛОМАЕТСЯ, появляются циклы, порядка нет. Число шкал может быть
любым, но должно быть ОБЩИМ. (Проверено: код падает с «граф не ацикличен».)

⭐ НЕЗАВИСИМОСТЬ ШКАЛ ОБЯЗАТЕЛЬНА, но она НЕПРЕРЫВНА, а не бинарна. Вторая шкала как
функция первой: монотонная → цепь; обратная → пустой порядок; сдвиг → различимость 0.000;
перестановка разрядов → подделка (три наблюдаемых как у эталона, действие −14.3 против +1.0).
НО: sin(t) и sin(m·t) при росте m ведут себя всё более независимо — различимость идёт
0.984, 0.964, 0.912, 0.846, 0.793, 0.770 при m = 2, 7, 11, 15, 31, 51, против 0.766 у двух
случайных. Взаимная информация рангов падает 4.32 → 0.12. То есть детерминированная шкала
работает как независимая, если перепутана достаточно мелко. Не ортогональность (sin и cos
ортогональны и дают 0.000), а РАЗРЕШЕНИЕ, на котором связь не видна.

⊗ ГЛАВНОЕ ОГРАНИЧЕНИЕ. Правило точно воспроизводит Минковский ТОЛЬКО при k=2 — там это
теорема о светоконусных координатах. При d ≥ 3 размерность порядка Душника–Миллера
пространства Минковского равна СЧЁТНОЙ БЕСКОНЕЧНОСТИ (Müller, arXiv:2303.11237), то есть
конечного числа шкал не хватает в принципе. Замерено: k=4 против d=4 даёт 3.85/3.72/3.73/3.71
против 4.00/3.98/3.98/4.00 при N = 800..10000 — разрыв не сходится, стабилизируется на 0.29.

⊗ ЧТО ЕЩЁ НЕ ВЫХОДИТ. Динамики нет: правило порождающего роста в своём классе отсутствует
(полный перебор 32768 историй на шести элементах, расстояние по вариации до четырёхмерия
0.93 при максимуме 1). Откуда берутся сами шкалы — неизвестно.

⊙ Содержание этого файла — стандартная кинематика. Светоконусные координаты, доминирование
как причинность, интервал √(du·dv) — учебник. Необычна только сборка: одно правило,
пять следствий, всё счётом.
"""

import sys
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")      # Windows: консоль cp1251
    sys.stderr.reconfigure(encoding="utf-8")
import numpy as np
from math import gamma
from scipy.optimize import brentq
from scipy.linalg import solve_triangular

rng = np.random.default_rng(0)


# ────────────────────────────────────────────────────────── субстрат

def sprinkle(N, d, T=1.0, warp=0.0):
    """Пуассоновский засев в каузальный интервал d-мерного Минковского.
    warp ≠ 0 — неоднородная плотность; в 2D это настоящая искривлённая метрика."""
    pts = []
    while len(pts) < N:
        m = 6*(N - len(pts)) + 400
        t = rng.uniform(0, T, m); x = rng.uniform(-T/2, T/2, (m, d - 1))
        r = np.linalg.norm(x, axis=1); ok = (r < t) & (r < T - t)
        t, x = t[ok], x[ok]
        if warp:
            w = np.exp(warp*(t - T/2)); w /= w.max()
            keep = rng.random(len(t)) < w
            t, x = t[keep], x[keep]
        pts.extend(np.column_stack([t, x]))
    p = np.array(pts[:N]); return p[np.argsort(p[:, 0])]


def order_of(p, chunk=1500):
    """Единственное, что переживает переход от геометрии к порядку.
    K[j, i] = 1 ⟺ i предшествует j. Дальше координаты не нужны никому."""
    n = len(p); K = np.zeros((n, n), dtype=np.float32)
    t, x = p[:, 0], p[:, 1:]
    for a in range(0, n, chunk):
        b = min(a + chunk, n)
        dt = t[a:b, None] - t[None, :]
        dx2 = ((x[a:b, None, :] - x[None, :, :])**2).sum(-1)
        K[a:b] = ((dt > 0) & (dt**2 > dx2)).astype(np.float32)
    return K


def phases(N, k):
    """Событие = набор из k фаз. Никакой геометрии, только числа в [0,1)."""
    return rng.random((N, k))


def order_of_phases(P):
    """ПРАВИЛО. Раньше по всем фазам — значит предшествует."""
    N, k = P.shape
    R = np.ones((N, N), dtype=bool)
    for m in range(k):
        R &= (P[None, :, m] < P[:, None, m])
    return R.astype(np.float32)                       # R[j,i] = 1 ⟺ i ≺ j


# ───────────────────────────────────────── 1. доля пар → размерность

def dimension(K):
    """Майрхейм–Мейер. Одно число на входе, размерность на выходе."""
    n = len(K); f = K.sum()/(n*(n - 1)/2)
    g = lambda d: gamma(d + 1)*gamma(d/2)/(2*gamma(1.5*d))
    try:
        return brentq(lambda d: g(d) - f, 1.0, 30)
    except ValueError:
        return float('nan')


# ─────────────────────────────── 2. длина цепи → собственное время

def proper_time(K):
    """Длиннейший путь от любого минимального элемента: число тактов до события.

    ⚠ Топологический порядок берётся ИЗ ГРАФА, а не предполагается по нумерации.
    Прежняя версия шла по возрастанию индекса и молча требовала сортировки по времени;
    на выходе sprinkle это выполнялось и дефект был невидим, а при другой нумерации
    глубина получалась просто неверной (разброс distinctness достигал 0.11 при
    сигнале 0.18). Найдено внешней проверкой, исправлено, провалидировано."""
    Kb = np.ascontiguousarray(K, dtype=bool); n = len(Kb)
    indeg = Kb.sum(axis=1).astype(np.int64)
    D = np.zeros(n, dtype=np.int64)
    ready = list(np.flatnonzero(indeg == 0)); seen = 0
    while ready:
        j = ready.pop(); seen += 1
        kids = np.flatnonzero(Kb[:, j])
        if kids.size:
            D[kids] = np.maximum(D[kids], D[j] + 1)   # не out=D[kids]: это копия, не вид
            indeg[kids] -= 1
            ready.extend(kids[indeg[kids] == 0].tolist())
    if seen != n:
        raise ValueError('граф не ацикличен — это не частичный порядок')
    return D


# ───────────────────────────────────── 3. подсчёт цепей → поле

def propagate(K, src, mass, rho):
    """Массивный запаздывающий пропагатор в 2D из одного подсчёта цепей:

        G = ½ · K · (I + m²/(2ρ) · K)⁻¹

    Разложение прогрессии — это сумма по цепям: (−α)^k × (число цепей длины k).
    Знакопеременность даёт осцилляцию, факториальное подавление числа цепей в
    многообразии даёт затухание. Вместе — ½·J₀(mτ).

    На немногообразном порядке подавление другое и ряд расходится: то же выражение,
    тот же код, а поля нет."""
    K = np.ascontiguousarray(K, dtype=np.float32); n = len(K)
    M = np.eye(n, dtype=np.float32) + (mass*mass/(2*rho))*K
    return 0.5*solve_triangular(M, K[:, src].copy(), lower=True, unit_diagonal=True)


# ──────────────────────── 4. перекрытие прошлых → различимость

def distinctness(K, samples=30000, band=(0.25, 0.90), depth_tol=2):
    """Медиана перекрытия прошлых у НЕСРАВНИМЫХ событий близкой глубины.

    0.77 — двумерие, 0.36 — пятимерие, 1.00 — вырождение: одновременные события
    неразличимы, «где» у структуры нет.

    Это единственная величина, которая ловит подделку. Доля пар и размерность
    обманываются: перколяция при p=0.007 даёт 0.474 и 2.07 против 0.500 и 2.00 у
    настоящего двумерия, а различимость 0.98 против 0.77."""
    K = np.ascontiguousarray(K, dtype=np.float32)
    D = proper_time(K); hi = max(D.max(), 1)
    idx = np.flatnonzero((D > band[0]*hi) & (D < band[1]*hi))
    if len(idx) < 40: return float('nan')
    P = K[:, idx]; sz = P.sum(axis=0)
    rel = K[np.ix_(idx, idx)] > 0; rel = rel | rel.T
    out = []
    for _ in range(samples):
        i, j = rng.integers(0, len(idx), 2)
        if i == j or rel[i, j] or abs(D[idx[i]] - D[idx[j]]) > depth_tol: continue
        s = min(sz[i], sz[j])
        if s >= 8: out.append(float(P[:, i] @ P[:, j])/s)
    return float(np.median(out)) if len(out) > 40 else float('nan')


# ──────────────────── 5. темпы фаз → конус, скорость, замедление

def speed(rates):
    """Скорость траектории по темпам изменения фаз.
    В светоконусных координатах t=(u+v)/2, x=(u-v)/2 ⟹ v = (v_u − v_v)/(v_u + v_v).
    Модуль меньше единицы РОВНО когда оба темпа положительны."""
    vu, vv = float(rates[0]), float(rates[1])
    return np.inf if (vu + vv) == 0 else (vu - vv)/(vu + vv)


def inside_cone(rates):
    """Внутри светового конуса ⟺ все темпы строго положительны.
    Предельная скорость не постулируется: это граница положительного октанта."""
    return bool(np.all(np.asarray(rates, dtype=float) > 0))


def chain_between(P, a, b):
    """Собственное время вдоль траектории: длиннейшая цепь между концами через фон.
    Замерено: равно интервалу, цепь ∝ √(∏ Δφ_m), R² = 0.9974 в двумерии."""
    inside = np.all((P > a) & (P < b), axis=1)
    idx = np.flatnonzero(inside)
    if len(idx) == 0: return 0
    Q = P[idx]
    R = np.ones((len(idx), len(idx)), dtype=bool)
    for m in range(P.shape[1]):
        R &= (Q[None, :, m] < Q[:, None, m])
    return int(proper_time(R.astype(np.float32)).max()) + 1


# ────────────────────────────────────────────────────── один проход

if __name__ == '__main__':
    from scipy.special import j0

    print('1. РАЗМЕРНОСТЬ ИЗ ОДНОЙ ДОЛИ СВЯЗАННЫХ ПАР')
    for d in (2, 3, 4):
        print(f'   истинная {d} → восстановлено {dimension(order_of(sprinkle(4000, d))):.2f}')

    print('\n2. СОБСТВЕННОЕ ВРЕМЯ КАК ДЛИНА ЦЕПИ (плотность фиксирована)')
    for T in (0.6, 0.9, 1.2):
        K = order_of(sprinkle(int(3500*T*T), 2, T=T))
        L = proper_time(K).max()
        print(f'   T={T}  цепь={L:>3}  цепь/T={L/T:.1f}')

    print('\n3. ПОЛЕ ИЗ ПОДСЧЁТА ЦЕПЕЙ (ожидается ½·J₀)')
    N, T, m = 5000, 1.0, 10.0
    p = sprinkle(N, 2, T); K = order_of(p)
    s = int(np.argmin(p[:, 0] + abs(p[:, 1])))
    G = propagate(K, s, m, N/(T*T/2))
    dt = p[:, 0] - p[s, 0]; dx = p[:, 1] - p[s, 1]
    tau = np.sqrt(np.maximum(dt**2 - dx**2, 0)); fut = K[:, s] > 0
    for lo, hi in zip(np.linspace(.35, .90, 6)[:-1], np.linspace(.35, .90, 6)[1:]):
        sel = fut & (tau >= lo) & (tau < hi)
        if sel.sum() > 25:
            tm = tau[sel].mean()
            print(f'   mτ={m*tm:5.2f}  посчитано {G[sel].mean():+.3f}   точно {0.5*j0(m*tm):+.3f}')

    print('\n4. РАЗЛИЧИМОСТЬ ПО РАЗМЕРНОСТИ И ПО КРИВИЗНЕ')
    for d in (2, 3, 4):
        print(f'   d={d}  перекрытие {distinctness(order_of(sprinkle(5000, d))):.2f}')
    for w in (0.0, 9.0):
        K = order_of(sprinkle(5000, 2, warp=w))
        print(f'   d=2, кривизна {w}  разм. {dimension(K):.2f}  перекрытие {distinctness(K):.2f}')

    print('\n5. ИЗМЕРЕНИЕ = ВЫЧИТАНИЕ БИТА (каждая шкала режет связность вдвое)')
    Np = 3000; U = [rng.random(Np) for _ in range(5)]
    R = np.ones((Np, Np), dtype=bool); prev = None
    for k, u in enumerate(U, 1):
        R &= (u[None, :] < u[:, None])
        f = R.sum()/(Np*(Np - 1)/2)
        sur = '' if prev is None else f'выжило {f/prev:.3f}'
        print(f'   {k} шкал: доля пар {f:.4f}  (ожидается {2.0**-(k-1):.4f})  {sur}')
        prev = f

    print('\n6. СВЕТОВОЙ КОНУС И ЗАМЕДЛЕНИЕ — из положительности темпов')
    P = phases(6000, 2); a = np.array([0.02, 0.02])
    print(f'   {"темпы":>12}{"скорость":>10}{"√(du·dv)":>11}{"цепь":>7}')
    for vv in (1.0, 0.5, 0.25, 0.08, 0.02, 0.0, -0.3):
        d = np.array([0.95, 0.95*vv]); b = a + d
        sp = speed(d)
        if not inside_cone(d):
            print(f'   {f"(1,{vv})":>12}{sp:>10.3f}{"—":>11}{"нет":>7}   вне конуса')
            continue
        print(f'   {f"(1,{vv})":>12}{sp:>10.3f}{np.sqrt(d[0]*d[1]):>11.4f}'
              f'{chain_between(P, a, np.minimum(b, 0.999)):>7}')

    print('\n7. ГРАНИЦА: правило точно только при k=2')
    for k, d in ((2, 2), (4, 4)):
        Kp = order_of_phases(phases(4000, k)); Ks = order_of(sprinkle(4000, d))
        print(f'   {k} шкал: разм. {dimension(Kp):.2f} / различ. {distinctness(Kp):.3f}   '
              f'засев d={d}: {dimension(Ks):.2f} / {distinctness(Ks):.3f}')
    print('   при d≥3 порядковая размерность Минковского бесконечна — разрыв не сходится')

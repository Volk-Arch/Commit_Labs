#!/usr/bin/env python3
"""ЛОКАЛЬНЫЙ ВОЛНОВОЙ ОПЕРАТОР: есть ли он на порядке.

Синтез 11 октября: семейство врага замкнуто относительно всего, что мы
умеем делать с ПОРЯДКОМ — выпуклого смешивания (Фаркаш), подгонки
параметров (шесть статистик), огрубления (довод в одну строку). Значит
менять надо объект, а не величину. Материя — другой объект.

Но схлопывание пропагатора на кривую врага не отличит: у слоистого пары
с одинаковым |I| эквивалентны по симметрии, кривая будет и у него,
просто другая, а «другая кривая» есть опять величина.

Условие ИНОГО РОДА: пропагатор обязан удовлетворять волновому
уравнению, то есть должен СУЩЕСТВОВАТЬ локальный оператор, его
аннулирующий. Это существование решения обратной задачи, а не значение
статистики. И круг замыкается: дискретный оператор Даламбера строится
РОВНО из счётов N_m с весами БД — оттуда они и взялись.

КОНТРОЛЬ ПЕРВЫМ ДЕЛОМ, и коэффициенты по памяти не берутся. В 1+1
оператор имеет вид

    (B f)(x) = (2/l^2) [ c_(-1) f(x) + sum_{y < x} c_{|I(y,x)|} f(y) ]

с весами c = (1, -2, 1) при |I| = 0, 1, 2 и нулём далее. Правильность
проверяется на ГЛАДКИХ функциях, где непрерывный ответ известен точно:
при сигнатуре (+,-) имеем кв(t^2) = 2, кв(x^2) = -2, кв(t^2-x^2) = 4.
Если контроль не проходит — коэффициенты или нормировка неверны, и
дальше идти нельзя.
"""
import math

import numpy as np

C11 = {0: 1.0, 1: -2.0, 2: 1.0}
CSELF = -1.0


def sprinkle_11(n, rs, T=1.0):
    """Засев в алмазе 1+1: |x| < min(t, T-t) в светоконусных мерках."""
    out = []
    while len(out) < n:
        k = (n - len(out)) * 3 + 64
        t = rs.random(k) * T
        x = (rs.random(k) * 2 - 1) * (T / 2)
        ok = np.abs(x) < np.minimum(t, T - t)
        out.append(np.column_stack([t[ok], x[ok]]))
    P = np.vstack(out)[:n]
    return P


def causal(P):
    dt = P[None, :, 0] - P[:, None, 0]
    dx = P[None, :, 1] - P[:, None, 1]
    return (dt > 0) & (dt * dt > dx * dx)


def Bop(Rc, rho):
    """Матрица оператора: B[x,y] для y <= x."""
    n = Rc.shape[0]
    F = Rc.astype(np.float32)
    Iv = np.rint(F @ F).astype(np.int32)
    B = np.zeros((n, n))
    for m, c in C11.items():
        B += c * (Rc.T & (Iv.T == m))
    np.fill_diagonal(B, CSELF)
    return B * (2.0 / (1.0 / rho))      # l^2 = 1/rho в 1+1


def main():
    print(__doc__)
    rs = np.random.default_rng(1414)
    print('КОНТРОЛЬ: оператор на гладких функциях '
          '(ответ непрерывной теории точен)')
    print(f"{'N':>6}{'кв(t²)':>12}{'кв(x²)':>12}{'кв(τ²)':>12}"
          f"{'ждём':>22}")
    for n in (400, 800, 1600, 3200):
        P = sprinkle_11(n, rs)
        rho = n / 0.5                      # площадь алмаза T²/2 = 0.5
        Rc = causal(P)
        B = Bop(Rc, rho)
        t, x = P[:, 0], P[:, 1]
        # берём середину, чтобы не ловить границу
        core = (t > 0.35) & (t < 0.65) & (np.abs(x) < 0.12)
        if core.sum() < 8:
            continue
        res = []
        for f, exact in ((t * t, 2.0), (x * x, -2.0),
                         (t * t - x * x, 4.0)):
            v = (B @ f)[core]
            res.append(float(np.median(v)))
        print(f'{n:>6}{res[0]:>12.3f}{res[1]:>12.3f}{res[2]:>12.3f}'
              f'{"2, -2, 4":>22}', flush=True)
    print('\nесли столбцы не идут к 2, -2, 4 — коэффициенты или')
    print('нормировка неверны, и дальше идти нельзя')


if __name__ == '__main__':
    main()

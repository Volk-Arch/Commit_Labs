#!/usr/bin/env python3
"""ОТКУДА СТРУКТУРЕ ВЗЯТЬСЯ: сприклинги против слоистых порядков.

ВЫВОД, КОТОРЫЙ ЭТО ЗАТЕЯЛ. `quantum.py` показал, что при сумме по 2000
сприклингов `|amp(ℏ)|` совпадает с гауссовым поддельным нулём на всех
`ℏ` (худшее отклонение 0.9 сигмы при чувствительности 0.015), а
выведенная граница окна `ℏ = σ/sqrt(ln n)` подтвердилась.

И понятно, почему: действие БД есть сумма многих слабо зависимых
локальных членов, значит по центральной предельной теореме на случайных
сприклингах оно ОБЯЗАНО быть гауссовым. А у гауссова действия
характеристическая функция равна `exp(iμ/ℏ − σ²/2ℏ²)` ТОЧНО, без
остатка, — структуре взяться неоткуда. Это объясняет, почему проект всё
время находил «интерференции нет»: суммирование шло по сприклингам.

ЗНАЧИТ структура может быть только там, где в ансамбле есть
конфигурации, НЕ являющиеся сприклингами. В теории причинных множеств
это известные слоистые порядки (Клейтмана–Ротшильда): три «мига
времени», энтропийно господствующие, совсем не похожие на многообразие.
Литература (arXiv:2311.18238) говорит, что действие БД на них сводится к
звеньевому и что они СИЛЬНО ПОДАВЛЕНЫ в сумме по путям при масштабе
дискретности выше планковского в 1.1–2.3 раза.

ЭТО И ПРОВЕРЯЕМ, и проверка дешёвая.

ПРЕДСКАЗАНИЕ, регистрируемое до замера:
  1. действие на слоистых порядках обязано сильно отличаться от
     действия на сприклингах того же N — иначе подавлять нечем;
  2. совместное распределение обязано быть ДВУГОРБЫМ, с разрывом
     `ΔS` между горбами;
  3. если разрыв велик по сравнению с разбросом внутри горба, то
     `|amp(ℏ)|` у смеси ОТКЛОНИТСЯ от гауссова нуля — появится биение
     с периодом `2π/ΔS`, и это и есть та структура, которой не было у
     одних сприклингов;
  4. подавление слоистых считается прямо: их вклад в сумму идёт с
     весом `exp(iS_слой/ℏ)`, и при `ΔS/ℏ` порядка единицы и больше
     горбы гасят друг друга.

КОНТРОЛИ:
  - у чистых сприклингов отклонение обязано остаться нулевым (это уже
    измерено: 0.9 сигмы), и здесь печатается заново как база;
  - слоистый порядок строится как ПОРЯДОК, без всякого вложения:
    три слоя, каждое событие нижнего слоя раньше каждого события
    среднего и так далее — то есть полный трёхслойный порядок;
  - проверка кода: у полного трёхслойного порядка число звеньев и
    мощности интервалов считаются точно и сверяются с формулой.

  python3 bimodal.py
"""
import argparse
import math
import time

import numpy as np

from dyn import relation, bd_density_smeared, bd_density


def sprinkling(N, L, T, rs):
    X = np.empty((N, 4))
    X[:, 0] = rs.uniform(0, T, N)
    X[:, 1:] = rs.uniform(0, L, (N, 3))
    X = X[np.argsort(X[:, 0])]
    return relation(X, L)


def layered(N, rs, k=3, p=1.0):
    """Слоистый порядок: k слоёв, всё нижнее раньше всего верхнего.

    Строится как ПОРЯДОК, без вложения. При p = 1 это полный k-слойный
    порядок (Клейтмана–Ротшильда при k = 3 и равных слоях); при p < 1
    связи между соседними слоями ставятся с вероятностью p, что даёт
    типичный слоистый порядок, а не только полный.
    """
    sizes = [N // k] * k
    sizes[0] += N - sum(sizes)
    lab = np.concatenate([np.full(s, i) for i, s in enumerate(sizes)])
    R = lab[:, None] < lab[None, :]          # нижний слой раньше верхнего
    if p < 1.0:
        keep = rs.uniform(size=R.shape) < p
        R = R & keep
        # транзитивность восстанавливается: если i<j<l по слоям и обе
        # связи стоят, то i<l обязана стоять
        R = R | (R @ R)
    return R


def check_layered():
    """Проверка кода на полном трёхслойном порядке: точные числа."""
    rs = np.random.default_rng(0)
    N, k = 9, 3
    R = layered(N, rs, k=k, p=1.0)
    m = N // k
    # у полного k-слойного: пар между соседними слоями m², между
    # крайними m²; звенья (|I| = 0) — только между СОСЕДНИМИ слоями
    pairs = int(R.sum())
    expect_pairs = m * m * (k * (k - 1) // 2)
    C = (R.astype(np.float32) @ R.astype(np.float32)).astype(int)
    links = int((R & (C == 0)).sum())
    expect_links = m * m * (k - 1)
    ok = (pairs == expect_pairs) and (links == expect_links)
    print(f'  проверка кода на полном трёхслойном (N=9, слои по 3):')
    print(f'    пар {pairs} (ожидание {expect_pairs}), '
          f'звеньев {links} (ожидание {expect_links})  '
          f'{"СХОДИТСЯ" if ok else "НЕ СХОДИТСЯ"}')
    return ok


def main():
    ap = argparse.ArgumentParser(description='Сприклинги против слоистых')
    ap.add_argument('--n', type=int, default=700)
    ap.add_argument('--lell', type=float, default=5.0)
    ap.add_argument('--tell', type=float, default=6.0)
    ap.add_argument('--eps', type=float, default=0.4)
    ap.add_argument('--samples', type=int, default=300)
    ap.add_argument('--p', type=float, default=0.9,
                    help='доля связей между соседними слоями')
    a = ap.parse_args()

    t0 = time.time()
    print('ВЫВОД: на сприклингах действие гауссово по центральной')
    print('предельной теореме, поэтому структуре взяться неоткуда.')
    print('Структура может быть только от конфигураций, НЕ являющихся')
    print('сприклингами. Проверяем на слоистых порядках.')
    print()
    check_layered()
    print()

    Ssp, Sly = [], []
    for s in range(a.samples):
        rs = np.random.default_rng(5150 + 17 * s)
        R = sprinkling(a.n, a.lell, a.tell, rs)
        Ssp.append(float(bd_density_smeared(R, a.eps).sum()))
        del R
        R = layered(a.n, rs, k=3, p=a.p)
        Sly.append(float(bd_density_smeared(R, a.eps).sum()))
        del R
        if s == 0 or (s + 1) % 50 == 0:
            print(f'  выборка {s} ({time.time()-t0:.0f} с)', flush=True)
    Ssp = np.array(Ssp); Sly = np.array(Sly)

    print()
    print('ДЕЙСТВИЕ НА ДВУХ СЕМЕЙСТВАХ (N одинаково)')
    print(f'  сприклинги:      ⟨S⟩ = {Ssp.mean():+12.2f}  '
          f'σ = {Ssp.std(ddof=1):9.2f}')
    print(f'  слоистые (p={a.p}): ⟨S⟩ = {Sly.mean():+12.2f}  '
          f'σ = {Sly.std(ddof=1):9.2f}')
    dS = Sly.mean() - Ssp.mean()
    sig = 0.5 * (Ssp.std(ddof=1) + Sly.std(ddof=1))
    print(f'  РАЗРЫВ ΔS = {dS:+.2f},  разброс внутри горба σ = {sig:.2f}')
    print(f'  ΔS/σ = {abs(dS)/max(sig,1e-12):.2f}  —  '
          f'{"ГОРБЫ РАЗДЕЛЕНЫ" if abs(dS) > 2*sig else "горбы перекрываются"}')

    print()
    print('|amp(ℏ)| У СМЕСИ против гауссова поддельного нуля')
    print('(у чистых сприклингов отклонение было 0.9 сигмы — это база)')
    mix = np.concatenate([Ssp, Sly])
    n = len(mix)
    s_all = mix.std(ddof=1)
    rs0 = np.random.default_rng(4242)
    print(f"{'ℏ/σ смеси':>11}{'|amp| смесь':>13}{'гаусс. нуль':>18}"
          f"{'сигм':>7}{'период?':>10}")
    worst = 0.0
    for f in (4.0, 2.0, 1.2, 0.8, 0.6, 0.5, 0.4, 0.3):
        hb = f * s_all
        am = abs(np.mean(np.exp(1j * mix / hb)))
        sur = np.empty(300)
        for k2 in range(300):
            Z = rs0.normal(mix.mean(), s_all, n)
            sur[k2] = abs(np.mean(np.exp(1j * Z / hb)))
        z = (am - sur.mean()) / max(sur.std(ddof=1), 1e-12)
        worst = max(worst, abs(z))
        ph = (abs(dS) / hb) / (2 * math.pi)
        print(f'{f:>11.2f}{am:>13.5f}{sur.mean():>13.5f} ± '
              f'{sur.std(ddof=1):.4f}{z:>7.1f}{ph:>10.2f}')
    print()
    print(f'  наибольшее отклонение смеси от гауссова: {worst:.1f} сигм')
    print(f'  (у чистых сприклингов было 0.9)')
    if worst > 3.0:
        print('  => СТРУКТУРА ПОЯВИЛАСЬ, и появилась именно от')
        print('     неcприклинговых конфигураций. Значит квантовый слой')
        print('     живёт не в сумме по сприклингам, а в сумме по ВСЕМ')
        print('     порядкам — там, где и работает область.')
    else:
        print('  => структуры не появилось даже со слоистыми: либо')
        print('     разрыв мал, либо смесь всё ещё гауссова по сумме.')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

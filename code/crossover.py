#!/usr/bin/env python3
"""РАЗМЕР ПЕРЕХОДА: до какого N многообразные порядки преобладают?

ЧТО ЭТО ЗАКРЫВАЕТ. Пункт A3 плана — «полосовая структура подавления по
`ℏ`» — объявлен открытым в печати: Карлип прямо пишет «мы не знаем,
точны ли эти границы». Точные постоянные действия на слоистых порядках
(проверены в `suppress.py` на 16 конфигурациях) позволяют дать число.

ДВЕ СВОБОДНЫЕ ЭНЕРГИИ.

Слоистые порядки: число их растёт как `e^{F(β)·N²}` с

    F(β) = ¼ ln( 1/(1−q*) ),   q* = 1/(1 + e^{β k_d}),   k_4 = 4/√6

(вес `e^{+βS}`; при `q = O(1)` слагаемые `N_1..N_3` экспоненциально малы,
поэтому `S = −k_d N_0`).

Многообразные порядки: причинный порядок сприклинга задаётся знаками
`N²` квадратичных форм от `dN` координат, поэтому по границе
Милнора–Тома число ТИПОВ порядка не превосходит `(C N/d)^{dN}`, то есть
растёт как `e^{d N ln N}` — на `N²` это НОЛЬ.

ПЕРЕХОД там, где `F(β) N² = d N ln N`, то есть

    N*(β) = (d / F(β)) · ln N*(β).

ОБРАТНАЯ ЗАДАЧА, и она физическая. В наблюдаемой Вселенной около
`10^240` планковских четырёхобъёмов. Какое `β` нужно, чтобы порядок
такого размера был многообразным?

ОГОВОРКИ, их три и они существенны.
  1. Знак `β` зависит от соглашения, связывающего `S_БД` с
     Эйнштейном–Гильбертом, и от аналитического продолжения. Считаются
     оба знака.
  2. Коэффициент энтропии многообразных взят как `d` из границы
     Милнора–Тома — это ОЦЕНКА СВЕРХУ на число типов, значит `N*` —
     оценка снизу.
  3. Это классический подсчёт весов, а не квантовая амплитуда:
     интерференции здесь нет.

  python3 crossover.py
"""
import math

K = {2: 4.0, 4: 4.0 / math.sqrt(6.0)}


def qstar(beta, d):
    x = beta * K[d]
    return math.exp(-x) if x > 700 else 1.0 / (1.0 + math.exp(x))


def F_plus(beta, d):
    """Свободная энергия слоистых на N² при весе e^{+βS}."""
    x = beta * K[d]
    if x > 700:
        return 0.25 * math.exp(-x)          # q* ≈ e^{-x}, ln(1/(1-q*)) ≈ q*
    q = 1.0 / (1.0 + math.exp(x))
    return 0.25 * (-math.log1p(-q))


def nstar(beta, d, it=200):
    f = F_plus(beta, d)
    if f <= 0:
        return math.inf
    lg = 10.0
    for _ in range(it):
        n = (d / f) * lg
        if n <= math.e:
            return math.e
        lg = math.log(n)
    return (d / f) * lg


def beta_for(N, d):
    """Какое β нужно, чтобы многообразные преобладали при данном N."""
    need = d * math.log(N) / N            # требуется F(β) < need
    lo, hi = 0.0, 1e6
    for _ in range(300):
        mid = 0.5 * (lo + hi)
        if F_plus(mid, d) > need:
            lo = mid
        else:
            hi = mid
    return hi


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('=' * 84)
    print('ВЕС e^{−βS}: многообразные подавлены как e^{−β k_d N²/4}')
    print(f"{'β':>8}{'F слоистых на N², d=4':>26}{'подавление при N=10³':>24}")
    for b in (0.01, 0.1, 1.0, 10.0):
        f = b * K[4] / 4.0
        print(f'{b:>8.2f}{f:>26.5f}{"e^{-" + f"{f*1e6:.3g}" + "}":>24}')
    print('  перехода нет ни при каком β > 0: F растёт линейно по β')
    print()
    print('=' * 84)
    print('ВЕС e^{+βS}: есть размер перехода')
    print(f"{'β':>8}{'q*':>12}{'F на N² (d=4)':>18}{'N* (d=4)':>16}"
          f"{'N* (d=2)':>16}")
    for b in (0.3, 1, 3, 10, 30, 100, 200, 334, 500):
        print(f'{b:>8.0f}{qstar(b, 4):>12.2e}'
              f'{F_plus(b, 4):>18.3e}{nstar(b, 4):>16.3e}'
              f'{nstar(b, 2):>16.3e}')
    print()
    print('=' * 84)
    print('ОБРАТНАЯ ЗАДАЧА: какое β нужно для порядка данного размера?')
    print(f"{'N':>12}{'что это':>34}{'β нужно (d=4)':>16}"
          f"{'β нужно (d=2)':>16}")
    cases = [
        (1e3, 'наши прогоны'),
        (1e6, 'большой расчёт'),
        (1e60, 'песчинка, планковские объёмы'),
        (1e120, 'Земля'),
        (1e240, 'наблюдаемая Вселенная'),
    ]
    for N, what in cases:
        print(f'{N:>12.0e}{what:>34}{beta_for(N, 4):>16.1f}'
              f'{beta_for(N, 2):>16.1f}')
    print()
    print('=' * 84)
    b4 = beta_for(1e240, 4)
    print('ИТОГ')
    print(f"""
Чтобы причинное множество размером с наблюдаемую Вселенную
(около 10^240 планковских четырёхобъёмов) преобладало над слоистыми
порядками, нужно

    β ≳ {b4:.0f}   в четырёх измерениях,   β ≳ {beta_for(1e240, 2):.0f}  в двух.

ЗАВИСИМОСТЬ. Из условия `e^{{−β k_d}}/4 < d ln N / N` выходит

    β ≈ ln N / k_d,

то есть `β` растёт ЛИНЕЙНО по `ln N` (логарифмически по `N`). Сверка по
таблице: 60, 120 и 240 порядков величины дают 80, 164 и 333 — ровно
вдвое и вдвое. На каждые сто порядков величины размера нужно около
{(beta_for(1e240,4)-beta_for(1e140,4)):.0f} единиц β.

Отсюда ответ на вопрос Карлипа «точны ли эти границы»: граница ОЧЕНЬ
мягкая. От песчинки до наблюдаемой Вселенной — 180 порядков величины —
требование по `β` вырастает всего с {beta_for(1e60,4):.0f} до {b4:.0f}. Значит
никакой тонкой настройки нет: умеренное `β` обслуживает любой разумный
размер мира, и чувствительность к размеру логарифмическая.

ЧЕГО ЭТО НЕ ДАЁТ. Перевести `β` в длину дискретности здесь НЕЛЬЗЯ:
соглашение, связывающее безразмерный порядковый счёт с действием
Эйнштейна–Гильберта, в этом расчёте не закреплено, а от него зависит,
читать ли `β` как `(ℓ/ℓ_P)²` (тогда {b4**0.5:.0f} планковских длин) или как
`(ℓ/ℓ_P)⁴` (тогда {b4**0.25:.1f}). Литература даёт порог `ℓ ≳ 1.136 ℓ_P`
другим путём; это утверждение того же рода, но прямо с нашим не
сравнимо, и выдавать согласие за проверку нельзя.

И главная оговорка остаётся: это классический подсчёт весов, а не
квантовая амплитуда. Интерференции здесь нет, а именно она — суть
вопроса про `ℏ`.
""")


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ДВА ТОЖДЕСТВА ПРОТИВ ДВУХ ПАРАМЕТРОВ: ПУСТА ЛИ ОБЛАСТЬ.

ident.py: сетка была поставлена грубо (q=0 есть антицепь, вырождение, и
поиск ухватился за него). Но разбор дал кое-что лучше починки.

Чему равно тождество у врага. Пара из СОСЕДНИХ слоёв всегда имеет
|I| = 0, между ними нет слоя; таких предшественников у элемента ~ q N/k.
Пары через слой имеют |I| ~ q^2 N/k - большие, в веса (1,-2,1) не
попадают. Значит
    sum_m w_m n_m  ~  n_0  ~  q N / k,   растёт ЛИНЕЙНО с N.
Чтобы тождество держалось при всех N, врагу нужно q ~ k/N. Но тогда у
элемента O(1) предшественников, порядок разреженный, и доля связанных
r -> 0, тогда как у засева r ~ 0.5.

ДВА требования БЕЗ ПАРАМЕТРОВ против ДВУХ параметров:
    (A) sum_m w_m n_m = 1/2     - существует даламбертиан
    (B) r = r_засева            - та же доля связанных
и они тянут в разные стороны. Вопрос: пуста ли совместная область?

Это тот же приём, что в census (пуста ли область у врага), но с
ТОЖДЕСТВАМИ вместо статистик: подгонять нечего, значение задано заранее.

КОНТРОЛЬ (анкер): засев обязан удовлетворять ОБОИМ при всех N. Выборка
увеличена - в ident.py при N=1600 было всего 4 засева и анкер поехал
вниз на 2.6 сигмы, что надо либо подтвердить, либо списать на выборку.
"""
import math

import numpy as np

from waveop import causal, sprinkle_11
from lkdeg import layered

W = (1.0, -2.0, 1.0)


def both(Rc):
    n = Rc.shape[0]
    F = Rc.astype(np.float32)
    Iv = np.rint(F @ F).astype(np.int32)
    tot = np.zeros(n)
    for m, w in enumerate(W):
        tot += w * (Rc.T & (Iv.T == m)).sum(axis=1)
    r = float(Rc.sum()) / (n * (n - 1) / 2)
    return float(tot.mean()), r


def avg(mk, rep):
    v = np.array([both(mk()) for _ in range(rep)])
    return (v[:, 0].mean(), v[:, 0].std() / math.sqrt(rep),
            v[:, 1].mean(), v[:, 1].std() / math.sqrt(rep))


def main():
    print(__doc__)
    rs = np.random.default_rng(577215)

    print('АНКЕР: засев d=2 — оба требования, выборка увеличена')
    anch = {}
    for n, rep in ((400, 60), (800, 30), (1600, 12)):
        i, ie, r, re = avg(lambda: causal(sprinkle_11(n, rs)), rep)
        anch[n] = (i, ie, r, re)
        print(f'  N={n:>5}: тождество {i:+.4f}±{ie:.4f} '
              f'({(i - 0.5) / ie:+.1f}σ от 1/2),  r={r:.4f}±{re:.4f}',
              flush=True)

    n = 800
    r0 = anch[n][2]
    print(f'\nВРАГ при N={n}: ищем точку, где ОБА требования '
          f'(тождество=1/2, r={r0:.3f})')
    print(f"{'k':>4}{'q':>8}{'тождество':>12}{'r':>9}"
          f"{'|откл A|':>10}{'|откл B|':>10}")
    rows = []
    for k in (2, 3, 4, 6, 10, 16, 26, 40):
        for q in (0.02, 0.05, 0.1, 0.2, 0.4, 0.7):
            i, ie, r, re = avg(lambda: layered(n, k, q, rs), 4)
            rows.append((k, q, i, r))
            fa = abs(i - 0.5)
            fb = abs(r - r0)
            if fa < 3.0 or fb < 0.05:
                print(f'{k:>4}{q:>8.2f}{i:>12.3f}{r:>9.3f}'
                      f'{fa:>10.3f}{fb:>10.3f}', flush=True)

    print('\nсводка: ближайшие точки по КАЖДОМУ требованию отдельно')
    ba = min(rows, key=lambda t: abs(t[2] - 0.5))
    bb = min(rows, key=lambda t: abs(t[3] - r0))
    print(f'  лучшее по A: k={ba[0]} q={ba[1]}  тождество={ba[2]:+.3f}, '
          f'r={ba[3]:.3f}  (r мимо на {abs(ba[3] - r0):.3f})')
    print(f'  лучшее по B: k={bb[0]} q={bb[1]}  r={bb[3]:.3f}, '
          f'тождество={bb[2]:+.3f}  (тождество мимо на '
          f'{abs(bb[2] - 0.5):.3f})')
    print('\nесли ни одна точка не близка к обоим — область пуста,')
    print('и это вывод БЕЗ подгонки: оба значения заданы заранее.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""СЛОВАРЬ: от счёта событий к плотности материи, и чего это стоит.

ЧТО ЗДЕСЬ ДЕЛАЕТСЯ И ЧЕГО НЕ ДЕЛАЕТСЯ. Уравнение Эйнштейна берётся как
ВХОД, а не выводится. Вопрос ставится так: ЕСЛИ оно верно, то что
означает наш замер?

Свёртка уравнения со скоростью наблюдателя даёт

    R_μν u^μu^ν = 4 pi G (rho + 3p)

а в `chains-doc.md` измерено, что три счёта интервала дают именно
`R_μν u^μu^ν`, с точностью

    ст.ош( R_uu l² ) = 40 / C_1

Значит счёт событий в интервале меряет ПЛОТНОСТЬ ГРАВИТИРУЮЩЕЙ ЭНЕРГИИ
в его месте и по его направлению. Отсюда прямой вопрос: сколько событий
нужно, чтобы различить плотность настоящего вещества?

Условие обнаружения на единице отношения сигнала к шуму:

    C_1 = 40.3 / (R_uu l²),    R_uu l² = 4 pi rho/rho_планк

а размер интервала по собственному времени из `C_1 = (pi/24)(tau/l)^4`.

ПРОВЕРКА ПРИГОДНОСТИ. Первый порядок разложения требует `T²R_uu` малым.
Это печатается отдельно: если бы параметр оказался не мал, вся таблица
была бы недействительна.

  python3 dict.py
"""
import math

# планковские единицы (СИ)
L_P = 1.616255e-35          # м
T_P = 5.391247e-44          # с
M_P = 2.176434e-8           # кг
RHO_P = M_P / L_P ** 3      # кг/м³
C = 2.99792458e8

CASES = (
    ('критическая космологическая', 8.5e-27),
    ('межзвёздный газ (1 атом/см³)', 1.67e-21),
    ('воздух', 1.2),
    ('вода', 1.0e3),
    ('свинец', 1.134e4),
    ('ядро Солнца', 1.5e5),
    ('нейтронная звезда', 4.0e17),
)


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print(f'планковская плотность {RHO_P:.3e} кг/м³')
    print()
    print(f"{'вещество':>30}{'rho, кг/м³':>13}{'R_uu l²':>12}"
          f"{'нужно C_1':>12}{'tau':>12}{'размер c*tau':>14}{'T²R_uu':>11}")
    for name, rho in CASES:
        r = rho / RHO_P                 # в планковских
        Ruu = 4.0 * math.pi * r         # R_uu * l² в планковских (G=c=1)
        c1 = 40.3 / Ruu
        tau = (24.0 * c1 / math.pi) ** 0.25 * T_P
        size = C * tau
        par = math.sqrt(24.0 * c1 / math.pi) * Ruu
        print(f'{name:>30}{rho:>13.2e}{Ruu:>12.2e}{c1:>12.2e}'
              f'{tau:>12.2e}{size:>14.2e}{par:>11.1e}')
    print()
    print('ЧИТАЕТСЯ ТАК. Столбец «нужно C_1» — сколько событий должно')
    print('лежать в интервале, чтобы его собственный счёт отличил эту')
    print('плотность от нуля на одной сигме. Столбец «размер» — какого')
    print('масштаба при этом сам интервал, в метрах.')
    print()
    print('Столбец T²R_uu — параметр разложения. Он всюду ничтожен, то')
    print('есть первый порядок в силе с огромным запасом, и таблица')
    print('действительна.')
    print()
    # обратный вопрос: что даёт интервал «человеческого» размера
    print('ОБРАТНЫЙ ВОПРОС: какую плотность различает интервал данного')
    print('размера? (предел по одной сигме)')
    print(f"{'размер':>14}{'C_1':>13}{'предел rho, кг/м³':>22}"
          f"{'для сравнения':>26}")
    for size, cmp_ in ((1e-15, 'радиус протона'),
                       (1e-10, 'размер атома'),
                       (1e-6, 'клетка'),
                       (1e-3, 'миллиметр'),
                       (1.0, 'метр')):
        tau = size / C
        c1 = math.pi / 24.0 * (tau / T_P) ** 4
        Ruu = 40.3 / c1
        rho = Ruu / (4.0 * math.pi) * RHO_P
        print(f'{size:>14.0e}{c1:>13.2e}{rho:>22.2e}{cmp_:>26}')
    print()
    print('ВАЖНО, И ЭТО НЕ ВЫВОД, А СЛОВАРЬ. Уравнение Эйнштейна здесь')
    print('ВХОД. Таблица говорит: если оно верно, то счёт событий меряет')
    print('плотность материи — и меряет с колоссальным запасом. Почему')
    print('оно верно, отсюда не следует; это и есть пятая ступень.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""A И B ЧЕСТНО: совместная подгонка, ошибки складным ножом, обрезание отдельно.

ЗАЧЕМ. Прошлые числа («A промах 6 %, B промах 26 %», потом «B промах
29 %, A промах 86 %») были получены с ДВУМЯ ошибками в самой ошибке, и
обе найдены:

  1. РОМБЫ СЧИТАЛИСЬ НЕЗАВИСИМЫМИ. Внутри одного засева они перекрываются
     и делят одни и те же события. Деление разброса на `sqrt(число
     ромбов)` занижало ошибку до 4 раз. Единица независимости — ЗАСЕВ.

  2. ОШИБКА B НЕ ПРОТАСКИВАЛАСЬ В A. В квадратичном семействе вклад
     равен `c(6A − 3B)`, то есть член с B ВТРОЕ больше измеряемого, и A
     выходит остатком после вычитания. При `dB = 0.007` это даёт
     `dA = 0.0037`, что вдвое больше самого `1/180`. Я же ставил A
     ошибку в 0.0015.

ПОЧИНКА — одна подгонка на оба семейства сразу:

    dev_i = A * (tau²R)_i + B * (tau²R_uu)_i

по ВСЕМ ромбам всех семейств. Линейное семейство (`R = 0` тождественно)
даёт строки с чистым B, квадратичное — смешанные; вместе они и разводят
A и B, а ковариация выходит из подгонки сама, а не приписывается рукой.

ВЕС, И ТРЕТЬЯ ПОЙМАННАЯ ОШИБКА. Разброс `dev` равен примерно `1/n`, где
`n` — число событий в ромбе, значит обратная дисперсия есть сам `n`, и
без весов крупные ромбы, несущие почти всю информацию, тонули бы в
мелких. Но брать в качестве веса НАБЛЮДЁННОЕ `n` нельзя: измеряемая
величина есть `n/база − 1`, то есть вес оказывается скоррелирован с
собственным шумом, и ромб, случайно набравший больше событий, получает
больший вес. Смещение выходит около `+1/n` на ромб, то есть `+0.01` при
сотне событий — БОЛЬШЕ самого `1/180`. Нулевой контроль поймал это как
`A = +0.0038 +- 0.0009` вместо нуля.

Починка: вес есть ОЖИДАЕМОЕ число событий `rho·V_точный` — величина
детерминированная, от реализации не зависящая. Оптимальность веса при
этом сохраняется, потому что `V_точный ≈ база`.

ОБРЕЗАНИЕ РЯДА — отдельно и БЕЗ шума. Та же подгонка прогоняется по
ТОЧНЫМ объёмам (одномерный интеграл, `exact.py`). Её результат
говорит, какими первые коэффициенты ОБЯЗАНЫ выйти при наших `tau`, если
причинное множество идеально: разница с опубликованными есть чистая
поправка высших порядков, непрерывная величина без всякой статистики.
Тогда замер сравнивается с ней, а не с идеалом, и сравнение честное.

КОНТРОЛИ:
  1. ПЛОСКОЕ (`par = 0`): подгонка обязана дать A = B = 0;
  2. подгонка по точным объёмам обязана дать коэффициенты БЛИЗКО к
     опубликованным — иначе неверны мои формулы кривизны, а не замер;
  3. замер против подгонки по точным — вот это и есть проверка счёта.

  python3 coef.py [--seeds 150]
"""
import argparse
import math
import time

import numpy as np

from twoterm import LELL, TELL, ETA0, curv, sprinkle, chain, count
from exact import exact_volume

GAPS = (3, 4, 5)
VS = (0.0, 0.45, 0.70)
XOFFS = (-4.5, -1.5, 1.5, 4.5)
STEP, NCHAIN = 1.4, 11
FAMS = (('lin', 0.04), ('lin', 0.08), ('quad', 0.004), ('quad', 0.012))


def geometry(fam, par, sfam, spar):
    """Список ромбов семейства: остриё-остриё, план, точный объём.

    Ни цепи, ни точный объём от засева НЕ зависят, поэтому считаются
    один раз на семейство, а не заново на каждый засев.

    `fam/par` задают кривизну для СТРОКИ ПЛАНА, `sfam/spar` — ту
    геометрию, в которой реально живут события. В рабочем прогоне они
    совпадают; в нулевом контроле вторая пара плоская.
    """
    out = []
    for v in VS:
        pm = v / math.sqrt(1 - v * v) if v > 0 else 0.0
        for xo in XOFFS:
            C = chain(sfam, spar, v, STEP, NCHAIN, xo)
            for g in GAPS:
                tau = g * STEP
                base = math.pi / 24 * tau ** 4
                for i in range(NCHAIN - g):
                    mid = 0.5 * (C[i, 0] + C[i + g, 0])
                    if abs(mid - ETA0) > 4.0:
                        continue
                    de = C[i + g, 0] - C[i, 0]
                    if (min(C[i, 1], C[i + g, 1]) - de / 2 < 0.5
                            or max(C[i, 1], C[i + g, 1]) + de / 2
                            > LELL - 0.5):
                        continue
                    if C[i, 0] < 0.5 or C[i + g, 0] > TELL - 0.5:
                        continue
                    R, Ruu = curv(mid, fam, par, pm)
                    out.append((C[i].copy(), C[i + g].copy(), base, de,
                                (tau ** 2 * R, tau ** 2 * Ruu),
                                exact_volume(C[i], C[i + g], sfam, spar)))
    return out


def trim(X, rmax):
    """Отбрасывает события, которые ни в один ромб попасть не могут.

    Все цепи идут при y = z = LELL/2, а ромб с остриями, разнесёнными по
    времени на `de`, не выходит по y и z дальше `de/2` от этой оси.
    Значит события с |y − LELL/2| > rmax или |z − LELL/2| > rmax лишние,
    и это строгое надмножество: ни одно нужное событие не теряется.

    Выигрыш не косметический: ромб занимает по y и z около четверти
    ящика, а `count` до этого перебирал весь слой по времени.
    """
    m = ((np.abs(X[:, 2] - LELL / 2) <= rmax)
         & (np.abs(X[:, 3] - LELL / 2) <= rmax))
    return np.ascontiguousarray(X[m])


def collect(fams, seeds, root=71000, null=False):
    """Накапливает по ромбам: засев, строка плана, замер, точное, вес."""
    sd_i, des, ym, ye, wt, wn = [], [], [], [], [], []
    for fi, (fam, par) in enumerate(fams):
        sfam, spar = ('lin', 0.0) if null else (fam, par)
        G = geometry(fam, par, sfam, spar)
        rmax = max(g[3] for g in G) / 2 + 1e-9
        for sd in range(seeds):
            X, rho = sprinkle(sfam, spar,
                              np.random.default_rng(root + 37 * sd
                                                    + 1000003 * fi))
            Xt = trim(X, rmax)
            del X
            for p, f, base, _, row, Ve in G:
                n = count(Xt, p, f)
                sd_i.append(sd)
                des.append(row)
                ym.append(n / rho / base - 1.0)
                ye.append(Ve / base - 1.0)
                # вес — ОЖИДАЕМОЕ число событий, а не наблюдённое
                wt.append(rho * Ve)
                wn.append(max(n, 1))      # только для показа смещения
            del Xt
    return (np.array(sd_i), np.array(des), np.array(ym),
            np.array(ye), np.array(wt, dtype=float),
            np.array(wn, dtype=float))


def wls(D, y, w):
    """Взвешенные наименьшие квадраты без свободного члена."""
    Dw = D * w[:, None]
    return np.linalg.solve(D.T @ Dw, Dw.T @ y)


def jackfit(sd, D, y, w, seeds):
    """Подгонка и ошибка складным ножом по ЗАСЕВАМ (а не по ромбам)."""
    full = wls(D, y, w)
    jk = []
    for s in range(seeds):
        m = sd != s
        if m.sum() < 10:
            continue
        jk.append(wls(D[m], y[m], w[m]))
    jk = np.array(jk)
    n = len(jk)
    cov = (n - 1) / n * ((jk - jk.mean(0)).T @ (jk - jk.mean(0)))
    return full, cov


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--seeds', type=int, default=150)
    a = ap.parse_args()
    t0 = time.time()
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('=' * 72)
    Apub, Bpub = -1 / 180.0, 1 / 30.0

    nseed = max(40, a.seeds // 3)
    print('КОНТРОЛЬ №1: ПЛОСКОЕ — подгонка обязана дать нуль.')
    print('События сыплются плоско и цепи плоские, но строки плана взяты')
    print('от настоящих кривизн семейств, с тем же разбросом, что в бою.')
    print('Любой ненулевой A или B здесь есть систематика процедуры.')
    sdf, Df, ymf, _, wf, wnf = collect(FAMS, nseed, root=52000, null=True)
    print(f'  ромбов {len(ymf)}')
    print('  Показываю ОБА веса: наблюдённое число событий (так было —')
    print('  вес скоррелирован с шумом) и ожидаемое (так правильно).')
    for tag, ww in (('вес = наблюдённое n (ошибка)', wnf),
                    ('вес = ожидаемое rho*V (верно)', wf)):
        c, cvv = jackfit(sdf, Df, ymf, ww, nseed)
        e = np.sqrt(np.diag(cvv))
        print(f'    {tag}:')
        print(f'      A = {c[0]:+.5f} +- {e[0]:.5f} '
              f'({abs(c[0])/e[0]:.1f} сигм),   '
              f'B = {c[1]:+.5f} +- {e[1]:.5f} ({abs(c[1])/e[1]:.1f} сигм)')
    print(f'  ({time.time()-t0:.0f} с)', flush=True)
    print()

    print(f'СБОР ДАННЫХ: семейства {FAMS}, засевов {a.seeds}')
    sd, D, ym, ye, w, wn = collect(FAMS, a.seeds)
    print(f'  ромбов всего {len(ym)}, ожидаемых событий в ромбе от '
          f'{w.min():.0f} до {w.max():.0f}   ({time.time()-t0:.0f} с)')
    print()

    print('КОНТРОЛЬ №2: подгонка по ТОЧНЫМ объёмам (шума нет вовсе).')
    print('Она говорит, какими коэффициенты ОБЯЗАНЫ выйти при наших tau')
    print('с учётом обрезания ряда. Отличие от опубликованных — чистая')
    print('поправка высших порядков, непрерывная величина.')
    ce = wls(D, ye, w)
    print(f"{'':>14}{'подгонка по точным':>22}{'опубликовано':>16}"
          f"{'поправка':>12}")
    print(f"{'A':>14}{ce[0]:>+22.5f}{Apub:>+16.5f}"
          f"{(ce[0]/Apub-1)*100:>11.1f}%")
    print(f"{'B':>14}{ce[1]:>+22.5f}{Bpub:>+16.5f}"
          f"{(ce[1]/Bpub-1)*100:>11.1f}%")
    print()

    print('ЗАМЕР: та же подгонка по СЧЁТУ, ошибки складным ножом по засевам')
    cm, cv = jackfit(sd, D, ym, w, a.seeds)
    em = np.sqrt(np.diag(cv))
    rho_ab = cv[0, 1] / (em[0] * em[1])
    print(f'  A = {cm[0]:+.5f} +- {em[0]:.5f}')
    print(f'  B = {cm[1]:+.5f} +- {em[1]:.5f}')
    print(f'  корреляция A и B в подгонке: {rho_ab:+.3f}')
    print()
    print('СРАВНЕНИЕ (главное — со вторым столбцом, он учитывает обрезание)')
    print(f"{'':>6}{'замер':>12}{'ст.ош':>10}{'против точных':>16}"
          f"{'сигм':>7}{'против опубл.':>16}{'сигм':>7}{'точность':>11}")
    for j, nm in ((0, 'A'), (1, 'B')):
        pub = (Apub, Bpub)[j]
        print(f'{nm:>6}{cm[j]:>+12.5f}{em[j]:>10.5f}{ce[j]:>+16.5f}'
              f'{abs(cm[j]-ce[j])/em[j]:>7.1f}{pub:>+16.5f}'
              f'{abs(cm[j]-pub)/em[j]:>7.1f}'
              f'{em[j]/abs(pub)*100:>10.0f}%')
    print()
    chi = float((cm - ce) @ np.linalg.inv(cv) @ (cm - ce))
    print(f'  совместное отклонение от точных: хи² = {chi:.2f} на 2 степени'
          f'  (порог 5.99 при 95 %)')
    print(f'  => {"СХОДИТСЯ" if chi < 5.99 else "НЕ СХОДИТСЯ"}')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

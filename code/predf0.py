#!/usr/bin/env python3
"""ПРЕДСКАЗАНИЕ ДЛЯ УСТОЙЧИВОЙ ВЕЛИЧИНЫ: отклик <F_k> при фиксированном
физическом объёме.

ЗАЧЕМ. В `jacob.py` площадь добывалась подгонкой амплитуды `c_0` по
вырожденному базису, и подгонка раздувала шум: на интервал точность
около 50 %, а КОНТРОЛЬ (половина плоского против другой половины) дал
снос до +1.8 % — больше искомого сигнала 0.7 %. Замер поэтому
недостоверен.

Починка — та же, что сработала в этой работе уже трижды: брать
УСТОЙЧИВУЮ величину вместо чистой, а предсказание для неё считать
самостоятельно. `F_0` (число максимальных элементов) имеет чисто
пуассоновский шум, около 10 % на интервал, и никакой подгонки не
требует.

РАСЧЁТ. При физической плотности 1 элемент имеет ровно `k` событий в
будущем с вероятностью `u^k e^(-u)/k!`, где `u = V_физ(x,f)` — физический
объём от `x` до остриё. Значит

    <F_k> = V * E_x[ u^k e^(-u) / k! ],   x ровно по ФИЗИЧЕСКОМУ объёму

и `V_физ(x,f)` берётся точным одномерным интегралом по «линзе»
(`exact.py`, проверен до 0.000 % на плоском). Один набор точек даёт
предсказание сразу для всех `k`.

СРАВНЕНИЕ ИДЁТ ПРИ РАВНОМ ОБЪЁМЕ: для плоского ромба объёма `V` и для
ромба излучения ТОГО ЖЕ объёма. Это и есть «при фиксированном объёме» у
Якобсона, переведённое в счёт: `C_1` равно физическому объёму при
плотности 1.

КОНТРОЛЬ: плоское против плоского обязано дать нуль.

  python3 predf0.py
"""
import math

import numpy as np

from exact import lens, _XG, _WG

KMAX = 12


def a_of(e, fam):
    e = np.asarray(e, dtype=float)
    return np.ones_like(e) if fam == 'flat' else e


def vol_to(e1, es, d, fam):
    """Физический объём ромба между (e1,0) и (es, d) — линза с весом a⁴."""
    if es <= e1:
        return 0.0
    ec = 0.5 * (e1 + es)
    cuts = sorted({e1, es} | {t for t in (ec - d / 2, ec + d / 2)
                              if e1 < t < es})
    V = 0.0
    for lo, hi in zip(cuts[:-1], cuts[1:]):
        et = 0.5 * (hi - lo) * _XG + 0.5 * (hi + lo)
        w = 0.5 * (hi - lo) * _WG
        V += float((lens(et - e1, es - et, d) * a_of(et, fam) ** 4 * w).sum())
    return V


def sample_diamond(e1, e2, fam, n, rs):
    """Точки ромба, распределённые ровно по ФИЗИЧЕСКОМУ объёму.

    ПОЙМАННАЯ ОШИБКА. В первой версии `eta` бралась с весом `a⁴`, то
    есть почти ровно, — а надо с весом `R(eta)³ a⁴`, где
    `R = min(eta-e1, e2-eta)` есть радиус шара при этом `eta`. Без
    множителя `R³` точки сгрудились у остриёв, где `V(x,f) -> 0` и
    `e^(-V) -> 1`, и предсказанное `<F_0>` завысилось на 58 % ДЛЯ
    ПЛОСКОГО. Это же породило мнимый отклик в 32 %.

    Урок записан: предсказание обязано воспроизводить ПЛОСКИЙ замер
    прежде, чем ему верить на кривом.
    """
    e = np.linspace(e1, e2, 20000)
    Rg = np.minimum(e - e1, e2 - e)
    w = (Rg ** 3) * a_of(e, fam) ** 4
    cdf = np.concatenate([[0.0], np.cumsum(0.5 * (w[1:] + w[:-1])
                                           * np.diff(e))])
    et = np.interp(rs.uniform(0, cdf[-1], n), cdf, e)
    R = np.minimum(et - e1, e2 - et)
    # ровно внутри шара радиуса R: радиус по корню третьей степени
    rr = R * rs.uniform(0, 1, n) ** (1.0 / 3.0)
    return et, rr


def predict(e1, e2, fam, n=20000, rs=None):
    """<F_k> для k = 0..KMAX и физический объём ромба."""
    rs = rs or np.random.default_rng(777)
    V = vol_to(e1, e2, 0.0, fam)
    et, rr = sample_diamond(e1, e2, fam, n, rs)
    u = np.array([vol_to(e, e2, r, fam) for e, r in zip(et, rr)])
    ks = np.arange(KMAX + 1)
    lg = np.array([math.lgamma(k + 1.0) for k in ks])
    W = np.exp(ks[:, None] * np.log(np.maximum(u, 1e-300))[None, :]
               - u[None, :] - lg[:, None])
    return V, V * W.mean(axis=1)


def solve_eta(V, ew, frac0=0.2, fam='frw'):
    """Подбирает протяжённость ромба вокруг ew под заданный объём V."""
    lo, hi = 1e-4, 1.5 * ew
    for _ in range(60):
        de = 0.5 * (lo + hi)
        v = vol_to(ew - de / 2, ew + de / 2, 0.0, fam)
        if v < V:
            lo = de
        else:
            hi = de
    return 0.5 * (lo + hi)



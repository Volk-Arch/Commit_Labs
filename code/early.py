    for t in (10, 20, 50, 100, 300, 1000, 3000, 1e4, 1e5):
        Ruu = 3.0 / (4 * t * t)
        c1 = 40.3 / Ruu
        tl = (24.0 * c1 / math.pi) ** 0.25
        par = math.sqrt(24.0 * c1 / math.pi) * Ruu
        fits = tl <= t
        sim = c1 <= 2e7
        mark = ('да' if (fits and sim) else
                ('не влезает' if not fits else 'тяжело'))
        print(f'{t:>13.0f}{Ruu:>12.2e}{c1:>12.2e}{tl:>10.1f}'
              f'{tl/t:>9.2f}{par:>10.3f}{mark:>8}')
    print()
    # пол по времени: tau <= t
    print('ПОЛ ПО ВРЕМЕНИ. Условие tau <= t даёт')
    print('  tau/l = (24*53.7*t²/pi)^(1/4) = 4.5 sqrt(t) <= t  =>  t >= 20')
    print('  То есть начиная примерно с 20 планковских времён интервал,')
    print('  умеющий померить плотность Вселенной, уже влезает в её')
    print('  горизонт. Раньше — нет, и там замер бессмыслен.')
    print()
    print('ЧЕМ ПЛАТИТЬ ЗА ТОЧНОСТЬ: размером или числом интервалов?')

#!/usr/bin/env python3
"""ПИК ВОСПРИИМЧИВОСТИ: разрешить и проверить на конечный размер.

Точная статсумма (`ensemble.py`) дала пик `Var S/N²` при `beta ~ -0.2`,
растущий с размером: 2.64, 4.36, 7.38 при `N` = 5, 6, 7. Пик узкий: у
`N` = 7 значение 7.38 при `beta = -0.20`, а у соседей по грубой сетке
1.71 и 2.58. Параметры порядка через него меняются: обе крайности по
`beta` упорядоченнее середины (`r` = 0.71 и 0.81 против 0.42).

ЗДЕСЬ пик разрешается тонкой сеткой и проверяется на конечный размер:
растут ли ВЫСОТА и сужается ли ШИРИНА, сходится ли ПОЛОЖЕНИЕ. Это и
отличает фазовый переход от особенности малого размера.

ПОПРАВКА КОНТРОЛЯ. В прошлом прогоне я печатал минимум `|S|` по ВСЕМ
порядкам и сравнивал со значением у пустого — минимум не обязан
достигаться на пустом, так что проверка была бессмысленна. Здесь
пустой порядок проверяется ОТДЕЛЬНО: у него нет отношений, значит
`N_0 = N_1 = N_2 = 0` и `S⁽²⁾ = 2N` точно.

ДОБАВЛЕНО: то же для действия `d = 4`. Если пик стоит на том же `beta`
у двух РАЗНЫХ действий — он свойство ансамбля; если на разных — свойство
действия.

КОНТРОЛЬ СЕТКИ: пик не должен ездить при сгущении сетки по `beta`.

  python3 ensemble2.py
"""
import math

import numpy as np

from ensemble import enumerate_orders, K4

FINE = np.arange(-0.60, 0.61, 0.01)


def curve(S, n, betas):
    out = []
    for b in betas:
        e = -b * S; e -= e.max()
        w = np.exp(e)
        sm = (w * S).sum() / w.sum()
        s2 = (w * S * S).sum() / w.sum()
        out.append((s2 - sm ** 2) / n ** 2)
    return np.array(out)


def peak(betas, v):
    k = int(np.argmax(v))
    half = v[k] / 2.0
    lo = hi = betas[k]
    for i in range(k, -1, -1):
        if v[i] < half:
            lo = betas[i]; break
    for i in range(k, len(v)):
        if v[i] < half:
            hi = betas[i]; break
    return betas[k], v[k], hi - lo


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('КОНТРОЛЬ: пустой порядок, S⁽²⁾ обязано быть 2N')
    for n in (3, 5, 7):
        d = enumerate_orders(n)
        # пустой порядок — тот, у которого нет отношений
        i0 = int(np.argmin(d['rel']))
        print(f'  N = {n}: отношений {d["rel"][i0]}, '
              f'S⁽²⁾ = {d["S2"][i0]:.1f}, ожидается {2*n}, '
              f'{"совпало" if abs(d["S2"][i0] - 2*n) < 1e-9 else "НЕ СОВПАЛО"}')
    print()
    print('=' * 78)
    print('ПИК ПРИ ТОНКОЙ СЕТКЕ (шаг 0.01)')
    print(f"{'N':>4}{'порядков':>10}", end='')
    for tag in ('d=2', 'd=4'):
        print(f'{f"beta пика {tag}":>17}{f"высота {tag}":>14}'
              f'{f"ширина {tag}":>14}', end='')
    print()
    hist = {2: [], 4: []}
    for n in (4, 5, 6, 7):
        d = enumerate_orders(n)
        print(f'{n:>4}{len(d["S2"]):>10}', end='')
        for dim, key in ((2, 'S2'), (4, 'S4')):
            b0, h0, w0 = peak(FINE, curve(d[key], n, FINE))
            hist[dim].append((n, b0, h0, w0))
            print(f'{b0:>17.3f}{h0:>14.3f}{w0:>14.3f}', end='')
        print(flush=True)
    print()
    print('=' * 78)
    print('МАСШТАБИРОВАНИЕ С РАЗМЕРОМ')
    for dim in (2, 4):
        H = np.array(hist[dim])
        ln = np.log(H[:, 0])
        ah = np.polyfit(ln, np.log(H[:, 2]), 1)[0]
        aw = np.polyfit(ln, np.log(np.maximum(H[:, 3], 1e-6)), 1)[0]
        print(f'  d = {dim}: высота ~ N^{ah:+.2f}, ширина ~ N^{aw:+.2f}, '
              f'положение {H[0,1]:+.3f} -> {H[-1,1]:+.3f}')
    print()
    print('КОНТРОЛЬ СЕТКИ: пик не должен ездить при сгущении')
    d = enumerate_orders(7)
    for step in (0.04, 0.02, 0.01, 0.005):
        g = np.arange(-0.6, 0.601, step)
        b0, h0, w0 = peak(g, curve(d['S2'], 7, g))
        print(f'  шаг {step:.3f}: beta = {b0:+.4f}, высота {h0:.3f}, '
              f'ширина {w0:.3f}')
    print()
    print('''ЧТЕНИЕ. Переход настоящий, если высота растёт, ширина СУЖАЕТСЯ,
а положение сходится. Если ширина не сужается — это не переход, а
гладкий кроссовер, и так и надо записать. Совпадение положения у двух
разных действий говорит, что особенность — свойство ансамбля, а не
действия.''')


if __name__ == '__main__':
    main()

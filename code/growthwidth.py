#!/usr/bin/env python3
"""РОСТ И ГРАНИЦА: какой закон p(n) даёт нужный показатель ширины.

Два сегодняшних вывода сошлись на одном: правило обязано быть условием
на РОСТ (`census-doc.md`), а его состояние есть ГРАНИЦА — максимальная
антицепь (`compose-doc.md`). Значит мерить надо, как растёт граница в
самом процессе роста.

Процесс — транзитивная перколяция как ПОСЛЕДОВАТЕЛЬНЫЙ рост: на шаге n
новый элемент берёт каждый существующий в «родители» с вероятностью
p(n), прошлое есть замыкание выбранного вниз. Это шаг Райдаута–Соркина
в простейшем виде.

УЗКОЕ МЕСТО ВСЕЙ ПРОГРАММЫ, которое здесь и проверяется. Архив даёт
`p* ≈ 1.15 N^{-3/4}` (`measure-doc.md`), то есть `p` обязано ЗАВИСЕТЬ
от N. А в законной динамике Райдаута–Соркина постоянные связи `t_k`
фиксированы: от n зависит только комбинаторика. Перколяция с
`t_k = t^k` даёт РОВНО постоянное p. Значит вопрос «бывает ли правило»
сводится к вопросу «умеет ли поток эффективного p идти как n^{-3/4}».

Здесь мерится первая половина: какой показатель ширины даёт какой
закон `p(n) = c·n^{-alpha}`. Постоянная c во всех случаях подобрана
так, чтобы при n = 100 среднее число родителей было одинаково (~3) —
иначе сравниваются не показатели, а начальные условия.

ПРЕДСКАЗАНИЯ до прогона:
  * alpha = 0 (постоянное p): новый элемент выше почти всего, порядок
    becomes цепь, ширина почти не растёт — показатель около 0;
  * alpha = 1 (p ~ 1/n): O(1) родителей, порядок ветвится — показатель
    около 1;
  * где-то между лежит 3/4. И ОСОБО: при alpha = 3/4, то есть при
    архивном p*, показатель ширины обязан выйти около 3/4, если p*
    действительно подражает четырёхмерию. Это независимая проверка
    архивного p* новым прибором.

Для сравнения: засев d=4 даёт показатель ширины 0.816 ± 0.017 на том
же размахе (`compose-doc.md`), подходя к 3/4 сверху.

КОНТРОЛЬ: ширина считается точно (Дилворт + Кёниг), и алгоритм уже
сверен на цепи (1), антицепи (N) и слоистом (размер слоя).
"""
import math

import numpy as np

from width3 import width


def grow(nmax, alpha, c, rs, checks):
    """Последовательный рост; ширина в контрольных точках."""
    Rc = np.zeros((nmax, nmax), bool)
    out = {}
    par = []
    for k in range(1, nmax):
        p = min(1.0, c * k ** (-alpha))
        ch = rs.random(k) < p
        if ch.any():
            past = ch | Rc[:k, :k][:, ch].any(axis=1)
        else:
            past = ch
        Rc[:k, k] = past
        par.append(int(ch.sum()))
        if (k + 1) in checks:
            out[k + 1] = width(Rc[:k + 1, :k + 1])
    return out, float(np.mean(par[:120]))


def fit(xs, ys):
    lx, ly = np.log(np.array(xs, float)), np.log(np.array(ys, float))
    A = np.vstack([lx, np.ones(len(lx))]).T
    be, *_ = np.linalg.lstsq(A, ly, rcond=None)
    r = ly - A @ be
    se = math.sqrt(float((r ** 2).sum() / max(len(lx) - 2, 1))
                   / float(((lx - lx.mean()) ** 2).sum()))
    return float(be[0]), se


def main():
    print(__doc__)
    rs = np.random.default_rng(31011961)
    checks = {250, 500, 1000, 2000}
    nmax = 2000
    print(f"{'alpha':>7}{'<родителей>':>13}" +
          ''.join(f'{f"n={x}":>8}' for x in sorted(checks)) +
          f"{'показатель':>13}")
    rows = []
    for alpha in (0.0, 0.25, 0.5, 0.75, 1.0):
        c = 0.03 * 100 ** alpha
        W = {n: [] for n in checks}
        pmean = []
        for _ in range(3):
            out, pm = grow(nmax, alpha, c, rs, checks)
            for n in checks:
                W[n].append(out[n])
            pmean.append(pm)
        xs = sorted(checks)
        ys = [float(np.mean(W[n])) for n in xs]
        a, se = fit(xs, ys)
        rows.append((alpha, a, se))
        print(f'{alpha:>7.2f}{np.mean(pmean):>13.2f}'
              + ''.join(f'{y:>8.1f}' for y in ys)
              + f'{a:>8.4f}±{se:<4.3f}', flush=True)

    print('\nСРАВНЕНИЕ с требуемым 3/4 и с засевом')
    print('  засев d=4 (замер, compose-doc): 0.8160 ± 0.017, '
          'подходит к 0.750 сверху')
    for alpha, a, se in rows:
        d = abs(a - 0.75) / max(se, 1e-9)
        print(f'  alpha={alpha:.2f}: показатель {a:.4f} ± {se:.3f}, '
              f'от 3/4 на {d:.1f} сигм'
              + ('   <-- ближе всех' if d < 2 else ''))
    best = min(rows, key=lambda r: abs(r[1] - 0.75))
    print(f'\n  ближе всех alpha = {best[0]:.2f}')
    print('  ВЫВОД: показатель ширины ' +
          ('растёт с alpha монотонно, значит нужное значение достигается'
           ' только при alpha > 0, то есть при p, ЗАВИСЯЩЕМ от n'
           if rows[0][1] < rows[-1][1] else
           'ведёт себя не монотонно — разбирать отдельно'))


if __name__ == '__main__':
    main()

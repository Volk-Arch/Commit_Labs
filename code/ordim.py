#!/usr/bin/env python3
"""РАСТЁТ ЛИ ПОРЯДКОВАЯ РАЗМЕРНОСТЬ ЗАСЕВА С РАЗМЕРОМ.

Зачем. По `tri-doc.md` решает кинематическое ограничение, а не вес:
n ln n << n^{3/2} << n^2, то есть при ОГРАНИЧЕННОЙ порядковой
размерности энтропия падает ниже масштаба локального веса. Но это
предложение надо проверить на самом засеве, иначе оно красивое и
неверное.

В 1+1 ограничение точное, а не приближённое. Световые координаты
u = t+x, v = t-x дают
    x < y  <=>  u_x < u_y  И  v_x < v_y,
то есть причинный порядок в 1+1 РОВНО двумерен в порядковом смысле, а
засев в диамант есть буквально случайные точки в квадрате с
покоординатным порядком.

В 4d условие x < y есть dt > 0 и dt^2 > |dx|^2 - это НЕ пересечение
линейных порядков, и размерность может расти с N. Если растёт, то
«ограниченная порядковая размерность» - неверная формулировка
ограничения, и её надо заменить на «вложимость» (причинное множество
задано n точками, значит таких не больше exp(O(d n ln n)) - оценка
энтропии выживает, а формулировка меняется).

МЕРА - нижняя граница. Порядок содержит ИНДУЦИРОВАННЫЙ стандартный
пример S_k (элементы a_1..a_k, b_1..b_k с a_i < b_j при i != j, a_i
несравнимо с b_i) => размерность >= k. Ищем наибольшее k жадно по
подвыборке пар: это даёт верную нижнюю границу, чего и достаточно.

ПРЕДСКАЗАНИЕ ДО ЗАМЕРА:
  * засев 1+1 обязан упереться РОВНО в 2 (размерность точно 2, значит
    индуцированного S_3 быть не может) - это контроль;
  * засев 4d обязан расти с N, если формулировка через порядковую
    размерность неверна.
"""
import math

import numpy as np

from waveop import causal, sprinkle_11
from sectors import sprinkle_d


def best_sk(Rc, rs, npair=2500, tries=24):
    """нижняя граница размерности: наибольший найденный индуцированный S_k."""
    n = Rc.shape[0]
    inc = ~(Rc | Rc.T)
    np.fill_diagonal(inc, False)
    ii, jj = np.nonzero(np.triu(inc, 1))
    if len(ii) == 0:
        return 1
    sel = rs.choice(len(ii), size=min(npair, len(ii)), replace=False)
    A, Bv = ii[sel], jj[sel]
    m = len(A)
    # пары (a_i,b_i) и (a_j,b_j) совместимы, если a_i<b_j и a_j<b_i
    C = Rc[np.ix_(A, Bv)]
    comp = C & C.T
    np.fill_diagonal(comp, False)
    best = 1
    deg = comp.sum(axis=1)
    for t in range(tries):
        order = (np.argsort(-deg) if t == 0
                 else rs.permutation(m))
        cl = []
        mask = np.ones(m, bool)
        for v in order:
            if not mask[v]:
                continue
            cl.append(v)
            mask &= comp[v]
            mask[v] = False
            if not mask.any():
                break
        best = max(best, len(cl))
    return best


def main():
    print(__doc__)
    rs = np.random.default_rng(13579)
    print('КОНТРОЛЬ, засев 1+1 (предсказание: РОВНО 2, S_3 быть не может)')
    for n in (100, 200, 400, 800):
        v = [best_sk(causal(sprinkle_11(n, rs)), rs) for _ in range(5)]
        print(f'  N={n:>5}: наибольший найденный S_k = {max(v)}  '
              f'(по 5 засевам: {v})'
              f'  => {"ОК" if max(v) <= 2 else "ПРЕДСКАЗАНИЕ НЕВЕРНО"}',
              flush=True)

    print('\nЗАСЕВ 4d (растёт ли):')
    for n in (100, 200, 400, 800):
        v = [best_sk(sprinkle_d(n, 4, rs), rs) for _ in range(5)]
        print(f'  N={n:>5}: наибольший найденный S_k = {max(v):>3}  '
              f'(по 5 засевам: {v})', flush=True)

    print('\nдля сравнения — засев 3d:')
    for n in (200, 800):
        v = [best_sk(sprinkle_d(n, 3, rs), rs) for _ in range(5)]
        print(f'  N={n:>5}: наибольший найденный S_k = {max(v):>3}')

    print('\nЧТЕНИЕ: у 1+1 граница обязана стоять на 2 (точное тождество');
    print('через световые координаты). Если у 4d растёт — ограничение')
    print('формулируется через ВЛОЖИМОСТЬ, а не через порядковую размерность.')


if __name__ == '__main__':
    main()

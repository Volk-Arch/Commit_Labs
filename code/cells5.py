#!/usr/bin/env python3
"""БЕЗ РУЧЕК: неподвижная точка из запаса ходов. Приходит ли размерность.

УТОЧНЁННЫЙ ДИАГНОЗ (он острее вечернего). В `cells4.py` я заключил, что
`k` сохраняется. Числа говорят точнее:

    от k = 5  при g = 0.10 -> доля пар 0.0991 = 2^(1-k) при k_эфф ≈ 4.4
    от k = 8  при g = 0.10 -> доля пар 0.0149 = 2^(1-k) при k_эфф ≈ 7.07

Сдвиг ОДИН И ТОТ ЖЕ, около 0.9. То есть правило не сохраняет `k_эфф`, а
сдвигает его на постоянную величину и **не имеет неподвижной точки**.
Корреляция шкал — это и есть уменьшение `k_эфф`, и правило её создаёт; но
сила пула не зависит от состояния, поэтому точки равновесия нет.

ЧТО НУЖНО. Правило, у которого отдача ЗАВИСИТ от текущего состояния.
Тогда неподвижная точка возникает сама, и её значение — выход, а не
настройка. Такое правило здесь есть, и совсем без ручек: его даёт ЗАПАС
ХОДОВ.

ЗАПАСЫ НЕ РАВНЫ. `AG[i,x]` = число шкал, где i раньше x; `i ≺ x` ровно
при `AG = k`. Доступные ходы:

    AG = k    совпали по всем шкалам      -> РАСЦЕПИТЬ (обменять в любой)
    AG = k-1  одна шкала против           -> СЦЕПИТЬ  (обменять в ней)
    AG = 1    одна шкала за               -> СЦЕПИТЬ  (обменять в ней)
    AG = 0    все шкалы против            -> РАСЦЕПИТЬ (обменять в любой)

В случайном ящике доля пар с `AG = k` равна `2^(-k)`, а с `AG = k-1` —
`k·2^(-k)`, то есть сцепляющих ходов в `k` РАЗ БОЛЬШЕ. Правило «сделай
любой доступный ход» даёт скорости, пропорциональные запасам: система
сгущается, запасы меняются, и она встаёт там, где запасы СРАВНЯЛИСЬ.

    #{AG в {1, k-1}} = #{AG в {0, k}}

Ни одного параметра. Неподвижная точка — выход комбинаторики.

ХОД С ПЛЕЧОМ. Обмен i и x рангами в шкале s (не соседей!). Это меняет их
отношение И их отношения ко всем, кто между ними, — то самое плечо,
которого не было у обмена соседей в `cells2.py` (там один ход менял одно
отношение из N²/2, и автомат не достал до 0.1 % матрицы).

ГЛАВНЫЙ ВОПРОС, и он ставится начисто, без ручек:

    неподвижная точка ОДНА при разных k  -> РАЗМЕРНОСТЬ ПРИХОДИТ САМА
    она тянется за 2^(1-k)               -> k по-прежнему правит

КОНТРОЛИ:
  слепое — обменивать случайные пары без разбора доступности: обязано
    остаться у ящика;
  запасы печатаются отдельной колонкой: на неподвижной точке обязаны
    сравняться, иначе это не равновесие, а остановка по другой причине;
  мерило — сприклинг в четырёхмерный ромб, все величины порядковые;
  перешкалирование соблюдено тождественно (шкалы суть ранги).

  python3 cells5.py
  python3 cells5.py --ks 4 6 8 12 --sweeps 150
"""
import argparse
import time

import numpy as np

from cells3 import box, ag_of, facts, target


def supplies(AG, k):
    """Запасы ходов: сцепляющих и расцепляющих."""
    join = int(((AG == 1) | (AG == k - 1)).sum()) // 2 * 2
    brk = int(((AG == 0) | (AG == k)).sum()) // 2 * 2
    return join, brk


def swap_pair(P, AG, inv, i, x, s, k):
    """Обмен i и x рангами в шкале s. Меняет O(N) отношений."""
    ri, rx = int(P[i, s]), int(P[x, s])
    P[i, s], P[x, s] = rx, ri
    inv[s, ri], inv[s, rx] = x, i
    # меняются только строки i и x; пересчитываем их целиком, O(N k)
    for y in (i, x):
        row = (P[y, :][None, :] < P).sum(1).astype(np.int64)
        row[y] = 0
        AG[y] = row.astype(np.int16)
        AG[:, y] = (k - row).astype(np.int16)
        AG[y, y] = 0


def step(P, AG, inv, k, rs, blind=False):
    """Один ход: доступная пара и обмен в управляющей шкале."""
    N = len(P)
    for _ in range(40):
        i = int(rs.integers(0, N))
        x = int(rs.integers(0, N))
        if i == x:
            continue
        a = int(AG[i, x])
        if blind:
            swap_pair(P, AG, inv, i, x, int(rs.integers(0, k)), k)
            return 1
        if a == k or a == 0:
            swap_pair(P, AG, inv, i, x, int(rs.integers(0, k)), k)
            return 1
        if a == k - 1:
            s = int(np.flatnonzero(P[x, :] < P[i, :])[0])
            swap_pair(P, AG, inv, i, x, s, k)
            return 1
        if a == 1:
            s = int(np.flatnonzero(P[i, :] < P[x, :])[0])
            swap_pair(P, AG, inv, i, x, s, k)
            return 1
    return 0


def main():
    ap = argparse.ArgumentParser(description='Без ручек')
    ap.add_argument('--n', type=int, default=400)
    ap.add_argument('--ks', type=int, nargs='+', default=[4, 6, 8, 12])
    ap.add_argument('--sweeps', type=int, default=80)
    ap.add_argument('--every', type=int, default=20)
    ap.add_argument('--blind', action='store_true')
    a = ap.parse_args()

    t0 = time.time()
    tg = target(a.n, np.random.default_rng(31337))
    print(f'N = {a.n}. НИ ОДНОЙ РУЧКИ: правило «сделай любой доступный ход».')
    print('Неподвижная точка там, где запасы сцепить/расцепить сравнялись.')
    print('Ход — обмен пары рангами (не соседей): O(N) отношений.')
    print()
    print(f'МЕРИЛО — сприклинг в четырёхмерный ромб, N = {a.n}:')
    print(f"  доля пар {tg['f']:.4f}  разм. {tg['dim']:.2f}  "
          f"выс. {tg['hi']}  n0..n3 {tg['n0']:.4f} {tg['n1']:.4f} "
          f"{tg['n2']:.4f} {tg['n3']:.4f}  разброс {tg['cv']:.4f}")
    print()

    fin = {}
    for k in a.ks:
        print(f'=== k = {k} шкал, старт — ящик (доля пар '
              f'{2.0**(1-k):.5f}) ===')
        print(f"{'проход':>8}{'доля пар':>10}{'разм.':>7}{'выс.':>6}"
              f"{'n0':>8}{'n1':>8}{'n2':>8}{'n3':>8}{'разброс':>9}"
              f"{'сцеп.запас':>12}{'расц.запас':>12}")
        rs = np.random.default_rng(4321 + k)
        P = box(a.n, k, rs)
        AG = ag_of(P)
        inv = np.empty((k, a.n), np.int32)
        for s in range(k):
            inv[s] = np.argsort(P[:, s])

        def show(w):
            fc = facts(AG == k)
            j, b = supplies(AG, k)
            print(f"{w:>8}{fc['f']:>10.4f}{fc['dim']:>7.2f}{fc['hi']:>6}"
                  f"{fc['n0']:>8.4f}{fc['n1']:>8.4f}{fc['n2']:>8.4f}"
                  f"{fc['n3']:>8.4f}{fc['cv']:>9.4f}{j:>12}{b:>12}",
                  flush=True)
            return fc, j, b

        show(0)
        for w in range(1, a.sweeps + 1):
            for _ in range(a.n):
                step(P, AG, inv, k, rs, blind=a.blind)
            if w % a.every == 0 or w == a.sweeps:
                fc, j, b = show(w)
        fin[k] = (fc, j, b)
        print()

    print('СВОДКА: одна ли неподвижная точка при разных k')
    print(f"{'k':>4}{'ящик 2^(1-k)':>14}{'пришло':>10}{'разм.':>8}"
          f"{'n0':>9}{'выс.':>6}{'запасы сц/рц':>16}")
    for k in a.ks:
        fc, j, b = fin[k]
        print(f"{k:>4}{2.0**(1-k):>14.5f}{fc['f']:>10.4f}{fc['dim']:>8.2f}"
              f"{fc['n0']:>9.4f}{fc['hi']:>6}"
              f"{f'{j}/{b}':>16}")
    print(f"{'мерило':>4}{'':>14}{tg['f']:>10.4f}{tg['dim']:>8.2f}"
          f"{tg['n0']:>9.4f}{tg['hi']:>6}")
    print()
    print('  пришло одинаково при разных k => РАЗМЕРНОСТЬ ПРИХОДИТ САМА;')
    print('  тянется за 2^(1-k) => k по-прежнему правит')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""СВЕТОПОДОБНАЯ СВЁРТКА R_mu_nu k^mu k^nu — скаляр фокусировки.

ЗАЧЕМ ИМЕННО ОНА, а не компоненты порознь. Три причины, и все три —
физика, а не удобство:

  1. ВАКУУМНОЕ УРАВНЕНИЕ. `R_mu_nu k^mu k^nu = 0` для ВСЕХ светоподобных
     `k` равносильно `R_mu_nu = lambda g_mu_nu`, то есть вакууму с
     космологической постоянной. Это и есть левая часть вакуумного
     уравнения Эйнштейна.
  2. УСЛОВИЕ ЭНЕРГИИ. `R_mu_nu k^mu k^nu >= 0` есть условие энергии на
     светоподобном направлении — то, на чём стоят теорема фокусировки и
     теоремы о сингулярностях.
  3. ФОКУСИРОВКА. Ровно эта величина входит в уравнение Райчаудхури для
     светоподобного пучка, то есть она и есть причина, по которой
     тяготение притягивает.

КАК ОНА СВЯЗАНА С КАРАНДАШОМ. Для светового `k ∝ (1, n_hat)` в
конформных координатах перекрёстных членов нет по симметрии, поэтому

    R_mu_nu k^mu k^nu = R_etaeta + R_xx

то есть просто СУММА двух компонент, которые карандаш измеряет
(`pencil-doc.md`: `alpha ∝ R_etaeta`, `beta ∝ R_xx`).

И ГЛАВНОЕ, ПОЧЕМУ ЭТО ВЫГОДНО. В подгонке `alpha` и `beta` сильно
ПОЛОЖИТЕЛЬНО скоррелированы (корреляция около 0.9), потому что столбцы
плана почти коллинеарны. Значит их РАЗНОСТЬ определена плохо, а СУММА —
хорошо. Разность даёт скаляр `R` (там вышло 120 % промаха), сумма даёт
светоподобную свёртку (17 %). Физике нужна сумма — повезло.

ОШИБКУ НАДО БРАТЬ С КОВАРИАЦИЕЙ, а не квадратурой: при корреляции +0.9
квадратура завысила бы её вдвое. Поэтому складной нож применяется к
самой сумме, а не к слагаемым.

КОНТРОЛЬ: у линейного семейства `R_etaeta + R_xx = 3h² + h² = 4h² > 0`,
то есть условие энергии ВЫПОЛНЕНО; у квадратичного `-3c + c = -2c < 0`,
то есть НАРУШЕНО — и верно, это семейство не отвечает никакой физической
материи. Замер обязан различить знаки.

  python3 nullcon.py
"""
import math
import pickle

import numpy as np

from pencil import SCRATCH, KFAC, V2CAL, V3CAL, truth, IX2, IX3
from pjoint import plan, solve


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    with open(f'{SCRATCH}/pencil.pkl', 'rb') as fh:
        res = pickle.load(fh)
    fk = [k for k in res if k[0] == 'flat'][0]
    curved = [k for k in res if k[0] != 'flat']
    Af, sdf = res[fk]

    print('=' * 76)
    print(f"{'':>22}{'из счёта':>14}{'ст.ош':>10}{'истина':>12}"
          f"{'сигм':>7}{'точн.':>8}{'усл.энергии':>14}")
    for col, nm, vcal in ((IX2, 'X_2', V2CAL), (IX3, 'X_3', V3CAL)):
        arms = ([(res[k][0], res[k][1], True) for k in curved]
                + [(Af, sdf, False)])
        A, D, w, sd = plan(arms)
        y = A[:, col]
        full = solve(D, y, w)
        us = np.unique(sd)
        jk = np.array([solve(D, y, w, sd != u) for u in us])
        k = len(us)
        f = vcal * KFAC
        for i, key in enumerate(curved):
            s = (full[2 * i] + full[2 * i + 1]) / f
            js = (jk[:, 2 * i] + jk[:, 2 * i + 1]) / f
            e = math.sqrt((k - 1) / k * ((js - js.mean()) ** 2).sum())
            Ree, Rxx, _ = truth(*key)
            tru = Ree + Rxx
            sign = ('выполнено' if s > 0 else 'НАРУШЕНО')
            sig_t = ('выполнено' if tru > 0 else 'НАРУШЕНО')
            ok = '' if sign == sig_t else '  <-- РАСХОЖДЕНИЕ'
            print(f'{nm+"  "+key[0]+" "+str(key[1]):>22}{s:>+14.5f}{e:>10.5f}'
                  f'{tru:>+12.5f}{abs(s-tru)/max(e,1e-12):>7.1f}'
                  f'{e/abs(tru)*100:>7.0f}%{sign:>14}{ok}')
    print()
    print('ДЛЯ СРАВНЕНИЯ, из `pjoint.py`: скаляр R у квадратичного вышел')
    print('+0.0183 +- 0.0087 против истины +0.0072, то есть 120 % — в семь')
    print('раз хуже светоподобной свёртки на тех же данных. Это и есть')
    print('следствие корреляции: разность плохо, сумма хорошо.')
    print()
    print('ЧТО ЭТО ДАЁТ ПЛАНУ. Левая часть ВАКУУМНОГО уравнения Эйнштейна')
    print('измерена с 17 % уже сейчас, и условие энергии на светоподобном')
    print('различается по знаку между физическим и нефизическим семейством.')
    print('То есть величина, на которой стоят фокусировка и теоремы о')
    print('сингулярностях, в причинном множестве СЧИТАЕТСЯ.')


if __name__ == '__main__':
    main()

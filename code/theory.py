#!/usr/bin/env python3
"""ТЕОРИЯ ПОКАЗАТЕЛЕЙ: что именно мы измерили, если не тяготение.

ПОВОД — его вопрос. «А может всё-таки не ошибка? Есть теоретический
способ понять показатель по массе и по расстоянию, где у нас ведёт?»

Оказалось, есть, и он всё объясняет. Измерения были ВЕРНЫ; неверен был
мой истолк их как тяготения.

ВЫВОД. Высота события есть длина самой долгой цепи в его прошлом, а в
плоском сприклинге плотности rho она растёт линейно по собственному
времени:

    h = c4 * tau,     c4 = m4 (rho * pi/24)^(1/4)

Разрежение у нас — пространственный шар радиуса `a` ВО ВСЕ ВРЕМЕНА, то
есть трубка. В причинном ромбе это срезает всё дно: при `t < a` вся
пространственная долька (её радиус равен `t`) целиком внутри трубки.
Значит цепь обязана начинаться не у прошлого острия, а на сфере
`|y| = a` при `t = a` — это самое раннее допустимое место, потому что
при `t_y < a` допустимых точек нет вовсе.

Лучшая такая точка лежит в направлении на `x`. Тогда для события
`x = (t, r)`:

    tau_с_дыркой = sqrt((t−a)² − (r−a)²) = sqrt(tau² − 2a(t−r))
    tau_без      = sqrt(t² − r²)

и в первом порядке по `a`

    ОТНОСИТЕЛЬНЫЙ дефицит = Δtau/tau = −a(t−r)/(t²−r²) = **−a/(t+r)**

Это НЕ `1/r`, и не обязано им быть: закон геометрический, он про
срезанное дно, а не про поле.

ЧТО ОТСЮДА СЛЕДУЕТ, и всё это проверяемо:

 1. По РАССТОЯНИЮ. Усреднение `1/(t+r)` по доступному в ромбе времени
    `t ∈ [r, T−r]` даёт `ln(T/2r)/(T−2r)` — не степенной закон вовсе, а
    логарифм на линейное. Значит МЕСТНЫЙ показатель обязан ехать с
    расстоянием — ровно то, что и наблюдалось, и что я записал как
    «систематику».
 2. По МАССЕ. Для ПОЛНОЙ дырки дефицит линеен по радиусу `a`, то есть
    `M^(1/3)`. Но массу мы меняли ГЛУБИНОЙ: внутри шара удалялась доля
    `f` событий. Тогда скорость роста цепи внутри падает как
    `(1−f)^(1/4)`, путь внутри задан радиусом, и
        дефицит ∝ a [1 − (1−f)^(1/4)] ≈ a f/4  ∝ M
    то есть ЛИНЕЙНО по массе. Измерено `M^(0.890 ± 0.139)`.
 3. АДДИТИВНЫЙ дефицит (разность `⟨h/τ⟩`) несёт лишний множитель
    `(t−r)/(t·tau)`, поэтому обязан быть КРУЧЕ относительного. Измерено:
    −0.639 против −0.502.
 4. Знак отрицателен, нулевая масса даёт ровно нуль, рассыпанный
    контроль плоский — всё это тоже следует.

ЧЕГО ТЕОРИЯ НЕ ОБЪЯСНЯЕТ, и это надо назвать: она первого порядка по
`a`, не учитывает блуждание самой долгой цепи (задача последнего
прохождения, показатели КПЗ) и считает цепь начинающейся точно на
поверхности трубки. Поэтому ожидать точного совпадения нельзя, и
сравнение ведётся по тому, БЛИЖЕ ли оно к измеренному, чем
ньютоновское −1.

  python3 theory.py
"""
import math

import numpy as np

# ИЗМЕРЕННОЕ (sharpen.py, N = 60000, 16 засевов, окно задано заранее)
ELL60 = (math.pi / 24.0 / 60000) ** 0.25
MEAS = dict(rel=-0.502, rel_se=0.042, add=-0.639, add_se=0.041,
            rel_all=-0.527, add_all=-0.746)
WIN = (2.96, 4.96)      # окно в ell, как в замере
ALL = (1.46, 9.96)      # все полосы


def predict(rc, T=1.0, a_small=1e-3, kind='rel', nt=4000):
    """Предсказанный дефицит в полосе радиуса rc, с взвешиванием по событиям.

    На радиусе `rc` события ромба заполняют время `t` от `rc` до `T−rc`
    равномерно (объём дольки даёт общий множитель `rc²`, по времени он
    постоянен), поэтому усреднение по `t` — равномерное.

    kind='rel' — относительный дефицит Δtau/tau = −a/(t+r)
    kind='add' — аддитивный, то есть разность ⟨h/τ_радар⟩. Радарное время
                 есть координатное `t`, высота `h = c4*tau`, поэтому
                     Δ(h/t) = c4 * Δtau / t,  Δtau = −a(t−r)/tau
                 и общий множитель `c4*a` в показатель не входит.
    """
    out = []
    for r in rc:
        t = np.linspace(r * (1 + 1e-9), T - r, nt)
        tau = np.sqrt(np.maximum(t * t - r * r, 1e-300))
        if kind == 'rel':
            d = a_small / (t + r)
        else:
            d = a_small * (t - r) / (tau * t)
        out.append(float(np.mean(d)))
    return np.array(out)


def slope(rc, y, lo=None, hi=None, ell=1.0):
    """Наклон по полосам. ПОЙМАННАЯ ОШИБКА ЕДИНИЦ: окно задано в ell, а
    радиусы в координатах, и отбор не выбирал ни одной полосы."""
    m = np.ones(len(rc), bool)
    if lo is not None:
        m &= rc >= lo * ell
    if hi is not None:
        m &= rc <= hi * ell
    if m.sum() < 2:
        return float('nan')
    return -np.polyfit(np.log(rc[m]), np.log(y[m]), 1)[0]


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('=' * 70)
    ell = ELL60
    print(f'N = 60000, ell = {ell:.5f}, ромб T = 1')
    print()

    # те же полосы, что в замере: по 0.5 ell от 1.46 до 9.96
    rc_ell = np.arange(1.46, 10.0, 0.5)
    rc = rc_ell * ell
    pr = predict(rc, kind='rel')
    pa = predict(rc, kind='add')

    print('ПРЕДСКАЗАННЫЙ ПРОФИЛЬ и его местный показатель')
    print('(местный показатель обязан ЕХАТЬ — закон не степенной)')
    print(f"{'r/ell':>8}{'относит.':>12}{'местный':>10}"
          f"{'аддитив.':>12}{'местный':>10}")
    for i in range(len(rc)):
        lr = la = float('nan')
        if 0 < i < len(rc) - 1:
            lr = slope(rc[i-1:i+2], pr[i-1:i+2], ell=ell)
            la = slope(rc[i-1:i+2], pa[i-1:i+2], ell=ell)
        print(f'{rc_ell[i]:>8.2f}{pr[i]:>12.3e}{-lr:>10.3f}'
              f'{pa[i]:>12.3e}{-la:>10.3f}')

    print()
    print('=' * 70)
    print('СРАВНЕНИЕ С ИЗМЕРЕННЫМ')
    print(f"{'величина':>24}{'теория':>10}{'измерено':>18}"
          f"{'расхождение':>14}{'от -1':>9}")
    rows = [
        ('относит., окно 2.96-4.96', slope(rc, pr, *WIN, ell=ell),
         MEAS['rel'], MEAS['rel_se']),
        ('аддитив., окно 2.96-4.96', slope(rc, pa, *WIN, ell=ell),
         MEAS['add'], MEAS['add_se']),
        ('относит., все полосы', slope(rc, pr, *ALL, ell=ell),
         MEAS['rel_all'], None),
        ('аддитив., все полосы', slope(rc, pa, *ALL, ell=ell),
         MEAS['add_all'], None),
    ]
    for lbl, th, me, se in rows:
        if se:
            dev = abs(-th - me) / se
            print(f'{lbl:>24}{-th:>10.3f}{me:>+12.3f} ± {se:.3f}'
                  f'{dev:>11.1f} σ{abs(me+1)/se:>7.1f} σ')
        else:
            print(f'{lbl:>24}{-th:>10.3f}{me:>+12.3f}'
                  f'{abs(-th-me):>19.3f}{"":>9}')

    print()
    # где аддитивный показатель проходит через -1: это и есть разгадка
    # прежнего «ньютоновского» результата
    la = np.array([slope(rc[i-1:i+2], pa[i-1:i+2], ell=ell)
                   for i in range(1, len(rc) - 1)])
    rr = rc_ell[1:-1]
    k = int(np.argmin(np.abs(la - 1.0)))
    print(f'  АДДИТИВНЫЙ показатель проходит через −1 при '
          f'r = {rr[k]:.2f} ell')
    print('  а прежние подгонки по 8 полосам при N = 60000 покрывали')
    print('  ровно 2.5...9.5 ell и давали «−0.95...−1.04». То есть')
    print('  «ньютоновский закон» был ЭТИМ законом, усреднённым по тому')
    print('  отрезку, где он случайно проходит через −1.')
    print()
    print('ГЛАВНОЕ СРАВНЕНИЕ: кто ближе к измеренному?')
    for lbl, th, me, se in rows[:2]:
        d_th = abs(-th - me)
        d_newton = abs(-1.0 - me)
        print(f'  {lbl}: теория промахивается на {d_th:.3f}, '
              f'ньютоновское −1 — на {d_newton:.3f} '
              f'(в {d_newton/max(d_th,1e-9):.1f} раз хуже)')

    print()
    print('=' * 70)
    print('ПО МАССЕ')
    print('  полная дырка:   дефицит ∝ a ∝ M^(1/3) = M^0.333')
    print('  дырка ГЛУБИНОЙ: дефицит ∝ a[1−(1−f)^(1/4)] ∝ f ∝ M^1')
    print('  измерено (массу меняли глубиной):  M^(+0.890 ± 0.139)')
    print(f'  промах от M^1:     {abs(0.890-1.0)/0.139:.1f} σ')
    print(f'  промах от M^(1/3): {abs(0.890-1.0/3)/0.139:.1f} σ')
    print()
    print('ЗНАК И НУЛИ (тоже следуют из вывода)')
    print('  дефицит отрицателен — дно срезано, цепь короче: ДА')
    print('  при нулевой массе ровно нуль:                   ДА (замер)')
    print('  рассыпанный контроль без профиля:               ДА (76× меньше)')
    print()
    print('ЧТО ТЕОРИЯ НЕ ПОКРЫВАЕТ')
    print('  первый порядок по a; блуждание самой долгой цепи (КПЗ) не')
    print('  учтено; цепь считается начинающейся точно на поверхности')
    print('  трубки. Поэтому точного совпадения и не ожидается.')


if __name__ == '__main__':
    main()

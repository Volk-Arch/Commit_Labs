#!/usr/bin/env python3
"""ДИАГНОЗ: коэффициенты неверны или оператор утопает в шуме?

waveop.py дал на гладких функциях сотни вместо 2, -2, 4. Две возможные
причины, и их надо различить ПРЕЖДЕ чем винить коэффициенты:
  (а) веса или нормировка неверны — тогда СРЕДНЕЕ по многим засевам
      тоже будет неверным;
  (б) оператор утопает в собственном шуме на одном засеве — тогда
      среднее пойдёт к 2, -2, 4, а разброс будет огромен. Это
      предсказывает наш же утренний закон sigma(S) ~ N
      (`sigma-doc.md`), и именно поэтому Соркин вводит размазку.

Различается прямо: считается СРЕДНЕЕ и РАЗБРОС по многим засевам и
многим точкам, и смотрится, идёт ли среднее к точному ответу.
"""
import math

import numpy as np

from waveop import Bop, causal, sprinkle_11


def main():
    print(__doc__)
    rs = np.random.default_rng(2727)
    print(f"{'N':>6}{'засевов':>9}{'точек':>8}"
          f"{'<кв(τ²)>':>12}{'разброс':>11}{'ош.среднего':>13}"
          f"{'отклон. от 4':>14}")
    for n, nspr in ((300, 120), (600, 70), (1200, 30)):
        vals = []
        for _ in range(nspr):
            P = sprinkle_11(n, rs)
            rho = n / 0.5
            B = Bop(causal(P), rho)
            t, x = P[:, 0], P[:, 1]
            core = (t > 0.35) & (t < 0.65) & (np.abs(x) < 0.12)
            if core.sum() < 3:
                continue
            f = t * t - x * x
            vals.extend(((B @ f)[core]).tolist())
        v = np.array(vals)
        m, s = float(v.mean()), float(v.std())
        e = s / math.sqrt(len(v))
        print(f'{n:>6}{nspr:>9}{len(v):>8}{m:>12.2f}{s:>11.1f}'
              f'{e:>13.2f}{abs(m-4)/max(e,1e-9):>13.1f}с', flush=True)
    print('\nЧТЕНИЕ: если среднее идёт к 4, а разброс велик — причина (б),')
    print('коэффициенты верны, и нужен размазанный оператор. Если среднее')
    print('не идёт к 4 — причина (а), неверны веса или нормировка.')
    print('\nСколько точек нужно для 1 сигмы при таком разбросе:')
    print('  (разброс/4)^2 — печатается ниже по последней строке')


if __name__ == '__main__':
    main()

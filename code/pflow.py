#!/usr/bin/env python3
"""ПОТОК СВЯЗЕЙ: какой закон p(n) даёт нужный показатель ширины.

Сегодняшние выводы: правило обязано быть условием на РОСТ, а состояние
несёт граница. Значит мерить надо, как растёт граница в самом процессе
роста, и сравнивать с требуемым N^{(d-1)/d} = N^{3/4}.

Процесс: транзитивная перколяция как последовательный рост — на шаге n
новый элемент берёт каждый существующий в родители с вероятностью p(n),
прошлое есть замыкание выбранного вниз. Это шаг Райдаута–Соркина в
простейшем виде.

УЗКОЕ МЕСТО ПРОГРАММЫ, которое здесь и мерится. Архив даёт
p* ~ 1.15 N^{-3/4}, то есть p обязано ЗАВИСЕТЬ от N. А в законной
динамике постоянные связи t_k фиксированы, и перколяция (t_k = t^k)
даёт РОВНО постоянное p. Значит вопрос «бывает ли правило» сводится к
вопросу «умеет ли поток эффективного p идти как n^{-3/4}».

Здесь мерится первая половина: какой показатель ширины даёт какой
закон p(n) = c·n^{-alpha}. Постоянная c подобрана так, чтобы при n=100
среднее число родителей было одинаково — иначе сравниваются начальные
условия, а не показатели.

ПРЕДСКАЗАНИЯ до прогона:
  alpha = 0  (постоянное p): новый элемент выше почти всего, порядок
             becomes цепь — показатель ширины около 0;
  alpha = 1  (p ~ 1/n): O(1) родителей, ветвление — показатель ~1;
  между ними лежит 3/4, и ОСОБО: при alpha = 3/4, то есть при архивном
  p*, показатель обязан выйти около 3/4, если p* правда подражает
  четырёхмерию. Это независимая проверка архивного p* новым прибором.

Для сравнения: засев d=4 даёт 0.816 ± 0.017 на сходном размахе,
подходя к 3/4 сверху (`compose-doc.md`).

КОНТРОЛЬ ширины: точный счёт (Дилворт + Кёниг), сверен на цепи (1),
антицепи (N) и слоистом (размер слоя).
"""
import math
import time

import numpy as np

from width3 import width


def grow(nmax, alpha, c, rs, checks):
    Rc = np.zeros((nmax, nmax), bool)
    out, par = {}, []
    for k in range(1, nmax):
        p = min(1.0, c * k ** (-alpha))
        ch = rs.random(k) < p
        past = (ch | Rc[:k, :k][:, ch].any(axis=1)) if ch.any() else ch
        Rc[:k, k] = past
        par.append(int(ch.sum()))
        if (k + 1) in checks:
            out[k + 1] = width(Rc[:k + 1, :k + 1])
    return out, float(np.mean(par[:100])), float(np.mean(par[-100:]))


def fit(xs, ys):
    lx, ly = np.log(np.array(xs, float)), np.log(np.array(ys, float))
    A = np.vstack([lx, np.ones(len(lx))]).T
    be, *_ = np.linalg.lstsq(A, ly, rcond=None)
    r = ly - A @ be
    se = math.sqrt(float((r ** 2).sum() / max(len(lx) - 2, 1))
                   / float(((lx - lx.mean()) ** 2).sum()))
    return float(be[0]), se


def main():
    print(__doc__)
    rs = np.random.default_rng(1420708)
    checks = {125, 250, 500, 1000}
    nmax, xs = 1000, sorted(checks)
    print(f"{'alpha':>6}{'родит. 1-е':>12}{'родит. посл.':>14}"
          + ''.join(f'{f"n={x}":>8}' for x in xs) + f"{'показатель':>14}")
    rows = []
    for alpha in (0.0, 0.25, 0.5, 0.75, 1.0):
        t0 = time.time()
        c = 0.03 * 100 ** alpha
        W = {n: [] for n in checks}
        p0 = p1 = 0.0
        for _ in range(2):
            out, a0, a1 = grow(nmax, alpha, c, rs, checks)
            for n in checks:
                W[n].append(out[n])
            p0, p1 = a0, a1
        ys = [float(np.mean(W[n])) for n in xs]
        a, se = fit(xs, ys)
        rows.append((alpha, a, se))
        print(f'{alpha:>6.2f}{p0:>12.2f}{p1:>14.2f}'
              + ''.join(f'{y:>8.1f}' for y in ys)
              + f'{a:>9.4f}±{se:<4.3f}  ({time.time()-t0:.0f}с)',
              flush=True)

    print('\nСРАВНЕНИЕ')
    print('  требуется для d=4:            0.750')
    print('  засев d=4 (замер):            0.816 ± 0.017')
    for alpha, a, se in rows:
        d = abs(a - 0.75) / max(se, 1e-9)
        print(f'  p ~ n^-{alpha:.2f}:  показатель {a:.4f} ± {se:.3f}, '
              f'от 3/4 на {d:>5.1f} сигм'
              + ('   <-- ближе всех' if d < 2.5 else ''))
    mono = all(rows[i][1] <= rows[i + 1][1] + 0.05
               for i in range(len(rows) - 1))
    print(f'\n  показатель растёт с alpha монотонно: {mono}')
    print('  ВЫВОД: нужное значение 3/4 достигается '
          + ('только при alpha > 0, то есть при p, ЗАВИСЯЩЕМ от n — '
             'а это и есть то, чего фиксированные связи Райдаута–Соркина '
             'не дают напрямую'
             if rows[0][1] < 0.6 else
             'уже при постоянном p — тогда узкого места нет'))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ДИНАМИКА: предпочитает ли действие профиль вокруг вещества.

ЗАЧЕМ ИМЕННО ЭТО. `game-doc.md` кончился выводом, а не неудачей: сприклинг
задаётся рукой как ПЛОСКИЙ, и вырезание шара не заставляет окружающее
искривиться, потому что уравнения поля в модели нет. Значит любая локальная
величина у разрежения обязана дать нуль (замкнутый ящик это подтвердил:
−0.0001 при шуме 0.005, и тот же нуль при шестикратной массе). Тяготение
может появиться только там, где порядок ОТВЕЧАЕТ на вещество сам.

Действие Бенинкасы–Доукера у проекта есть и проверено как локальное поле
(`bdfield.py`: носитель ровно 2.5 ell, ⟨b⟩ = −0.201 ± 0.439 в плоской
глубине), но ни разу не использовалось как ПРИНЦИП, порождающий
конфигурации.

ПОСТАНОВКА. Полный Метрополис по действию при нужном размере не
укладывается в разумное время, поэтому берётся ВАРИАЦИОННАЯ постановка —
она и острее, и дешевле. Не «куда придёт ансамбль», а «что действие
предпочитает»:

    число событий ФИКСИРОВАНО (B сильно зависит от N, иначе сравнивать
    нечего); вокруг разрежения навязывается радиальный профиль плотности

        rho(r) ∝ exp(A * rad / r),     r > rad

    и для набора A считается ⟨B⟩ по ансамблю.

    минимум при A = 0      =>  плоское окружение предпочтительно,
                               тяготения из порядка НЕТ
    минимум при A ≠ 0      =>  вещество само наводит профиль, то есть
                               это и есть искомая динамика

ПОЧЕМУ АНСАМБЛЬ ОБЯЗАТЕЛЕН. `cancel-doc.md`: сокращение в действии живёт
в знаковом среднем (|Δb| = 18.4 при ⟨Δb⟩ = 0.5, то есть в 36 раз). Один
мир не покажет ничего, и это уже проверено на опыте.

КОНТРОЛИ, поставленные до замера:
  1. СИЛА ЗАМЕРА печатается ДО вывода: разброс ⟨B⟩ по засевам даёт то,
     какую разницу замер вообще способен увидеть. Нуль без силы — не
     вывод (правило №3);
  2. БЕЗ ДЫРКИ — базовая линия для РАЗНОСТИ, а не плоская кривая.
     Поправка к первоначальной формулировке: профиль там навязывается
     тот же самый, поэтому B вправе меняться, и требовать плоскости
     неверно. Смысл контроля в том, что ход действия от самой
     деформации одинаков с дыркой и без, значит в разности он
     сокращается, и остаётся только вклад ВЕЩЕСТВА;
  3. A = 0 — общая нулевая точка обоих наборов;
  4. краевые члены в B велики, поэтому b_x суммируется только по
     глубине по времени, а не по всему слою;
  5. знак A: профиль наружу и внутрь берутся оба, минимум ищется, а не
     предполагается.

  python3 dyn.py --quick
  python3 dyn.py --n 5000 --seeds 10
"""
import argparse
import math
import time

import numpy as np


def base_world(N, L, T, rad, rs, hole=True):
    """Один РОВНЫЙ мир; версия с дыркой — тот же мир без внутренних.

    ПОЙМАННАЯ НЕЭФФЕКТИВНОСТЬ. Сначала мир с дыркой строился отдельным
    отбором (события внутри шара отбрасывались при генерации), и потому
    выходила ДРУГАЯ реализация. Снаружи шара события у двух миров не
    совпадали, разность «с дыркой минус без дырки» складывала два
    независимых шума, и выходила шумнее каждой из частей: 298 против
    206 и 249.

    Починка — как в `bigfall.py`: один мир, и версия с дыркой получается
    УДАЛЕНИЕМ внутренних событий. Тогда снаружи стоят буквально те же
    события, и разность спарена на уровне событий, а не только засевов.
    """
    hc = np.array([L / 2] * 3)
    X = np.empty((N, 4))
    X[:, 0] = rs.uniform(0, T, N)
    X[:, 1:] = rs.uniform(0, L, (N, 3))
    if hole:
        d = X[:, 1:] - hc
        d -= L * np.round(d / L)
        X = X[np.linalg.norm(d, axis=1) >= rad]
    return X[np.argsort(X[:, 0])]


def warp(X, L, rad, A, rmax):
    """Деформация РАДИУСА, реализующая профиль rho ∝ exp(A*rad/r).

    ОБЩИЕ СЛУЧАЙНЫЕ ЧИСЛА. Независимые конфигурации для каждого A здесь
    безнадёжны: быстрая проверка дала ⟨B⟩ = +2406 ± 3312, то есть замер
    видел бы только разницу свыше 9937 при искомых 1000...5000. Это та
    самая известная стена действия (σ(B) ~ N^+0.357 против сигнала
    N^-0.500).

    Приём: брать ОДИН мир и деформировать его. Отображение радиуса
    детерминировано, поэтому конфигурации при разных A отличаются малыми
    сдвигами ТЕХ ЖЕ событий, и в разности B(A) − B(0) основная часть
    флуктуации сокращается.

    Отображение g строится из сохранения числа событий внутри радиуса:

        ∫_rad^g rho_A(u) u² du  =  ∫_rad^r rho_0(u) u² du

    причём rho_A нормирована так, чтобы на [rad, rmax] полное число
    совпадало — тогда g есть биекция [rad, rmax] -> [rad, rmax] и ни
    одно событие не теряется. События за rmax не трогаются (там мешает
    кубическая форма ящика).
    """
    hc = np.array([L / 2] * 3)
    d = X[:, 1:] - hc
    d -= L * np.round(d / L)
    r = np.linalg.norm(d, axis=1)
    if A == 0.0:
        return X.copy()
    # ПОЙМАННАЯ ОШИБКА, ВТОРОЙ РАЗ ЗА ДЕНЬ. Профиль был
    #     rho = rho0 (1 + A*rad/r)
    # и при A < -1 уходил в минус: прогон падал, как раньше падала
    # конформная плотность в `curved.py`. Там я тогда ограничил амплитуду
    # РУКОЙ, после того как увидел падение, — и это была подгонка.
    #
    # Правильная починка не предел, а параметризация, которая НЕ МОЖЕТ
    # нарушить положительность:
    #     rho = rho0 * exp(A*rad/r)
    # положительна при любом A и совпадает с прежней при малых A. Тот же
    # приём, что замена линеаризации на точное a^4.
    u = np.linspace(rad, rmax, 4000)
    w = np.exp(A * rad / u)
    # нормировка: равное полное число на [rad, rmax]
    num = np.trapezoid(w * u * u, u)
    den = np.trapezoid(u * u, u)
    w = w * den / num
    # накопленные числа и обратное отображение
    cum_t = np.concatenate([[0.0], np.cumsum(
        0.5 * (w[1:] * u[1:] ** 2 + w[:-1] * u[:-1] ** 2) * np.diff(u))])
    cum_0 = (u ** 3 - rad ** 3) / 3.0
    inside = (r >= rad) & (r <= rmax)
    tgt = np.interp(r[inside], u, cum_0)
    g = np.interp(tgt, cum_t, u)
    Y = X.copy()
    scale = np.ones(len(X))
    scale[inside] = g / np.maximum(r[inside], 1e-12)
    Y[:, 1:] = hc + d * scale[:, None]
    Y[:, 1:] = np.mod(Y[:, 1:], L)
    return Y[np.argsort(Y[:, 0])]


def relation(X, L):
    """Матрица порядка с замыканием по пространству."""
    t = X[:, 0]
    S = X[:, 1:]
    dt = t[None, :] - t[:, None]            # dt[i,j] = t_j - t_i
    d = S[None, :, :] - S[:, None, :]
    d -= L * np.round(d / L)
    d2 = (d * d).sum(2)
    return (dt > 0) & (dt * dt > d2)


def bd_density_smeared(R, eps, chunk=512):
    """Сглаженное действие Доукера–Глейзера вместо резкого.

    ЧТО ЭТО СНИМАЕТ. Шум в резком действии идёт от коэффициентов
    (1, −9, 16, −8): большие знакочередующиеся числа при больших
    величинах, то есть сокращение почти полное, а остаток — разность
    близких величин. Весь смысл сглаживания (Доукер–Глейзер) в том, чтобы
    заменить резкие коэффициенты плавно спадающим весом: слагаемых
    больше, но каждое меньше, и сокращение мягче.

    Вес берётся из `weight.py` (`w_of`), где он проверен пределом
    eps -> 1: там он обязан дать ровно C(n) резкого действия, и даёт.
    """
    from weight import w_of
    C = (R.astype(np.float32) @ R.astype(np.float32)).astype(np.int32)
    n = len(R)
    out = np.full(n, eps, np.float64)
    for a in range(0, n, chunk):
        b = min(a + chunk, n)
        w = w_of(C[:, a:b], eps) * R[:, a:b]
        out[a:b] += w.sum(0)
        del w
    del C
    return out


def bd_density(R):
    """b_x = 1 − n₀ + 9n₁ − 16n₂ + 8n₃, где n_m = #{y ≺ x : |I(y,x)| = m}."""
    C = (R.astype(np.float32) @ R.astype(np.float32)).astype(np.int32)
    n = len(R)
    b = np.ones(n, np.float64)
    coef = (-1.0, 9.0, -16.0, 8.0)
    for m, cf in enumerate(coef):
        cnt = (R & (C == m)).sum(0)        # по y ≺ x, для каждого x
        b += cf * cnt
    return b


def main():
    ap = argparse.ArgumentParser(description='Предпочитает ли действие профиль')
    ap.add_argument('--n', type=int, default=4200)
    ap.add_argument('--lell', type=float, default=8.0)
    ap.add_argument('--tell', type=float, default=9.0)
    ap.add_argument('--radell', type=float, default=2.0)
    ap.add_argument('--seeds', type=int, default=10)
    ap.add_argument('--deep', type=float, default=2.6,
                    help='отступ по времени: краевые члены в B велики')
    ap.add_argument('--eps', type=float, default=1.0,
                    help='сглаживание Доукера–Глейзера; 1.0 = резкое БД')
    ap.add_argument('--quick', action='store_true')
    a = ap.parse_args()

    t0 = time.time()
    # единицы ell: плотность 1 => N = L^3 * T
    L, T = a.lell, a.tell
    ell = 1.0
    N = a.n
    rad = a.radell
    # ДЁШЕВЛЕ ПО-ДРУГОМУ, а не больше засевов. Отношение сигнала к шуму
    # идёт как sqrt(затронутых событий) * A: число затронутых задано
    # ящиком в единицах ell и не растёт без роста стоимости как N³, а
    # амплитуда свободна. Значит давить надо АМПЛИТУДОЙ.
    #
    # И мерить не отдельные точки, а НАКЛОН В НУЛЕ: подгонка
    #     ⟨ΔB⟩ = alpha*A + beta*A²
    # по всем A сразу. Вопрос «наводит ли вещество профиль» есть вопрос
    # «отличен ли alpha от нуля»: при alpha ≠ 0 плоское окружение не
    # стационарная точка действия.
    #
    # ПОПРАВКА К СЕБЕ: сначала я написал, что без дырки alpha обязан быть
    # нулём «по симметрии». Это неверно: профиль exp(A*rad/r) при
    # A -> -A не переходит в своё зеркало, и центр там есть даже без
    # дырки, а действие отзывается на градиент плотности. Поэтому без
    # дырки alpha ВПРАВЕ быть ненулевым, и контроль служит базовой
    # линией для разности, а не нулём.
    As = ([0.0, 0.6, 1.2] if a.quick else
          [-1.2, -0.8, -0.4, 0.0, 0.4, 0.8, 1.2])
    seeds = 3 if a.quick else a.seeds
    print('ВАРИАЦИОННЫЙ вопрос: что ПРЕДПОЧИТАЕТ действие, а не куда')
    print('придёт ансамбль. Число событий фиксировано, профиль')
    print('перераспределяет: rho(r) ∝ 1 + A*rad/r при r > rad.')
    print()
    print(f'ящик {L} x {T} ell, N = {N} (плотность {N/(L**3*T):.3f}), '
          f'дырка {rad} ell')
    print(f'b_x суммируется по глубине: t в [{a.deep}, {T-a.deep}] ell')
    print(f'засевов {seeds}, значений A: {As}')
    print(f'действие: {"РЕЗКОЕ БД" if a.eps >= 1 else f"СГЛАЖЕННОЕ, eps = {a.eps}"}')
    print()

    rmax = L / 2.0
    def act(X):
        R = relation(X, L)
        b = bd_density(R) if a.eps >= 1.0 else bd_density_smeared(R, a.eps)
        del R
        t = X[:, 0]
        deep = (t >= a.deep) & (t <= T - a.deep)
        v = float(b[deep].sum())
        del b
        return v

    def measure_paired(hole):
        """Для каждого засева: один мир, затем его деформации.

        Возвращает (засевы x значения A) действий — ПАРНО, то есть в
        строке стоят деформации одного и того же мира.
        """
        M = np.empty((seeds, len(As)))
        for s_ in range(seeds):
            rs = np.random.default_rng(55000 + 263 * s_)
            X0 = base_world(N, L, T, rad, rs, hole=hole)
            for j, A in enumerate(As):
                M[s_, j] = act(warp(X0, L, rad, A, rmax))
            del X0
            if s_ == 0 or (s_ + 1) % 5 == 0:
                print(f'    засев {s_} ({time.time()-t0:.0f} с)', flush=True)
        return M

    i0 = As.index(0.0)
    print('С ДЫРКОЙ (парно: один мир, затем его деформации)')
    MH = measure_paired(True)
    print('БЕЗ ДЫРКИ (контроль №2: базовая линия для разности)')
    MN = measure_paired(False)

    print()
    print('КОНТРОЛЬ №1 (сила замера, до всяких выводов)')
    print(f'  НЕпарно: разброс B по засеву {MH[:, i0].std(ddof=1):.0f}, '
          f'ст.ош {MH[:, i0].std(ddof=1)/math.sqrt(seeds):.0f}')
    jn = max(range(len(As)), key=lambda j: abs(As[j]))   # не A=0
    dpar = MH[:, jn] - MH[:, i0]
    print(f'  ПАРНО:   разброс B(A)−B(0) {dpar.std(ddof=1):.0f}, '
          f'ст.ош {dpar.std(ddof=1)/math.sqrt(seeds):.0f}')
    gain = MH[:, i0].std(ddof=1) / max(dpar.std(ddof=1), 1e-12)
    print(f'  парность снизила разброс в {gain:.1f} раз')
    print()

    for lbl, M in (('С ДЫРКОЙ', MH), ('БЕЗ ДЫРКИ (базовая линия)', MN)):
        print(f'{lbl}: ⟨B(A) − B(0)⟩ парно')
        print(f"{'A':>7}{'разность':>12}{'ст.ош':>9}{'сигм':>7}")
        for j, A in enumerate(As):
            d = M[:, j] - M[:, i0]
            se = d.std(ddof=1) / math.sqrt(seeds)
            print(f'{A:>7.2f}{d.mean():>+12.1f}{se:>9.1f}'
                  f'{abs(d.mean())/max(se,1e-12):>7.1f}')
        print()

    DD = (MH - MH[:, i0][:, None]) - (MN - MN[:, i0][:, None])
    print('РАЗНОСТЬ (с дыркой) − (без дырки), парно по засеву:')
    print('общий ход от самой деформации снят, остаётся то, что идёт')
    print('ИМЕННО от вещества')
    print(f"{'A':>7}{'разность':>12}{'ст.ош':>9}{'сигм':>7}")
    mu, ses = [], []
    for j, A in enumerate(As):
        m_ = DD[:, j].mean()
        se = DD[:, j].std(ddof=1) / math.sqrt(seeds)
        mu.append(m_); ses.append(se)
        print(f'{A:>7.2f}{m_:>+12.1f}{se:>9.1f}'
              f'{abs(m_)/max(se,1e-12):>7.1f}')
    mu = np.array(mu); ses = np.array(ses)

    # НАКЛОН В НУЛЕ — главный ответ. Ошибка складным ножом ПО ЗАСЕВАМ
    # (засевы независимы, точки по A — нет, они из одного мира).
    print('НАКЛОН В НУЛЕ: ⟨ΔB⟩ = alpha*A + beta*A²')
    print('alpha ≠ 0  =>  плоское окружение НЕ стационарно => динамика')
    AA = np.array(As)
    def fit_alpha(M):
        c = np.polyfit(AA, M.mean(0), 2)
        return c[1], c[0]
    for lbl, M in (('с дыркой', MH - MH[:, i0][:, None]),
                   ('без дырки (базовая линия, не нуль)',
                    MN - MN[:, i0][:, None]),
                   ('РАЗНОСТЬ', DD)):
        al, be = fit_alpha(M)
        jk = []
        for s_ in range(seeds):
            keep = [i for i in range(seeds) if i != s_]
            jk.append(fit_alpha(M[keep])[0])
        jk = np.array(jk)
        se = math.sqrt((seeds - 1) / seeds * ((jk - jk.mean()) ** 2).sum())
        print(f'  {lbl:<42} alpha = {al:+9.1f} +- {se:6.1f} '
              f'({abs(al)/max(se,1e-12):.1f} сигм), beta = {be:+.0f}')
    print()
    imin = int(np.argmin(mu))
    print(f'  минимум при A = {As[imin]:+.2f}')
    # ПОЙМАННАЯ ОШИБКА ЛОГИКИ ВЕРДИКТА. Сначала здесь стояло: если
    # argmin пришёлся на A = 0, объявить «плоское предпочтительно». Но
    # при A = 0 разность ТОЖДЕСТВЕННО нулевая, поэтому argmin попадает
    # туда всегда, когда прочие точки — шум, и вердикт выносился на
    # пустом месте. Это та же болезнь, что «нуль без силы».
    #
    # Правильно: объявлять предпочтение плоского только если прочие
    # точки ЗНАЧИМО выше нуля. Иначе — не решено, и печатается, чего
    # не хватает.
    # ВЕРДИКТ ПО НАКЛОНУ, а не по лучшей точке. Третья за сутки починка
    # этой логики, и по той же причине: прежние версии объявляли ответ по
    # одной точке. При шести ненулевых A случайный выход за 3 сигмы
    # вероятен около 1.6 %, то есть «лучшая 3.4 сигмы» есть по существу
    # ~2.4. Сводная величина — alpha по ВСЕМ точкам, и порог для
    # отдельной точки берётся с поправкой на число сравнений.
    al_d, _ = fit_alpha(DD)
    jk = []
    for s_ in range(seeds):
        keep = [i for i in range(seeds) if i != s_]
        jk.append(fit_alpha(DD[keep])[0])
    jk = np.array(jk)
    se_d = math.sqrt((seeds - 1) / seeds * ((jk - jk.mean()) ** 2).sum())
    sig_al = abs(al_d) / max(se_d, 1e-12)
    m = len(As) - 1
    thr = 3.0 + math.log(max(m, 1)) ** 0.5      # поправка на m сравнений
    best = max(abs(mu[j]) / max(ses[j], 1e-12)
               for j in range(len(As)) if j != i0)
    print(f'  НАКЛОН по всем точкам: alpha = {al_d:+.1f} +- {se_d:.1f} '
          f'({sig_al:.1f} сигм)')
    print(f'  лучшая отдельная точка: {best:.1f} сигм, порог с поправкой '
          f'на {m} сравнений: {thr:.1f}')

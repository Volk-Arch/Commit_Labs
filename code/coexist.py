#!/usr/bin/env python3
"""СОСУЩЕСТВОВАНИЕ: не враг против засева, а две фазы.

Мысль, которую надо проверить. Огрубление отображает слоистого врага в
слоистого врага с теми же k, q (`coarse.py`) - он НЕПОДВИЖНАЯ ТОЧКА, как
и засев. Две неподвижные точки, а не правая и неправая. Соперничество
тогда есть F = E - TS: враг берёт энтропией (таких порядков несравнимо
больше), засев - действием (у него есть геометрия). Место равновесия -
переход, и он измерен: пик теплоёмкости на beta = 0.04.

Если в точке перехода фазы СОСУЩЕСТВУЮТ, ансамбль есть СМЕСЬ двух, и
его СРЕДНЕЕ не лежит ни в одной области - ровно как намерено
(`crit-geom-doc.md`: хи2 мимо и геометрии, и врага). Среднее воды со
льдом не есть ни вода, ни лёд. Но ДОЛЯ это различает: часть конфигураций
может быть настоящей геометрией, и среднее такого не видит по
построению.

Проверка в два шага, второй только если прошёл первый:
  1. РАЗДЕЛЯЕТ ли вектор отношений обилий при малом N, где работает
     критический сэмплер (N=24)? При N=1000 разделял нацело (frac.py),
     но там конфигурации богаче.
  2. Если да - какая ДОЛЯ критических конфигураций попадает в область
     засева.

КОНТРОЛИ: вторая партия засевов обязана попадать (порог - 95-й
процентиль по первой партии); слоистый враг обязан не попадать, иначе
при N=24 величина не разделяет и шаг 2 бессмыслен.
"""
import math

import numpy as np

from sectors import sprinkle_d
from lkdeg import layered
from critmix import ladder, NEW
from critgeom3 import box

N = 24
MS = (1, 2, 3, 4)


def prof(Rc):
    F = Rc.astype(np.float32)
    Iv = np.rint(F @ F).astype(np.int32)
    n0 = float((Rc & (Iv == 0)).sum())
    return np.array([float((Rc & (Iv == m)).sum()) / max(n0, 1.0)
                     for m in MS])


def main():
    print(__doc__)
    rs = np.random.default_rng(5196152)

    A = np.array([prof(box(N, 3, 1.56, rs)) for _ in range(120)])
    mu, sd = A.mean(axis=0), A.std(axis=0, ddof=1)
    print(f'область засева (d=3, a=1.56 — лучшая подгонка фазы), '
          f'N={N}, 120 конфигураций')
    print('  центр:   ' + ' '.join(f'{v:.4f}' for v in mu))
    print('  разброс: ' + ' '.join(f'{v:.4f}' for v in sd))

    def chi(X):
        return (((X - mu) / sd) ** 2).sum(axis=1)

    thr = float(np.percentile(chi(A), 95))
    print(f'  порог: хи2 = {thr:.1f}')

    B = np.array([prof(box(N, 3, 1.56, rs)) for _ in range(80)])
    nb = int((chi(B) <= thr).sum())
    print(f'\nКОНТРОЛЬ 1, вторая партия засевов: {nb}/80 '
          f'=> {"ОК" if nb >= 60 else "СБОЙ"}')

    print('КОНТРОЛЬ 2, слоистый враг (обязан НЕ попадать):')
    anyin = []
    for k, dl in ((3, 1.0), (4, 2.0), (6, 2.0), (8, 3.0)):
        q = min(dl * k / N, 0.95)
        E = np.array([prof(layered(N, k, q, rs)) for _ in range(60)])
        fr = int((chi(E) <= thr).sum())
        anyin.append(fr / 60)
        print(f'  k={k} delta={dl}: {fr:>2}/60   '
              f'медиана хи2 = {np.median(chi(E)):>8.1f}')
    sep = max(anyin) < 0.25
    print(f'  => {"РАЗДЕЛЯЕТ" if sep else "НЕ РАЗДЕЛЯЕТ при N=24"}')
    if not sep:
        print('\nшаг 2 не проводится: при N=24 величина не различает,')
        print('и доля критических конфигураций ничего бы не значила.')
        return

    print('\nШАГ 2: доля КРИТИЧЕСКИХ конфигураций в области засева')
    k4 = NEW.index(0.04)
    for sd_ in (9001, 9002):
        rsx = np.random.default_rng(sd_)
        recs = ladder(N, NEW, 700, rsx, every=6)
        print(f'  (зерно {sd_}: обмены мин {recs[1].min():.2f})')
    print('  — сбор конфигураций требует отдельного прохода, см. ниже')


if __name__ == '__main__':
    main()

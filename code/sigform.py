#!/usr/bin/env python3
"""ФОРМА вместо показателя: sigma(S) против числа вкладывающих пар.

Три прогона дали показатель sigma(S) = 1.0485 ± 0.0215, 0.8953 ± 0.0283,
0.9474 ± 0.0291 — между собой это 4.4 сигмы при заявленных ошибках.
Значит показатель зависит от окна по N: профиль искривлён, и одного
показателя там нет. Сегодняшний урок говорит проверять ФОРМУ.

Форма. В действие вкладывают только пары с m <= 3 (при m >= 4 вес ноль),
их число P = N0+N1+N2+N3. Если разброс есть дробовой шум по ним,

    sigma(S) = A * sqrt(P),    A постоянная

Это ОДИН параметр на пять точек, и он проверяется не подгонкой
показателя, а постоянством A.

ПРЕДСКАЗАНИЕ до прогона. Асимптотически P ~ N^{1.5}, значит видимый
показатель sigma обязан стремиться к 0.75 — к моему исходному прогнозу
лестницы. А замеренный сейчас P растёт как N^{1.66}, что даёт видимый
показатель 0.83, и наблюдаемые 0.89-1.05 должны лежать ВЫШЕ 0.75 именно
потому, что пары ещё в переходной области. То есть прогноз лестницы не
опровергнут, а просто не достигнут при N <= 3200.

Проверяемое следствие: половина МЕСТНОГО показателя P должна совпадать
с местным показателем sigma на том же шаге по N. Это сравнение двух
независимо замеренных величин без свободных параметров.

КОНТРОЛЬ. Нуль-форма: если вместо P взять полное число пар N(N-1)/2,
A обязана поехать вниз как N^{-0.17}, потому что полное число пар растёт
как N^2, а не как N^{1.66}. Если A постоянна и для P, и для полного
числа пар, значит проверка ничего не различает.
"""
import math

import numpy as np

from qcarrier import sprinkle4
from sigexp import counts4, K4


def run(n, k, rs):
    rows = [counts4(sprinkle4(n, rs, 1.0)) for _ in range(k)]
    A = np.array(rows, dtype=float)
    S = K4 * (A[:, 0] - A[:, 1] + 9 * A[:, 2] - 16 * A[:, 3]
              + 8 * A[:, 4])
    P = A[:, 1:5].sum(axis=1)
    return float(S.std(ddof=1)), float(P.mean()), k


def main():
    print(__doc__)
    rs = np.random.default_rng(141421)
    plan = [(200, 300), (400, 240), (800, 160), (1600, 100), (3200, 48)]
    Ns, sd, Pm, ks = [], [], [], []
    print(f"{'N':>6}{'засевов':>9}{'sigma(S)':>10}{'<P>':>10}"
          f"{'A=sigma/sqrt(P)':>17}{'A_полн':>9}")
    for n, k in plan:
        s, p, kk = run(n, k, rs)
        Ns.append(n); sd.append(s); Pm.append(p); ks.append(kk)
        full = n * (n - 1) / 2
        print(f'{n:>6}{k:>9}{s:>10.0f}{p:>10.0f}'
              f'{s/math.sqrt(p):>17.2f}{s/math.sqrt(full):>9.2f}',
              flush=True)
    Ns = np.array(Ns, float); sd = np.array(sd); Pm = np.array(Pm)
    ks = np.array(ks)
    A = sd / np.sqrt(Pm)
    Af = sd / np.sqrt(Ns * (Ns - 1) / 2)
    err = 1.0 / np.sqrt(2 * (ks - 1))

    print('\nФОРМА: постоянна ли A')
    for nm, y, pred in (('A = sigma/sqrt(P)', A, 0.0),
                        ('A_полн (нуль-форма)', Af, -0.17)):
        p = np.polyfit(np.log(Ns), np.log(y), 1)
        drift = (y.max() / y.min() - 1) * 100
        print(f'  {nm:>22}: дрейф {drift:>5.1f}% по 16-кратному N, '
              f'показатель {p[0]:+.3f} (ждём {pred:+.2f})')

    print('\nСЛЕДСТВИЕ без параметров: половина местного показателя P '
          'против местного показателя sigma')
    print(f"{'шаг':>14}{'пок. P':>9}{'половина':>10}{'пок. sigma':>12}"
          f"{'расхожд.':>10}")
    for i in range(len(Ns) - 1):
        lr = math.log(Ns[i + 1] / Ns[i])
        ep = math.log(Pm[i + 1] / Pm[i]) / lr
        es = math.log(sd[i + 1] / sd[i]) / lr
        es_err = math.sqrt(err[i] ** 2 + err[i + 1] ** 2) / lr
        print(f'  {int(Ns[i]):>5}->{int(Ns[i+1]):<6}{ep:>9.3f}'
              f'{ep/2:>10.3f}{es:>7.3f}±{es_err:<4.2f}'
              f'{abs(es-ep/2)/es_err:>8.1f}с')

    print('\nИТОГ формы: предсказание sigma = A*sqrt(P) при A из '
          'первой точки')
    A0 = A[0]
    print(f"{'N':>6}{'предсказано':>13}{'замерено':>11}{'отношение':>11}")
    for i in range(len(Ns)):
        pr = A0 * math.sqrt(Pm[i])
        print(f'  {int(Ns[i]):>4}{pr:>13.0f}{sd[i]:>11.0f}'
              f'{sd[i]/pr:>11.3f}')


if __name__ == '__main__':
    main()

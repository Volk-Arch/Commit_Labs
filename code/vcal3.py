#!/usr/bin/env python3
"""ПРАВИЛЬНЫЕ ПРОФИЛИ A(v), B(v) — замена неверного плана.

Точный интеграл (`vcal2.py`) показал, что допущение конвейера
`X_2 = V2CAL * R_uu * tau^2` НЕВЕРНО: на экспоненциальном плече, где
`R_etaeta = 0` точно, конвейер обязан дать нуль, а точный интеграл даёт
+0.00246 +- 0.00026 — промах 9.5 сигм. Моя формула через моменты ромба
попадает (+0.00240).

В переводе на компоненты при ПОКОЕ выходит

    X_2/tau^2 = -0.0253 R_etaeta + 0.0192 R_xx

то есть в покоящемся интервале сидят ОБЕ компоненты сравнимыми
коэффициентами, а конвейер считал, что видна только `R_etaeta`.
Линейное плечо к этой ошибке слепо (смесь даёт -0.0567 против модельных
-0.0603, разница 6% — внутри калибровочной погрешности 14%), и я
валидировал модель именно на нём.

ЗДЕСЬ считаются правильные профили. Для интервала с быстротой `v`
нужны моменты ГЛОБАЛЬНОГО `eta`, а не собственного времени. Связь
скалярная и точная: точка с координатами покоя `(s, w)` имеет

    delta_eta = [ (s - tau/2) + v w_1 ] / sqrt(1 - v^2)

поэтому всё считается в системе покоя интервала, без бустов.

    S(v) = <delta^2> по ромбу
    Q(v) = <delta_x^2 + delta_y^2> по упорядоченным парам
    P(v) = <delta_x delta_y> по упорядоченным парам

    X_2/tau^2 = A(v) R_etaeta + B(v) R_xx,
    A = 8P/3 + (2/3)(Q - 2S),   B = 8P + 4(Q - 2S)

(вывод: `u = (R_xx - R_etaeta/3)/2`, `vv = (R_xx + R_etaeta/3)/2`
подставлены в `16 vv P + (2u + 6vv)(Q - 2S)`.)

КОНТРОЛЬ при v = 0: `A` обязано выйти -0.02532, `B` +0.01922 — числа,
полученные независимо в `vcal.py`.

РЕШАЮЩЕЕ: отношение `B/A` как функция `v`. Конвейер предполагал, что
вклад идёт как `(R_etaeta + R_xx v^2)/(1-v^2)`, то есть `B/A = v^2`,
растущее от нуля. Если истинное `B/A` ведёт себя иначе — план был
вырожден НЕ потому, что геометрия не пускает, а потому, что столбцы
были неверны.

  python3 vcal3.py
"""
import math

import numpy as np

from vcal import ball

NB = 6


def moments(v, tau, n, rs, d=4):
    """S, Q, P для ромба с быстротой v, в глобальном eta."""
    gam = 1.0 / math.sqrt(1.0 - v * v)

    def diam(n_, T):
        z = rs.random(n_)
        half = z < 0.5
        y = np.where(half, 2 * z, 2 * (1 - z)) ** (1.0 / d)
        s = np.where(half, 0.5 * y, 1.0 - 0.5 * y) * T
        R = np.minimum(s, T - s)
        return s, ball(rs, n_, d - 1, R)

    sx, wx = diam(n, tau)
    dex = ((sx - 0.5 * tau) + v * wx[:, 0]) * gam
    # ромб I(x,q), q = (tau, 0): в системе покоя это ромб между x и q
    dt = tau - sx
    r2 = np.einsum('ij,ij->i', wx, wx)
    t2 = dt * dt - r2
    ok = t2 > 0
    sx_, wx_, dex_, dt_ = sx[ok], wx[ok], dex[ok], dt[ok]
    t2 = t2[ok]
    taux = np.sqrt(t2)
    m = len(sx_)
    # ось I(x,q) имеет быстроту относительно системы покоя: направление
    # (dt, -wx). Точку берём в собственной системе под-ромба и
    # пересчитываем в координаты покоя ГЛОБАЛЬНОГО интервала.
    sy0, wy0 = diam(m, 1.0)
    nvec = np.column_stack([dt_, -wx_[:, 0], -wx_[:, 1], -wx_[:, 2]])
    e0 = nvec / taux[:, None]
    B = np.zeros((m, d - 1, d))
    seed = np.zeros((m, d - 1, d))
    for i in range(d - 1):
        seed[:, i, i + 1] = 1.0

    def mk(a, b):
        return a[:, 0] * b[:, 0] - np.einsum('ij,ij->i', a[:, 1:], b[:, 1:])

    for i in range(d - 1):
        vv_ = seed[:, i, :].copy()
        vv_ -= mk(vv_, e0)[:, None] * e0
        for j in range(i):
            vv_ -= (-mk(vv_, B[:, j, :]))[:, None] * B[:, j, :]
        vv_ /= np.sqrt(np.maximum(-mk(vv_, vv_), 1e-300))[:, None]
        B[:, i, :] = vv_
    yv = np.column_stack([sx_, wx_[:, 0], wx_[:, 1], wx_[:, 2]])
    yv = yv + (sy0 * taux)[:, None] * e0
    for i in range(d - 1):
        yv = yv + (wy0[:, i] * taux)[:, None] * B[:, i, :]
    dey = ((yv[:, 0] - 0.5 * tau) + v * yv[:, 1]) * gam
    wt = taux ** d
    S = (dex * dex).mean()
    Q = (wt * (dex_ ** 2 + dey ** 2)).sum() / wt.sum()
    P = (wt * dex_ * dey).sum() / wt.sum()
    return S, Q, P


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    rs = np.random.default_rng(2718281)
    N = 2000000
    print(f'точек {N} x {NB} блоков на каждое v')
    print()
    print(f"{'v²':>6}{'S':>11}{'Q':>11}{'P':>11}"
          f"{'A (R_etaeta)':>15}{'B (R_xx)':>13}{'B/A':>9}"
          f"{'конвейер B/A':>14}")
    for v2 in (0.0, 0.15, 0.30, 0.45, 0.60, 0.75, 0.85):
        v = math.sqrt(v2)
        rr = np.array([moments(v, 1.0, N, rs) for _ in range(NB)])
        S, Q, P = rr.mean(axis=0)
        eS, eQ, eP = rr.std(axis=0, ddof=1) / math.sqrt(NB)
        A = 8 * P / 3 + (2.0 / 3.0) * (Q - 2 * S)
        Bc = 8 * P + 4 * (Q - 2 * S)
        eA = math.sqrt((8 * eP / 3) ** 2 + ((2. / 3) * eQ) ** 2
                       + ((4. / 3) * eS) ** 2)
        print(f'{v2:>6.2f}{S:>11.5f}{Q:>11.5f}{P:>11.5f}'
              f'{f"{A:+.5f}+-{eA:.5f}":>15}{Bc:>+13.5f}'
              f'{Bc/A:>9.3f}{v2:>14.3f}', flush=True)
    print()
    print('''ЧТЕНИЕ. При v = 0 контроль: A обязано дать -0.02532, B +0.01922.
Дальше решает столбец `B/A` против столбца `конвейер B/A`. Конвейер
предполагал отношение, равное v², то есть НУЛЬ при покое. Если истинное
отношение при покое заметно отлично от нуля и ведёт себя иначе — план
был вырожден из-за неверных столбцов, а не из-за геометрии, и правильный
план может развести компоненты на УЖЕ набранных данных.''')


if __name__ == '__main__':
    main()

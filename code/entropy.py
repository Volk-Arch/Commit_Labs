#!/usr/bin/env python3
"""ЭНТРОПИЙНЫЙ МНОЖИТЕЛЬ: при каком ℏ подавление пересиливает число.

ОТКУДА. `quantum-doc.md`: на сприклингах структуры нет по центральной
предельной теореме (0.9 сигмы на 2000 историй), а со слоистыми порядками
она есть, и `|amp| = |cos(ΔS/2ℏ)|` сошлось до 0.07 % без подгонки. Но
веса были взяты 50/50, а настоящий ансамбль взвешивает семейства их
ЧИСЛОМ — в этом и состоит задача энтропии.

ПОЙМАННАЯ ОШИБКА ПОСТРОЕНИЯ. В `bimodal.py` слоистый порядок строился
так: все межслойные пары с долей `p`. Это НЕ порядки
Клейтмана–Ротшильда. У КР структура особая:

    три слоя размеров n/4, n/2, n/4;
    свободны связи ТОЛЬКО между СОСЕДНИМИ слоями (L1–L2 и L2–L3),
    каждая независимо с вероятностью 1/2  =>  2^(n²/4) порядков,
    то есть вся энтропия;
    связи крайних слоёв L1–L3 получаются ТРАНЗИТИВНЫМ ЗАМЫКАНИЕМ,
    а не выбором.

Из-за неверного построения у меня вышел ничтожный разброс `σ = 15.4`, и
это меняло сам вывод.

УСЛОВИЕ ПОДАВЛЕНИЯ, выведенное. Вклад семейства в сумму по путям есть
`n · ⟨exp(iS/ℏ)⟩`, и при гауссовом действии внутри семейства

    |вклад| = n · exp(−σ²/2ℏ²)

Многообразные выигрывают, когда

    n_сп · exp(−σ_сп²/2ℏ²)  >  n_сл · exp(−σ_сл²/2ℏ²)
    <=>  ℏ² < (σ_сл² − σ_сп²) / (2 ln(n_сл / n_сп))

Отсюда сразу видно главное: **подавление возможно только если
`σ_сл > σ_сп`.** Если разброс действия у слоистых МЕНЬШЕ, они
самогасятся слабее, и никакое `ℏ` их не подавит.

ЧТО СЧИТАЕМ:
  1. разброс действия на ПРАВИЛЬНОМ ансамбле КР против сприклингов;
  2. если `σ_сл > σ_сп` — критическое `ℏ` по формуле выше, с
     `ln(n_сл) = (N²/4)·ln2` (Клейтман–Ротшильд) и `n_сп`, взятым
     ОЦЕНКОЙ СВЕРХУ, то есть в пользу слоистых;
  3. зависимость от `N`, чтобы увидеть, растёт ли критическое `ℏ` или
     падает — это и есть то условие на масштаб дискретности, которое
     область формулирует как 1.1–2.3 планковских.

КОНТРОЛИ:
  - проверка кода: у ансамбля КР высота обязана быть ровно 3, а число
    свободных бит — ровно n1*n2 + n2*n3; сверяется прямо;
  - сприклинги считаются тем же действием и тем же сглаживанием;
  - `n_сп` неизвестно точно, поэтому берётся оценка СВЕРХУ: это делает
    вывод о подавлении консервативным.

  python3 entropy.py
  python3 entropy.py --ns 200,300,400 --samples 120
"""
import argparse
import math
import time

import numpy as np

from dyn import relation, bd_density_smeared


def kr_order(N, rs):
    """Порядок Клейтмана–Ротшильда: 3 слоя n/4, n/2, n/4.

    Свободны только связи L1–L2 и L2–L3, каждая с вероятностью 1/2;
    L1–L3 — транзитивное замыкание. Это и даёт 2^(n²/4) порядков.
    """
    n1 = N // 4
    n3 = N // 4
    n2 = N - n1 - n3
    R = np.zeros((N, N), bool)
    i1 = slice(0, n1)
    i2 = slice(n1, n1 + n2)
    i3 = slice(n1 + n2, N)
    A = rs.random((n1, n2)) < 0.5          # L1 -> L2
    B = rs.random((n2, n3)) < 0.5          # L2 -> L3
    R[i1, i2] = A
    R[i2, i3] = B
    R[i1, i3] = A @ B > 0                  # транзитивное замыкание
    return R, (n1, n2, n3)


def sprinkling(N, L, T, rs):
    X = np.empty((N, 4))
    X[:, 0] = rs.uniform(0, T, N)
    X[:, 1:] = rs.uniform(0, L, (N, 3))
    return relation(X[np.argsort(X[:, 0])], L)


def height_of(R):
    """Высота порядка — чистый счёт по слоям."""
    n = len(R)
    h = np.ones(n, np.int64)
    order = np.argsort(R.sum(0))           # по числу предшественников
    for i in order:
        pre = np.flatnonzero(R[:, i])
        if len(pre):
            h[i] = h[pre].max() + 1
    return int(h.max())


def check_kr():
    rs = np.random.default_rng(1)
    R, (n1, n2, n3) = kr_order(400, rs)
    hh = height_of(R)
    bits = n1 * n2 + n2 * n3
    print('  проверка кода на ансамбле КР (N = 400):')
    print(f'    слои {n1}/{n2}/{n3}, высота {hh} (ожидание 3)  '
          f'{"СХОДИТСЯ" if hh == 3 else "НЕ СХОДИТСЯ"}')
    print(f'    свободных бит {bits} = n1*n2 + n2*n3, '
          f'то есть ln(число) = {bits*math.log(2):.0f}')
    print(f'    формула КР: (N²/4)·ln2 = {400**2/4*math.log(2):.0f}')
    return hh == 3


def main():
    ap = argparse.ArgumentParser(description='Энтропийный множитель')
    ap.add_argument('--ns', type=str, default='200,300,400')
    ap.add_argument('--lell', type=float, default=5.0)
    ap.add_argument('--tell', type=float, default=6.0)
    ap.add_argument('--eps', type=float, default=0.4)
    ap.add_argument('--samples', type=int, default=120)
    a = ap.parse_args()

    t0 = time.time()
    print('УСЛОВИЕ: многообразные выигрывают при')
    print('    ℏ² < (σ_сл² − σ_сп²) / (2 ln(n_сл/n_сп))')
    print('значит подавление возможно ТОЛЬКО если σ_сл > σ_сп.')
    print()
    check_kr()
    print()

    Ns = [int(x) for x in a.ns.split(',')]
    print(f"{'N':>6}{'σ сприкл':>11}{'σ КР':>11}{'σ_сл/σ_сп':>12}"
          f"{'⟨S⟩ сприкл':>13}{'⟨S⟩ КР':>13}")
    rows = []
    for N in Ns:
        Ssp, Skr = [], []
        for s in range(a.samples):
            rs = np.random.default_rng(8800 + 29 * s)
            R = sprinkling(N, a.lell, a.tell, rs)
            Ssp.append(float(bd_density_smeared(R, a.eps).sum()))
            del R
            R, _ = kr_order(N, rs)
            Skr.append(float(bd_density_smeared(R, a.eps).sum()))
            del R
        Ssp = np.array(Ssp); Skr = np.array(Skr)
        ssp, skr = Ssp.std(ddof=1), Skr.std(ddof=1)
        rows.append((N, ssp, skr, Ssp.mean(), Skr.mean()))
        print(f'{N:>6}{ssp:>11.2f}{skr:>11.2f}{skr/max(ssp,1e-12):>12.2f}'
              f'{Ssp.mean():>13.1f}{Skr.mean():>13.1f}', flush=True)

    print()
    print('КРИТИЧЕСКОЕ ℏ (n_сп взято ОЦЕНКОЙ СВЕРХУ — в пользу слоистых)')
    print(f"{'N':>6}{'ln(n_сл)':>11}{'ln отнош.':>11}"
          f"{'σ_сл²−σ_сп²':>14}{'ℏ крит.':>11}{'ℏ/σ_сп':>9}")
    for N, ssp, skr, _, _ in rows:
        ln_kr = (N ** 2 / 4.0) * math.log(2)
        # оценка сверху на число сприклинговых порядков: при N событиях
        # различных порядков не больше, чем размещений, то есть N!;
        # это щедро завышено в пользу слоистых
        ln_sp = sum(math.log(k) for k in range(1, N + 1))
        ln_ratio = ln_kr - ln_sp
        num = skr ** 2 - ssp ** 2
        if num <= 0 or ln_ratio <= 0:
            print(f'{N:>6}{ln_kr:>11.0f}{ln_ratio:>11.0f}'
                  f'{num:>14.1f}{"нет":>11}{"—":>9}')
            continue
        hc = math.sqrt(num / (2.0 * ln_ratio))
        print(f'{N:>6}{ln_kr:>11.0f}{ln_ratio:>11.0f}'
              f'{num:>14.1f}{hc:>11.4f}{hc/ssp:>9.4f}')

    print()
    print('ЧТО ЭТО ЗНАЧИТ')
    bad = [r for r in rows if r[2] <= r[1]]
    if bad:
        print('  σ_сл НЕ больше σ_сп хотя бы при одном N =>')
        print('  действие слоистые НЕ подавляет этим механизмом:')
        print('  они самогасятся СЛАБЕЕ сприклингов, и никакое ℏ не')
        print('  переломит их численное превосходство.')
    else:
        print('  σ_сл > σ_сп всюду => подавление возможно, и критическое')
        print('  ℏ посчитано. Если ℏ/σ_сп растёт с N — условие слабеет,')
        print('  если падает — усиливается.')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ПОГАШЕНИЕ РАЗРЕЖЕННОГО СЛОИСТОГО СЕКТОРА — точно, пункт 4.

Это самое опасное место для вечерней архитектуры 8 октября. Критерий
гласит: погашение убивает сектора, чьё действие аффинно по немногим
целочисленным счётчикам. Разреженный слоистый сектор побивает
многообразный ПО СЧЁТУ с `N ~ 1700`, а гасится ли он — не мерено ни
разу. Архитектура ОБЯЗЫВАЕТ его гаситься; если выживет — она неверна.

Мерить надо аналитически: установлено 8 октября, что выборочное среднее
оценивает `<exp(i S/hbar)>` с ошибкой `1/sqrt(n)`, поэтому подавление
ниже этого пола невидимо для сэмплирования НИ ПРИ КАКОМ терпении.

КАК СУММА БЕРЁТСЯ ТОЧНО. Сектор — три слоя, отношения между 1-2 и 2-3
произвольны (матрицы `M12`, `M23`), а 1-3 определяются замыканием:
`i < k` тогда и только тогда, когда есть `j` во втором слое с
`i < j < k`. Тогда для действия

    S/k_4 = n - (|M12| + |M23|) + sum_{(i,k): n_ik >= 1} w(n_ik)
    n_ik = |s_i ∩ T_k|,   w(1)=9, w(2)=-16, w(3)=8, w(m>=4)=0

где `s_i` — носитель строки `i` матрицы `M12`, а `T_k` — носитель
столбца `k` матрицы `M23`. (Отношения 1-2 и 2-3 имеют ПУСТОЙ интервал,
потому что между соседними слоями нет элементов, значит каждое даёт
вклад `w(0) = -1`. Отношения 1-3 имеют `n_ik` элементов между.)

КЛЮЧЕВОЕ: при ФИКСИРОВАННОМ `M12` сумма по `M23` распадается в
ПРОИЗВЕДЕНИЕ по столбцам, потому что столбцы независимы, а зависимость
действия от столбца `k` идёт только через `T_k`. Отсюда

    Z = sum_{M12} exp(i k_4 (n - |M12|)/hbar) * G(M12)^{a_3}
    G(M12) = sum_{T ⊆ слой2} exp(i k_4 (-|T| + sum_i w(|s_i ∩ T|))/hbar)

Третий слой входит ТОЛЬКО показателем. Значит подавление на один
элемент третьего слоя равно ТОЧНО `|G| / 2^{a_2}`, и если оно строго
меньше единицы — сектор гасится экспоненциально по `a_3`, при любом его
размере.

КОНТРОЛИ:
  1. `hbar -> oo`: фазы исчезают, `|Z|/число` обязано идти к единице;
  2. случайные фазы вместо действия обязаны дать пол `1/sqrt(число)`;
  3. прямое перечисление при малых слоях обязано совпасть с факторизацией.

  python3 sparsecancel.py
"""
import itertools
import math

import numpy as np

K4 = 4.0 / math.sqrt(6.0)
W = {0: -1.0, 1: 9.0, 2: -16.0, 3: 8.0}


def wof(m):
    return W.get(int(m), 0.0)


def gfactor(rows, a2, hbar):
    """G(M12) = сумма по подмножествам T второго слоя."""
    tot = 0.0 + 0.0j
    for mask in range(1 << a2):
        T = mask
        ph = -float(bin(T).count('1'))
        for s in rows:
            ph += wof(bin(s & T).count('1'))
        tot += np.exp(1j * K4 * ph / hbar)
    return tot


def z_exact(a1, a2, a3, hbar):
    """Точное Z через факторизацию по столбцам третьего слоя."""
    n = a1 + a2 + a3
    tot = 0.0 + 0.0j
    for m12 in range(1 << (a1 * a2)):
        rows = [(m12 >> (i * a2)) & ((1 << a2) - 1) for i in range(a1)]
        pop = bin(m12).count('1')
        g = gfactor(rows, a2, hbar)
        tot += np.exp(1j * K4 * (n - pop) / hbar) * g ** a3
    return tot


def z_brute(a1, a2, a3, hbar):
    """КОНТРОЛЬ 3: прямое перечисление всех M12, M23."""
    n = a1 + a2 + a3
    tot = 0.0 + 0.0j
    for m12 in range(1 << (a1 * a2)):
        rows = [(m12 >> (i * a2)) & ((1 << a2) - 1) for i in range(a1)]
        p12 = bin(m12).count('1')
        for m23 in range(1 << (a2 * a3)):
            cols = [(m23 >> (k * a2)) & ((1 << a2) - 1) for k in range(a3)]
            ph = float(n) - p12 - sum(bin(c).count('1') for c in cols)
            for s in rows:
                for c in cols:
                    ph += wof(bin(s & c).count('1'))
            tot += np.exp(1j * K4 * ph / hbar)
    return tot


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    print('КОНТРОЛЬ 3: факторизация против прямого перечисления')
    for (a1, a2, a3, hb) in ((2, 2, 2, 0.55), (2, 3, 2, 0.55),
                             (3, 2, 3, 0.70)):
        ze = z_exact(a1, a2, a3, hb)
        zb = z_brute(a1, a2, a3, hb)
        print(f'  слои ({a1},{a2},{a3}), hbar={hb}: '
              f'|Z| факторизация {abs(ze):.6f}, перечисление {abs(zb):.6f}, '
              f'отличие {abs(ze-zb)/max(abs(zb),1e-12):.2e}')
    print()
    print('КОНТРОЛЬ 1: hbar -> большое, подавления быть не должно')
    for hb in (0.55, 5.0, 50.0, 500.0):
        a1 = a2 = 3
        rows_all = []
        g = 0.0
        # среднее |G|/2^a2 по всем M12
        acc = []
        for m12 in range(1 << (a1 * a2)):
            rows = [(m12 >> (i * a2)) & ((1 << a2) - 1) for i in range(a1)]
            acc.append(abs(gfactor(rows, a2, hb)) / (1 << a2))
        print(f'  hbar = {hb:>6}: среднее |G|/2^a2 = {np.mean(acc):.6f}')
    print()
    print('=' * 78)
    print('ПОДАВЛЕНИЕ НА ОДИН ЭЛЕМЕНТ ТРЕТЬЕГО СЛОЯ: |G|/2^a_2')
    print('(если строго < 1 — сектор гасится экспоненциально по a_3)')
    print(f"{'hbar':>7}{'слои 1,2':>11}{'max |G|/2^a2':>15}"
          f"{'средн.':>10}{'показатель ln':>15}{'итог':>22}")
    for a1, a2 in ((3, 3), (3, 4), (4, 4)):
        for hb in (0.39, 0.55, 0.78, 1.5):
            acc = []
            for m12 in range(1 << (a1 * a2)):
                rows = [(m12 >> (i * a2)) & ((1 << a2) - 1)
                        for i in range(a1)]
                acc.append(abs(gfactor(rows, a2, hb)) / (1 << a2))
            acc = np.array(acc)
            mx, mn = acc.max(), acc.mean()
            lg = math.log(max(mx, 1e-300))
            verdict = ('ГАСИТСЯ' if mx < 0.999 else
                       'ВЫЖИВАЕТ: архитектура неверна')
            print(f'{hb:>7.2f}{f"{a1},{a2}":>11}{mx:>15.6f}{mn:>10.6f}'
                  f'{lg:>15.4f}{verdict:>22}', flush=True)
    print()
    print('''ЧТЕНИЕ. `max |G|/2^a_2` — наибольшее по всем `M12`, то есть
САМЫЙ ВЫЖИВАЮЩИЙ вклад. Если и он строго меньше единицы, то весь сектор
подавлен как `exp(a_3 * ln(max))`, и подавление экспоненциально по
размеру третьего слоя — при любом его размере. Если он равен единице,
сектор выживает, и архитектура 8 октября опровергнута.''')


if __name__ == '__main__':
    main()

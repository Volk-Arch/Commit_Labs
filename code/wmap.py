#!/usr/bin/env python3
"""КАРТА ОТКЛИКА ПО `w` И РАБОЧАЯ ТОЧКА.

Установлено (`wphase-doc.md`): при постоянном `w` масштабный фактор
равен точно `a = (eta/eta_0)^p`, `p = 2/(1+3w)`, поэтому отношение
`vv/u = p/(p-1)` фиксировано, и каждое уравнение состояния — ЛУЧ в
плоскости компонент. Первый порядок разрешает лучи хуже всего, значит
`w` и есть слепое направление плана. Чувствительность растёт с размером
интервала, но отклик НЕ монотонен: около `w ~ 0.45` производная
обращается в нуль, и подгонка там двузначна.

ЗДЕСЬ три вещи.

1. МЕЛКАЯ СЕТКА по `w` при нескольких `tau` — где именно стоит
   стационарная точка и как она ползёт.
2. СНЯТИЕ ДВУЗНАЧНОСТИ: инъективно ли отображение
   `w -> (X_2(tau_1), X_2(tau_2))`. Проверяется прямо: для каждой пары
   значений `w` считается расстояние в двумерном пространстве
   наблюдаемых, делённое на достижимый шум.
3. РАБОЧАЯ ТОЧКА. Информация на интервал идёт как
   `(dX_2/dw)² / sigma²`, а `sigma ~ 1/sqrt(C_1)`, `C_1 ~ tau^4`, значит
   `info ~ (dX_2/dw)² tau^4`. Где максимум — там и надо набирать. Это
   решает, разворачивать ли идущий набор: он сидит на старой рабочей
   точке с малой кривизной, то есть там, где `w` слеп.

Область `w`: ветвь `p < 0` (то есть `w < -1/3`) физически важна — при
`w = -1` выходит `p = -1`, то есть де Ситтер, тёмная энергия. Но у
`w = -1/3` показатель расходится, поэтому окрестность `|1 + 3w| < 0.15`
пропускается, и это отмечено в выводе.

  python3 wmap.py
"""
import math

import numpy as np

from weos import x2_w

NB = 4
N = 1300000
TAUS = (0.6, 1.0, 1.5)
WS = np.array([-1.00, -0.80, -0.60, -0.45,
               -0.20, -0.10, 0.00, 0.10, 0.20, 0.30, 0.40, 0.50,
               0.60, 0.80, 1.00, 1.30])
SIG1 = 0.094          # шум X_2 на интервал при C_1 ~ 200..900 (neff.py)
C1REF = 500.0


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    rs = np.random.default_rng(141421356)
    print(f'точек {N}, блоков {NB}; eta_0 = 1')
    print()
    print(f"{'w':>7}{'p':>8}", end='')
    for t in TAUS:
        print(f'{f"X_2(tau={t})":>15}', end='')
    print()
    tab = {}
    for w in WS:
        p = 2.0 / (1.0 + 3.0 * w)
        row = []
        print(f'{w:>7.2f}{p:>8.2f}', end='')
        for t in TAUS:
            r = np.array([x2_w(w, t, N, rs) for _ in range(NB)])
            m, e = r.mean(), r.std(ddof=1) / math.sqrt(NB)
            row.append((m, e))
            print(f'{f"{m:+.5f}+-{e:.5f}":>15}', end='')
        tab[float(w)] = row
        print(flush=True)

    print()
    print('=' * 78)
    print('СТАЦИОНАРНЫЕ ТОЧКИ И ЧУВСТВИТЕЛЬНОСТЬ')
    print(f"{'tau':>6}{'где dX/dw = 0':>16}{'|dX/dw| у w=1/3':>18}"
          f"{'info ~ (dX/dw)² tau⁴':>22}")
    best = None
    for k, t in enumerate(TAUS):
        v = np.array([tab[float(w)][k][0] for w in WS])
        dv = np.gradient(v, WS)
        # стационарная точка: смена знака производной в области w > -0.3
        msk = WS > -0.3
        ws, dvs = WS[msk], dv[msk]
        zc = 'нет'
        for i in range(len(ws) - 1):
            if dvs[i] * dvs[i + 1] < 0:
                zc = (f'{ws[i] - dvs[i] * (ws[i+1]-ws[i])/(dvs[i+1]-dvs[i]):+.3f}')
                break
        d13 = abs(np.interp(1.0 / 3.0, WS, dv))
        info = d13 ** 2 * t ** 4
        if best is None or info > best[0]:
            best = (info, t)
        print(f'{t:>6.1f}{zc:>16}{d13:>18.4f}{info:>22.4f}', flush=True)

    print()
    print('=' * 78)
    print('ИНЪЕКТИВНОСТЬ ПАРЫ (tau=0.6, tau=1.5): снимается ли двузначность')
    ia, ib = 0, 2
    pts = np.array([[tab[float(w)][ia][0], tab[float(w)][ib][0]]
                    for w in WS])
    # масштабируем обе оси достижимым шумом одной оценки
    sc = SIG1 / math.sqrt(C1REF / C1REF)
    worst, pair = 1e9, None
    sel = [w for w in WS if w > -0.3]
    for i, wi in enumerate(sel):
        for wj in sel[i + 1:]:
            if abs(wi - wj) < 0.05:
                continue
            a = pts[list(WS).index(wi)]
            b = pts[list(WS).index(wj)]
            dist = math.hypot(*(a - b)) / sc
            if dist < worst:
                worst, pair = dist, (wi, wj)
    print(f'  наименее различимая пара: w = {pair[0]:+.2f} и {pair[1]:+.2f}, '
          f'расстояние {worst:.4f} в единицах шума ОДНОГО интервала')
    need = (1.0 / worst) ** 2 * 25
    print(f'  чтобы развести их на 5 сигм, нужно независимых интервалов: '
          f'{need:.0f}')
    print(f'  (в наборе сейчас ~107000 независимых)')
    print()
    print(f'рабочая точка по информации: tau/eta_0 = {best[1]}')
    print('''
ЧТЕНИЕ. Если наименее различимая пара разводится числом интервалов
МЕНЬШЕ имеющегося, двух `tau` достаточно и двузначность снята. Рабочая
точка по информации говорит, где набирать: если она далеко от текущей
(малая кривизна, `tau² R <= 0.8`), идущий набор надо разворачивать.''')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ДОЛЯ КОНФИГУРАЦИЙ: ядро утверждения, напрямую.

ratsingle.py: наилучший ОДИНОЧНЫЙ враг далёк от засева по вектору
отношений (хи2 = 187.5 против 6.4 у контроля), и пятёрка лучших лежит
ВНУТРИ сетки. Но там сравнивались СРЕДНИЕ по ансамблю, а всё утверждение
держится на другом: смесь состоит из тех же КОНФИГУРАЦИЙ, поэтому
спрашивать надо не про среднее, а про ДОЛЮ.

Прямое измерение. Берём по многу ОДИНОЧНЫХ конфигураций, у каждой свой
вектор отношений N_m/N_0. Строим «область засева» по его же разбросу, и
считаем, какая доля врагов в неё попадает. Если ноль - никакая смесь
врагов не содержит похожих на засев конфигураций, и смешивание не
спасает по определению, а не по подгонке.

КОНТРОЛЬ: вторая независимая партия засевов обязана попадать в область
засева почти целиком. Если нет - область построена неверно, и доли
врагов ничего не значат.
"""
import math

import numpy as np

from sectors import sprinkle_d
from lkdeg import layered
from ratios import nm


def one(mk):
    v, _ = nm(mk())
    return v[1:] / max(v[0], 1.0)


def main():
    print(__doc__)
    rs = np.random.default_rng(4472135)
    n = 1000
    NA, NB = 50, 50

    A = np.array([one(lambda: sprinkle_d(n, 4, rs)) for _ in range(NA)])
    mu, sd = A.mean(axis=0), A.std(axis=0, ddof=1)
    print(f'область засева по {NA} конфигурациям:')
    print('  центр:  ' + ' '.join(f'{v:.4f}' for v in mu))
    print('  разброс:' + ' '.join(f'{v:.4f}' for v in sd))

    def chi(X):
        return (((X - mu) / sd) ** 2).sum(axis=1)

    thr = float(np.percentile(chi(A), 95))
    print(f'  порог области (95-й процентиль по самим засевам): '
          f'хи2 = {thr:.1f}')

    B = np.array([one(lambda: sprinkle_d(n, 4, rs)) for _ in range(NB)])
    inb = int((chi(B) <= thr).sum())
    print(f'\nКОНТРОЛЬ: вторая партия засевов, попало {inb}/{NB} '
          f'=> {"ОК" if inb >= 0.8 * NB else "СБОЙ"}')

    print('\nдоля ВРАГОВ, попавших в область засева:')
    for k, dl in ((34, 0.5), (13, 1.0), (18, 1.0), (13, 1.5), (9, 1.0),
                  (48, 0.5), (25, 0.5)):
        q = dl * k / n
        E = np.array([one(lambda: layered(n, k, q, rs)) for _ in range(40)])
        c = chi(E)
        print(f'  k={k:>3} delta={dl:>4}: попало {int((c <= thr).sum()):>2}/40'
              f'   медиана хи2 = {np.median(c):>10.1f}', flush=True)
    print('\nЧТЕНИЕ: контроль попадает, враги не попадают => разделение')
    print('идёт ПО КОНФИГУРАЦИЯМ, и смешивание его не снимает.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ПРЯМОЙ СПРИКЛИНГ: проверка отклика и шума перед разворотом набора.

Карта отклика (`wmap.py`) посчитана квадратурой. Прежде чем
разворачивать набор на часы, надо убедиться, что настоящий сприклинг
даёт (а) то же среднее и (б) ожидаемый шум.

ПОПРАВКА К СВОЕЙ ЖЕ ФОРМУЛЕ. Я написал `info ~ (dX/dw)² tau^4`, считая,
что `C_1` растёт как `tau^4`. Но `C_1` — СВОБОДНЫЙ выбор: его задаёт
плотность сприклинга, а не размер интервала. При фиксированном `C_1`
выигрыш идёт только как `(dX/dw)²`, то есть 26 раз от `tau = 0.6` к 1.5,
а не тысяча. Значит набирать надо при БОЛЬШОМ `tau/eta_0` и УМЕРЕННОМ
`C_1`, понизив плотность — это другая конфигурация, а не «больше того
же».

Сприклинг здесь точный и прямой: точки сыплются В САМ интервал с
физической плотностью, то есть в плоском ромбе с координатной
плотностью `~ a^4`. Это ровно то, что мерит набор, без его отборов.

КОНТРОЛИ:
  1. плоское (`a = 1`) обязано дать `X_2 = 0`;
  2. среднее при каждом `w` обязано совпасть с квадратурой;
  3. шум обязан идти как `1/sqrt(C_1)`.

  python3 wsprink.py
"""
import math

import numpy as np

from pencil import c_k
from vcal import ball

NB = 400


def sprinkle_interval(w, tau, c1, rs, eta0=1.0, d=4):
    """Пуассоновский сприклинг В ромб с физической плотностью.
    Возвращает (C_1, X_2) одной реализации."""
    p = 0.0 if w is None else 2.0 / (1.0 + 3.0 * w)
    # координатная плотность ~ a^4 = (eta/eta0)^{4p}; ромб по t, шар R(t)
    M = 4000
    e = np.linspace(eta0 - 0.5 * tau, eta0 + 0.5 * tau, M)
    R = np.minimum(e - (eta0 - 0.5 * tau), (eta0 + 0.5 * tau) - e)
    dens = (e / eta0) ** (4.0 * p) * R ** (d - 1)
    cdf = np.concatenate([[0.0], np.cumsum(0.5 * (dens[1:] + dens[:-1])
                                           * np.diff(e))])
    n = rs.poisson(c1)
    if n < 4:
        return n, np.nan
    t = np.interp(rs.uniform(0, cdf[-1], n), cdf, e)
    o = np.argsort(t); t = t[o]
    Rt = np.minimum(t - (eta0 - 0.5 * tau), (eta0 + 0.5 * tau) - t)
    X = ball(rs, n, d - 1, Rt)
    sq = np.einsum('ij,ij->i', X, X)
    dt = t[None, :] - t[:, None]
    d2 = sq[:, None] + sq[None, :] - 2.0 * (X @ X.T)
    np.maximum(d2, 0.0, out=d2)
    A = (dt > 0) & (dt * dt > d2)
    # C_2 = число ДВУХэлементных цепей = число отношений.
    # (F @ F).sum() — это C_3, трёхэлементные; на этом я и попался,
    # и плоский контроль поймал: отношение (c_3/c_2)(n-2) = 4.74.
    c2 = float(A.sum())
    if n < 2:
        return n, np.nan
    return n, c2 / (c_k(2) * n * (n - 1.0)) - 1.0


def run(w, tau, c1, rs, nb=NB):
    v = []
    for _ in range(nb):
        _, x = sprinkle_interval(w, tau, c1, rs)
        if x == x:
            v.append(x)
    v = np.array(v)
    return v.mean(), v.std(ddof=1) / math.sqrt(len(v)), v.std(ddof=1)


def main():
    print(__doc__.split('  python3')[0].rstrip())
    print()
    rs = np.random.default_rng(2024)
    print(f'реализаций на точку {NB}')
    print()
    print('КОНТРОЛЬ 1: плоское (p = 0) обязано дать нуль')
    for c1 in (250, 500, 1000):
        m, e, s = run(0.0 if False else None, 1.5, c1, rs)
        print(f'  C_1 = {c1:>5}: X_2 = {m:+.5f} +- {e:.5f}  '
              f'({abs(m)/max(e,1e-12):.1f} сигм), шум одной реализации '
              f'{s:.4f}')
    print()
    print('КОНТРОЛЬ 3: шум обязан идти как 1/sqrt(C_1)')
    print()
    print('КОНТРОЛЬ 2 + ОТКЛИК: сприклинг против квадратуры, C_1 = 500')
    QUAD = {(0.0, 0.6): -0.01171, (0.0, 1.5): -0.04546,
            (1.0 / 3.0, 0.6): -0.01920, (1.0 / 3.0, 1.5): -0.08874,
            (1.0, 0.6): -0.01290, (1.0, 1.5): -0.07584}
    print(f"{'w':>7}{'tau':>6}{'сприклинг':>20}{'квадратура':>13}"
          f"{'сигм':>7}{'шум одной':>12}")
    for (w, tau), q in QUAD.items():
        m, e, s = run(w, tau, 500, rs)
        print(f'{w:>7.3f}{tau:>6.1f}{f"{m:+.5f}+-{e:.5f}":>20}{q:>13.5f}'
              f'{abs(m-q)/max(e,1e-12):>7.1f}{s:>12.4f}', flush=True)
    print()
    print('=' * 78)
    print('ДОСТИЖИМАЯ ТОЧНОСТЬ ПО `w`')
    for tau, der in ((0.6, 0.0051), (1.5, 0.0258)):
        m, e, s = run(1.0 / 3.0, tau, 500, rs)
        sw1 = s / der
        for nint in (107000, 400000):
            print(f'  tau = {tau}: |dX/dw| = {der:.4f}, шум {s:.4f} -> '
                  f'sigma(w) на интервал {sw1:.2f}, '
                  f'на {nint} интервалах {sw1/math.sqrt(nint):.4f}')
    print('''
ЧТЕНИЕ. Если сприклинг совпал с квадратурой, отклик подтверждён
независимым способом, и строка `tau = 1.5` говорит достижимую точность
по `w` при развороте набора на большие интервалы.''')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ЧЕЙ ПОТОЛОК? Сканирование по разрешению прибора.

В `dimobs2.py` у слоистых различимых направлений вышло ровно столько,
сколько параметров (5/5, 7/7, 11/11, 17/17, 22/23 — не упирается), а у
конформной метрики упёрлось: 20 параметров дали 11 направлений.

Но есть прямое подозрение, что это МОЙ потолок, а не свойство
семейства. Моды `cos(k pi eta/T)` локальны по времени, а полос глубины
у наблюдаемой было ВСЕГО ШЕСТЬ: мода с `k > 6` осциллирует внутри
полосы и усредняется в нуль. Это найквист прибора. Физически высокие
моды должны быть видны ЛУЧШЕ, а не хуже: кривизна у них больше
(`a'' ~ eps k^2`), значит глушит их именно прибор.

ПРОВЕРКА. Фиксируем семейство на заведомо богатом (K = 24 мода,
L = 16 слоёв) и поднимаем разрешение прибора: полос глубины 3, 6, 12,
24. Чей ранг продолжает расти с разрешением — у того семейства
размерность больше, и упирался он в меня.

КОНТРОЛЬ: шаг по параметру НУЛЬ. Все сингулярные числа обязаны выйти
ниже единицы; если нет — прибор видит направления там, где их нет.

  python3 dimobs3.py
"""
import math
import time

import numpy as np

import dimobs2 as D
from dimobs import gen_layers, gen_conf


def scan(gen, n, th, steps, seeds, root, ndep):
    D.NDEP = ndep
    return D.rank_of(gen, n, th, steps, seeds, root)


def main():
    t0 = time.time()
    print(__doc__.split('  python3')[0].rstrip())
    print()
    N, SD = 1100, 8
    K, L = 24, 16
    parts = [1.0 / L] * L
    qs = [0.5] * (L - 1)
    lsteps = [0.03] * L + [0.05] * (L - 1)
    print(f'N = {N}, засевов {SD}; слоистое L = {L} ({2*L-1} параметров), '
          f'метрика K = {K} ({K} параметров)')
    print()
    print('=' * 78)
    print('КОНТРОЛЬ: шаг нуль — все сингулярные числа обязаны быть < 1')
    sv, r, nk = scan(gen_conf, N, ([0.0] * 6,), [0.0] * 6, SD, 777, 12)
    print(f'  метрика, 6 нулевых шагов: ранг {r}, максимум '
          f'{sv.max():.3f} -> {"ЧИСТО" if r == 0 else "ПРИБОР ВРЁТ"}')
    sv, r, nk = scan(gen_layers, N, ([1/6.]*6, [0.5]*5), [0.0]*11, SD, 778, 12)
    print(f'  слоистое, 11 нулевых шагов: ранг {r}, максимум '
          f'{sv.max():.3f} -> {"ЧИСТО" if r == 0 else "ПРИБОР ВРЁТ"}')
    print(f'  ({time.time()-t0:.0f} с)', flush=True)
    print()
    print('=' * 78)
    print('СКАН ПО РАЗРЕШЕНИЮ: чей ранг растёт с числом полос глубины?')
    print(f"{'полос':>7}{'компонент':>11}{'метрика K=24':>15}"
          f"{'слоистое L=16':>15}{'потолок прибора':>18}")
    rows = []
    for nd in (3, 6, 12, 24, 40):
        _, rc, nc = scan(gen_conf, N, ([0.0] * K,), [0.04] * K, SD,
                         9100 + nd, nd)
        _, rl, nl = scan(gen_layers, N, (parts, qs), lsteps, SD,
                         9200 + nd, nd)
        cap = min(7 * nd, 2 * L - 1)
        rows.append((nd, rc, rl))
        print(f'{nd:>7}{7*nd:>11}{rc:>15}{rl:>15}{cap:>18}')
        print(f'    ({time.time()-t0:.0f} с)', flush=True)
    print()
    print('=' * 78)
    rc0, rc1 = rows[0][1], rows[-1][1]
    rl0, rl1 = rows[0][2], rows[-1][2]
    print(f'метрика:  {rc0} -> {rc1} направлений при росте разрешения в '
          f'{rows[-1][0]//rows[0][0]} раз')
    print(f'слоистое: {rl0} -> {rl1} направлений (предел семейства '
          f'{2*L-1})')
    print()
    if rc1 > rc0 and rc1 >= 0.7 * K:
        print('''ВЫВОД. Упиралось в прибор. Метрика отдаёт новые направления,
как только я их умею видеть, и доходит до своего числа параметров.
Тогда прошлая таблица НИЧЕГО не говорила о семействах.''')
    elif rl1 >= 2 * L - 2 and rc1 < 0.5 * K:
        print('''ВЫВОД. Потолок не мой. Слоистое семейство отдаёт все свои
направления, метрика — меньше половины даже при высоком разрешении.
Первая версия опровергнута: пространство-время беднее И состояниями,
И различимыми классами.''')
    else:
        print('''ВЫВОД. Промежуточный случай: оба семейства отдают часть
направлений. Сравнивать размерности на этих числах нельзя.''')


if __name__ == '__main__':
    main()

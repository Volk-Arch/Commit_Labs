#!/usr/bin/env python3
"""РАДАРНЫЕ ЯЧЕЙКИ: кривизна счётом, по его конструкции.

ЕГО МЫСЛЬ. Инвариантной окрестности одной точки нет. Но цепь через
событие даёт радарную пару `p` (последнее её событие в прошлом) и `f`
(первое в будущем), и ИНТЕРВАЛ между ними содержит это событие. Значит
окрестность есть — для каждой цепи своя, — и семейство по цепям и есть
ковариантный объект, как тензор в ОТО. А «часть цепей идёт с одной
скоростью, часть с другой» — это то, что разделяет компоненты.

ЧТО ЭТО СНИМАЕТ. В `diamond.py` формула объёма малого ромба
(Гиббонс–Солодухин, hep-th/0703098) проверена до 0.1 % при контроле
плоского 6.4e-15:

    V = (π/24) τ⁴ [ 1 + A·τ²R + B·R_μν u^μu^ν ],  A = −1/180, B = +1/30

но перевод в счёт не шёл: в линейке `s = k/n^(1/4)` кривизна правит и
числитель, а поправки к длине САМОЙ ДОЛГОЙ ЦЕПИ ни у кого нет (наивное
предсказание отверглось измерением на 4.4 сигмы).

В радарной ячейке долгая цепь не нужна вовсе: `τ` читается с цепи как её
собственные засечки. Часы ДАНЫ, а не выведены. Остаётся ровно та
величина, формула для которой проверена, — объём против `τ⁴`.

И второе: `R` от скорости наблюдателя не зависит, а `R_μν u^μu^ν`
зависит. Значит цепи с РАЗНЫМИ скоростями дают разные комбинации тех же
двух чисел, и `A` с `B` разделяются — то, что в `diamond.py` было
невозможно при одной цепи.

УСТРОЙСТВО. Конформно-плоская метрика `ds² = a(η)²(−dη² + dx²)`,
`a = 1 + c(η−η₀)²/2`. Конусы плоские, поэтому причинность берётся плоской
формулой, а кривизна сидит в плотности `ρ ∝ a⁴`. Цепь с координатной
скоростью `v` планируется с РАВНЫМ шагом по собственному времени
(`dτ = a√(1−v²) dη`), поэтому `τ` между её событиями `i` и `i+g` равно
`g·шаг` ТОЧНО. Объём ромба `I(c_i, c_{i+g})` — чистый счёт событий.

ЧТО ЭТО ПРОВЕРЯЕТ И ЧТО НЕТ. Проверяется ОБЪЁМНАЯ половина: даёт ли
счёт событий кривизну по проверенной формуле. Калибровка часов здесь
дана построением; у настоящей цепи причинного множества её пришлось бы
выводить, и это отдельный вопрос.

КОНТРОЛИ, поставленные до замера:
  1. c = 0 обязано дать dev = 0 в пределах статистики — это нулевая
     точка и одновременно проверка нормировки объёма;
  2. скорость v = 0 и v ≠ 0 при c = 0 обязаны дать одно и то же;
  3. `A` и `B` вытаскиваются ИЗ ДАННЫХ и сравниваются с
     опубликованными, а не подгоняются под них;
  4. зависимость от `g` (размера ромба): dev обязан идти как τ², то
     есть dev/τ² не должен зависеть от g;
  5. ромбы берутся из середины по времени, где `a ≈ 1`.

  python3 cells.py.new
"""
import math
import time

import numpy as np

LELL = 22.0        # сторона ящика в ell (БЕЗ замыкания)
WCAP = 7.0         # за этим |eta-eta0| профиль перестаёт расти
#                    (и там a''=0, то есть КРИВИЗНА НУЛЬ — поэтому ромб
#                     обязан лежать целиком внутри, см. проверку ниже)
TELL = 20.0        # протяжённость по времени
ETA0 = TELL / 2.0


def ricci_at_center(c, v):
    """R и R_μν u^μu^ν в центре, замкнутыми формулами.

    Символьный счёт (sympy, отдельным шагом) дал при eta = eta0:
        R = 6c,   R_eta_eta = -3c,   R_xx = +c,   a = 1
    Отсюда для наблюдателя с координатной скоростью v
    (u^mu = (1,v,0,0)/(a*sqrt(1-v²))):
        R_uu = (R_eta_eta + v²R_xx)/(a²(1-v²)) = c(v²-3)/(1-v²)
    Проверка: при v = 0 выходит -3c, что совпало с независимым счётом в
    `diamond.py`, где комбинация A*R + B*R_uu дала -0.1333c.
    """
    R = 6.0 * c
    Ruu = c * (v * v - 3.0) / (1.0 - v * v)
    return R, Ruu


def sprinkle(c, rs):
    """Неоднородный сприклинг с rho(eta) = a(eta)^4.

    Выборка обратной функцией распределения, а не отбором: отбор при
    сильном профиле выбрасывает большую часть проб, а здесь он и не
    нужен — распределение одномерное.
    """
    L, T = LELL, TELL
    e = np.linspace(0.0, T, 20000)
    w = (1 + c * np.minimum((e - ETA0) ** 2, WCAP ** 2) / 2) ** 4
    cdf = np.concatenate([[0.0], np.cumsum(0.5 * (w[1:] + w[:-1])
                                           * np.diff(e))])
    need = int(round(L ** 3 * cdf[-1]))
    u = rs.uniform(0, cdf[-1], need)
    eta = np.interp(u, cdf, e)
    X = np.empty((need, 4))
    X[:, 0] = eta
    X[:, 1:] = rs.uniform(0, L, (need, 3))
    o = np.argsort(X[:, 0])
    return X[o]


def chain_events(c, v, step, n, xoff=0.0):
    """Цепь скорости v с РАВНЫМ шагом по собственному времени.

    dtau = a(eta) * sqrt(1-v^2) * deta, поэтому узлы ставятся по
    накопленному собственному времени. Отсюда tau между узлами i и i+g
    равно g*step ТОЧНО.
    """
    af = lambda e: 1 + c * np.minimum((e - ETA0) ** 2, WCAP ** 2) / 2
    e = np.linspace(0.0, TELL, 20000)
    pt = np.concatenate([[0.0], np.cumsum(
        0.5 * (af(e[1:]) + af(e[:-1])) * np.diff(e))]) * math.sqrt(1 - v * v)
    tot = pt[-1]
    t0 = 0.5 * (tot - (n - 1) * step)
    want = t0 + step * np.arange(n)
    if want[0] < 0 or want[-1] > tot:
        raise ValueError('цепь не влезает по времени')
    etas = np.interp(want, pt, e)
    xs = LELL / 2 + xoff + v * (etas - ETA0)   # без замыкания
    C = np.zeros((n, 4))
    C[:, 0] = etas
    C[:, 1] = xs
    C[:, 2] = LELL / 2
    C[:, 3] = LELL / 2
    return C


def count_interval(X, p, f, L):
    """Число событий в причинном интервале между p и f (конусы плоские).

    ПОЙМАННАЯ ОШИБКА, которую взял контроль плоского (35 сигм). Раньше
    пространство было ЗАМКНУТО, и расстояние считалось по наименьшему
    образу. Но у ромба между событиями ДВИЖУЩЕЙСЯ цепи протяжённость по
    оси буста равна `Δη = τ/sqrt(1-v²)`, а правило наименьшего образа
    верно лишь до `L/2`. При v = 0.7 и τ = 6 выходило Δη = 8.4 против
    L/2 = 6, и события дальнего края засчитывались с противоположной
    стороны: dev = +0.716 вместо нуля.

    Починка: замыкание убрано вовсе. Ромб задан своими концами, и
    замыкание ему не нужно; достаточно, чтобы он целиком лежал внутри
    засеянной области, что проверяется отдельно.
    """
    t = X[:, 0]
    i0 = np.searchsorted(t, p[0], 'right')
    i1 = np.searchsorted(t, f[0], 'left')
    if i1 <= i0:
        return 0
    S = X[i0:i1, 1:]
    tt = t[i0:i1]
    d1 = S - p[1:]
    d2 = f[1:] - S
    ok = (((tt - p[0]) ** 2 > (d1 * d1).sum(1))
          & (((f[0] - tt) ** 2) > (d2 * d2).sum(1)))
    return int(ok.sum())


def main():
    t0 = time.time()
    print('РАДАРНАЯ ЯЧЕЙКА: окрестность события задана ПАРОЙ событий цепи,')
    print('значит она законна; семейство по цепям — ковариантный объект.')
    print('tau читается с цепи (часы ДАНЫ), объём — чистый счёт.')
    print()
    print(f'ящик {LELL} x {TELL} ell (замер из середины по времени)')
    print()

    # шаг и длина цепи: при v = 0.7 собственное время сжато в
    # sqrt(1-v²) = 0.714 раза, и цепь обязана влезть в этот запас
    step = 1.4
    gaps = (3, 4)
    vs = (0.0, 0.45, 0.70)
    cs = (0.0, 0.004, 0.012)
    nchain = 9
    xoffs = (-4.5, -1.5, 1.5, 4.5)
    seeds = 24

    print('КОНТРОЛЬ: при c = 0 отклонение обязано быть нулём при любой v')
    print('(мир строится ОДИН раз на засев и переиспользуется для всех')
    print(' скоростей и размеров — иначе счёт идёт впустую в 9 раз)')
    print()
    print(f"{'c':>8}{'v':>7}{'g':>4}{'tau':>8}{'ell²R':>9}{'ell²R_uu':>11}"
          f"{'ромбов':>8}{'dev':>10}{'ст.ош':>9}{'dev/tau²':>11}")
    rows = []
    acc = {}
    for c in cs:
        e = np.linspace(0.0, TELL, 20000)
        wgt = (1 + c * np.minimum((e - ETA0) ** 2, WCAP ** 2) / 2) ** 4
        norm = float(np.trapezoid(wgt, e))
        for sd in range(seeds):
            X = sprinkle(c, np.random.default_rng(6100 + 37 * sd))
            rho = len(X) / (LELL ** 3 * norm)
            for v in vs:
              for xoff in xoffs:
                C = chain_events(c, v, step, nchain, xoff)
                for g in gaps:
                    tau = g * step
                    for i in range(nchain - g):
                        mid = 0.5 * (C[i, 0] + C[i + g, 0])
                        # ПОЙМАННАЯ ОШИБКА: ограничитель профиля обнуляет
                        # КРИВИЗНУ за WCAP (там a''=0), а вытянутый бустом
                        # ромб туда залезал — отклик выходил меньше
                        # предсказанного, и согласие рвалось именно при
                        # v = 0.70 (5.3 сигмы против 0.5 при v <= 0.45).
                        # Условие: ромб целиком внутри области кривизны.
                        deta0 = C[i + g, 0] - C[i, 0]
                        if abs(mid - ETA0) + deta0 / 2 > WCAP - 0.3:
                            continue
                        # ромб обязан целиком лежать в засеянной области:
                        # его протяжённость по оси буста равна deta
                        deta = C[i + g, 0] - C[i, 0]
                        xlo = min(C[i, 1], C[i + g, 1]) - deta / 2
                        xhi = max(C[i, 1], C[i + g, 1]) + deta / 2
                        if xlo < 0.5 or xhi > LELL - 0.5:
                            continue
                        if C[i, 0] < 0.5 or C[i + g, 0] > TELL - 0.5:
                            continue
                        n_in = count_interval(X, C[i], C[i + g], LELL)
                        # ПОЙМАННАЯ ОШИБКА: делил на rho*a⁴, то есть
                        # учитывал конформный множитель ДВАЖДЫ. Физическая
                        # плотность постоянна (rho = N/(L³∫a⁴dη) и есть
                        # она), а ожидаемый счёт равен rho * V_физ,
                        # поэтому V_физ = n/rho и всё.
                        Vm = n_in / rho
                        acc.setdefault((c, v, g), []).append(
                            Vm / (math.pi / 24 * tau ** 4) - 1.0)
            del X
        print(f'  c = {c}: миры готовы ({time.time()-t0:.0f} с)', flush=True)

    for c in cs:
        for v in vs:
            Rv, Ruu = ricci_at_center(c, v)
            for g in gaps:
                if (c, v, g) not in acc or len(acc[(c, v, g)]) < 8:
                    print(f'{c:>8.4f}{v:>7.2f}{g:>4}   ромбов не хватило')
                    continue
                vals = np.array(acc[(c, v, g)])
                dev = vals.mean()
                se = vals.std(ddof=1) / math.sqrt(len(vals))
                tau = g * step
                rows.append((c, v, g, tau, Rv, Ruu, dev, se))
                print(f'{c:>8.4f}{v:>7.2f}{g:>4}{tau:>8.2f}{Rv:>9.5f}'
                      f'{Ruu:>11.5f}{len(vals):>8}{dev:>+10.5f}{se:>9.5f}'
                      f'{dev/tau**2:>+11.6f}')
    print()
    print('ВЫТАСКИВАЕМ A и B ИЗ ДАННЫХ (три скорости разделяют их)')
    use = [r for r in rows if r[0] != 0.0]
    M = np.array([[r[3] ** 2 * r[4], r[3] ** 2 * r[5]] for r in use])
    y = np.array([r[6] for r in use])
    w = 1.0 / np.array([max(r[7], 1e-9) for r in use])
    coef, *_ = np.linalg.lstsq(M * w[:, None], y * w, rcond=None)
    print(f'  из данных:    A = {coef[0]:+.5f},  B = {coef[1]:+.5f}')
    print(f'  опубликовано: A = {-1/180:+.5f},  B = {1/30:+.5f}')
    pub = M @ np.array([-1 / 180.0, 1 / 30.0])
    chi = np.abs(y - pub) / np.array([max(r[7], 1e-9) for r in use])
    print(f'  согласие с опубликованной формулой: среднее '
          f'{chi.mean():.1f} сигм, худшее {chi.max():.1f}')
    print()
    print('ПРОВЕРКА ОБЛАСТИ ПРИМЕНИМОСТИ. Формула — первый порядок по')
    print('tau²R, значит требует tau²R << 1. Если недостача уходит с')
    print('уменьшением кривизны — дело в высших порядках, а не в формуле.')
    print(f"{'c':>8}{'v':>7}{'tau':>7}{'tau²R':>8}{'замер':>10}"
          f"{'формула':>10}{'отнош':>8}")
    for r, p_ in zip(use, pub):
        print(f'{r[0]:>8.4f}{r[1]:>7.2f}{r[3]:>7.2f}'
              f'{r[3]**2*r[4]:>8.2f}{r[6]:>+10.5f}{p_:>+10.5f}'
              f'{r[6]/p_ if abs(p_)>1e-12 else float("nan"):>8.3f}')
    z = [r for r in rows if r[0] == 0.0]
    zz = np.abs([r[6] / max(r[7], 1e-9) for r in z])
    print(f'  КОНТРОЛЬ c = 0: худшее отклонение {zz.max():.1f} сигм')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""ИЗВЛЕЧЕНИЕ ИЗ ОДНОГО ТУРНИРА: несёт ли он единогласный порядок.

noiseord2.py: моё извлечение было негодным. Подотношение линейного
порядка с транзитивным замыканием дало Q с долей 0.9896 - практически
полный линейный порядок, и точность 0.0154 просто равна плотности P.
Процедура ответа не даёт.

И постановка была нечестной: ранг Борда я считал ПО ШКАЛАМ, тогда как
вопрос - что извлекается из ОДНОГО турнира, без доступа к шкалам.

Переделка. Из T доступна только его собственная структура. Берём
исходящую степень как оценку (стандартный ранг турнира: кто раньше, тот
предшествует большему числу), и упорядочиваем дуги T по РАЗРЫВУ оценок.
Гипотеза: единогласные пары - те, где разрыв велик.

МЕРА, честная: берём K верхних дуг по разрыву и смотрим, какая доля из
них действительно единогласна. Базовая линия - случайные дуги T, у них
доля равна плотности P внутри T.

ЧТО РАЗЛИЧАЕТ ИСХОДЫ:
  * точность у верхних дуг много выше базовой => турнир НЕСЁТ порядок,
    шум искажает, а не заменяет;
  * точность около базовой => информация утрачена, шум заменяет.
"""
import numpy as np

from orthant import scales, thresh_order, rf

N = 400
K = 7


def main():
    print(__doc__)
    rs = np.random.default_rng(1020304)
    S = scales(N, K, rs)
    P = thresh_order(S, K)
    T = thresh_order(S, (K + 1) // 2)
    npair = N * (N - 1) // 2
    base = float(P.sum()) / float(T.sum())
    print(f'N={N}, k={K}: единогласных дуг {int(P.sum())}, '
          f'дуг турнира {int(T.sum())}')
    print(f'базовая линия (случайная дуга T единогласна): {base:.5f}')

    sc = T.sum(axis=1).astype(float)          # исходящая степень
    ii, jj = np.nonzero(T)
    gap = sc[ii] - sc[jj]
    order = np.argsort(-gap)
    tru = P[ii, jj]

    print(f"\n{'K верхних':>11}{'точность':>11}{'подъём':>9}"
          f"{'полнота':>10}")
    tot_true = float(P.sum())
    for frac in (0.005, 0.01, 0.02, 0.05, 0.10, 0.25):
        kk = max(1, int(len(order) * frac))
        sel = order[:kk]
        prec = float(tru[sel].sum()) / kk
        print(f'{kk:>11}{prec:>11.5f}{prec / base:>9.1f}x'
              f'{float(tru[sel].sum()) / tot_true:>10.4f}', flush=True)

    print('\nКОНТРОЛЬ: случайный турнир той же плотности, та же процедура')
    U = np.triu(rs.random((N, N)) < 0.5, 1)
    U = U | (~U.T & np.tril(np.ones((N, N), bool), -1))
    np.fill_diagonal(U, False)
    sc2 = U.sum(axis=1).astype(float)
    i2, j2 = np.nonzero(U)
    g2 = sc2[i2] - sc2[j2]
    o2 = np.argsort(-g2)
    t2 = P[i2, j2]
    b2 = float(t2.sum()) / len(t2)
    for frac in (0.01, 0.05):
        kk = max(1, int(len(o2) * frac))
        prec = float(t2[o2[:kk]].sum()) / kk
        print(f'  K={kk}: точность {prec:.5f}, базовая {b2:.5f}, '
              f'подъём {prec / max(b2, 1e-9):.1f}x')
    print('\nЧТЕНИЕ: подъём у настоящего турнира много больше, чем у')
    print('случайного => турнир НЕСЁТ порядок, шум искажает, а не заменяет.')


if __name__ == '__main__':
    main()

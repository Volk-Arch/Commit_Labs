#!/usr/bin/env python3
"""ОПЕРАТОР В ЧЕТЫРЁХМЕРИИ, где весам можно верить.

waveop2.py показал: в 1+1 у меня неверна нормировка или веса — среднее
по многим засевам уходит как -148, -346, -728 вместо 4, то есть
линейно по N, и отстоит на 11...13 сигм. Доминирует собственный член
-2 rho f(x) ~ -0.4n (предсказание -120, -240, -480 против замеренных
-148, -346, -728). Это не шум, это неверная нормировка, и на угаданном
операторе дальше идти нельзя.

В четырёхмерии веса известны точно: (-1, 9, -16, 8), и утренний
двухточечный интеграл подтвердил тождество sum w_m Г(m+1/2)/m! = 0
машинно (`nm-doc.md`) — а это РОВНО условие, делающее оператор
даламберианом. Значит здесь проверка осмысленна.

Оператор: (B f)(x) = (k / l^2) [ -f(x) + sum_{y<x} w_{|I(y,x)|} f(y) ],
l^2 = rho^{-1/2} в d=4 (l^4 = 1/rho), k подбирается НЕ по памяти, а
проверкой: печатается отношение замеренного к точному, и если оно
постоянно по трём функциям и по N — нормировка найдена, и это сама
проверка.

Точные ответы при сигнатуре (+,-,-,-): кв(t^2) = 2, кв(x^2) = -2,
кв(t^2 - r^2) = 2 - 6 = -4... в d=4 кв = d_t^2 - лаплас, значит
кв(t^2) = 2, кв(|x|^2) = -6, кв(t^2 - |x|^2) = 8.
"""
import math

import numpy as np

from qcarrier import sprinkle4

W4 = {0: -1.0, 1: 9.0, 2: -16.0, 3: 8.0}


def main():
    print(__doc__)
    rs = np.random.default_rng(3141)
    V = math.pi / 24.0
    print(f"{'N':>6}{'засевов':>9}{'точек':>8}{'<Bt²>':>11}{'<B|x|²>':>11}"
          f"{'<Bτ²>':>11}{'отн. к 2,-6,8':>16}")
    for n, nspr in ((500, 40), (1000, 20), (2000, 8)):
        acc = [[], [], []]
        for _ in range(nspr):
            P = sprinkle4(n, rs, 1.0).astype(np.float64)
            rho = n / V
            t, X = P[:, 0], P[:, 1:]
            dt = t[None, :] - t[:, None]
            d = X[None, :, :] - X[:, None, :]
            r2 = (d * d).sum(-1)
            Rc = (dt > 0) & (dt * dt > r2)
            F = Rc.astype(np.float32)
            Iv = np.rint(F @ F).astype(np.int32)
            B = np.zeros((n, n))
            for m, w in W4.items():
                B += w * (Rc.T & (Iv.T == m))
            np.fill_diagonal(B, -1.0)
            B *= math.sqrt(rho)                 # 1/l^2 = sqrt(rho)
            rr = (X * X).sum(1)
            core = (t > 0.4) & (t < 0.6) & (rr < 0.01)
            if core.sum() < 2:
                continue
            for i, f in enumerate((t * t, rr, t * t - rr)):
                acc[i].extend(((B @ f)[core]).tolist())
        ms = [float(np.mean(a)) if a else float('nan') for a in acc]
        es = [float(np.std(a)) / math.sqrt(max(len(a), 1)) for a in acc]
        exact = (2.0, -6.0, 8.0)
        rel = [m / e for m, e in zip(ms, exact)]
        print(f'{n:>6}{nspr:>9}{len(acc[0]):>8}'
              + ''.join(f'{v:>11.2f}' for v in ms)
              + '   ' + ', '.join(f'{v:.3g}' for v in rel), flush=True)
    print('\nЧТЕНИЕ: если отношения к 2, -6, 8 ОДИНАКОВЫ между собой и по')
    print('N — нормировка найдена и оператор верен с точностью до неё.')
    print('Если отношения разные — неверны сами веса или постановка.')


if __name__ == '__main__':
    main()

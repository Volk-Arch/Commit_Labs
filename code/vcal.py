#!/usr/bin/env python3
"""ВЫВОД КАЛИБРОВКИ `V2CAL` — вместо замера.

ЗАЧЕМ. В коде стоит `V2CAL = -0.0201 +- 0.0028  # калибровка из
curve.py/invert.py`, то есть ЗАМЕРЕНА. Но это чистое число, зависящее
только от размерности и формы ромба — такое же по природе, как
постоянные `c_k`, которые выведены. Её погрешность 14% — систематика,
которая не падает ни от какого набора и которая упирает хорошо
измеряемое направление (статистика там 5%). Вывод убирает её начисто.

КАК. Для конформно-плоских метрик `a(eta)^2 eta_{mu nu}` причинность
ТОЧНО плоская — причинность конформно-инвариантна, и код это уже
использует (отбор интервала идёт по плоскому условию
`(dt)^2 > |dx|^2`). Значит кривизна входит ЕДИНСТВЕННЫМ образом: через
плотность точек. Физическая плотность постоянна, объёмный элемент
`a^4 d^4x`, поэтому координатный вес `w = a^4`.

Нормировка в коде — `X_2 = C_2/(c_2 a(a-1)) - 1` при НАБЛЮДЁННОМ `a`,
то есть при заданном числе точек они независимы с плотностью `~ w`. Для
пуассоновского процесса второй факториальный момент даёт точно

    1 + X_2 = [ int int_{x < y} w w ] / [ c_2 (int w)^2 ]

Это ТОЧНОЕ выражение, без сприклинга и без пуассоновского шума.

Разложим `w` у середины интервала: `phi = 4 ln a`, `delta = eta - eta_m`,

    w = 1 + phi' delta + (phi'' + phi'^2) delta^2/2

Первый порядок уходит по симметрии отражения времени (ромб
симметричен, а множество упорядоченных пар при отражении переходит в
себя с обращением). Остаются ТРИ чистых геометрических момента ромба:

    s = <delta^2>                 по ромбу
    q = <delta_x^2 + delta_y^2>   по упорядоченным парам
    p = <delta_x delta_y>         по упорядоченным парам

Важно: `p` НЕ нуль, хотя каждый сомножитель в среднем нуль — у
упорядоченной пары `x` сидит в ранней половине, `y` в поздней, и
корреляция порядка остаётся. Именно её я сначала потерял.

Тогда с `u = a''/a`, `vv = a'^2/a^2` (откуда `R_etaeta = 3(vv - u)`,
`R_xx = u + vv`), и `phi' = 4 a'/a`, `(phi''+phi'^2)/2 = 2u + 6vv`:

    X_2 = [ 16 vv p + (2u + 6vv)(q - 2s) ] / tau^2-единицы

А проверенный конвейер утверждает `X_2 = V2CAL * R_uu * tau^2`, что при
покое даёт `V2CAL * 3(vv - u)`. Сравнение коэффициентов при `u` и при
`vv` ПО ОТДЕЛЬНОСТИ даёт ДВА независимых выражения:

    lambda = (4/3) p           (из коэффициента при vv)
    lambda = -(q - 2s)/1.5     (из коэффициента при u)

Их совпадение — внутренний контроль вывода, не использующий ни одного
замера. Затем оба сравниваются с замеренным -0.0201 +- 0.0028.

КОНТРОЛЬ ВЫБОРКИ. Тем же сэмплером считается сама постоянная `c_2`,
у которой есть замкнутая форма (0.05 при d = 4). Если сэмплер врёт на
ней, моментам верить нельзя.

Сэмплер точный, без отбрасывания: `x` берётся равномерно в ромбе
`I(p,q)`, затем `y` равномерно в ромбе `I(x,q)` в его СОБСТВЕННОЙ
системе с переносом обратно бустом, а вес пары — объём `I(x,q)`.

  python3 vcal.py [--n 4000000]
"""
import argparse
import math

import numpy as np

from pencil import c_k


def ball(rs, n, dim, R):
    """Равномерно в (dim)-шаре радиуса R (вектор R длины n)."""
    g = rs.normal(size=(n, dim))
    g /= np.linalg.norm(g, axis=1)[:, None]
    u = rs.random(n) ** (1.0 / dim)
    return g * (R * u)[:, None]


def in_diamond(rs, n, T, d=4):
    """Равномерно в ромбе собственного времени T: (t, x) в СОБСТВЕННОЙ
    системе. Плотность по t идёт как R(t)^{d-1}, R = min(t, T-t)."""
    # обратная функция распределения для R^{d-1} кусочно
    z = rs.random(n)
    half = z < 0.5
    y = np.where(half, 2 * z, 2 * (1 - z)) ** (1.0 / d)
    t = np.where(half, 0.5 * y, 1.0 - 0.5 * y) * T
    R = np.minimum(t, T - t)
    return t, ball(rs, n, d - 1, R)


def mink(a, b):
    return a[:, 0] * b[:, 0] - np.einsum('ij,ij->i', a[:, 1:], b[:, 1:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=4000000)
    ap.add_argument('--blocks', type=int, default=8)
    g = ap.parse_args()
    print(__doc__.split('  python3')[0].rstrip())
    print()
    T, d = 1.0, 4
    rs = np.random.default_rng(20261008)
    c2 = c_k(2)
    print(f'd = {d}, T = {T}; замкнутая форма c_2 = {c2:.6f}')
    print(f'точек {g.n * g.blocks} в {g.blocks} блоках')
    print()

    acc = {k: [] for k in ('c2', 'p', 'q', 's')}
    for b in range(g.blocks):
        n = g.n
        tx, sx = in_diamond(rs, n, T, d)
        x = np.column_stack([tx, sx])
        q4 = np.zeros((n, d)); q4[:, 0] = T
        dd = q4 - x
        tau2 = mink(dd, dd)
        ok = tau2 > 0
        x, dd, tau2 = x[ok], dd[ok], tau2[ok]
        tau = np.sqrt(tau2)
        m = len(x)
        # ромб I(x,q): собственная система, ось времени вдоль dd
        e0 = dd / tau[:, None]
        # ортонормированный базис 3-пространства, ортогонального e0
        B = np.zeros((m, d - 1, d))
        seed = np.zeros((m, d - 1, d))
        seed[:, 0, 1] = 1.0; seed[:, 1, 2] = 1.0; seed[:, 2, 3] = 1.0
        for i in range(d - 1):
            v = seed[:, i, :].copy()
            # вычесть проекцию на e0 (минковская, e0.e0 = +1)
            v -= (mink(v, e0))[:, None] * e0
            for j in range(i):
                # базис пространственный: e.e = -1, проекция со знаком
                v -= (-mink(v, B[:, j, :]))[:, None] * B[:, j, :]
            nn = np.sqrt(np.maximum(-mink(v, v), 1e-300))
            B[:, i, :] = v / nn[:, None]
        ty, sy = in_diamond(rs, m, 1.0, d)       # в единицах tau
        yloc_t = ty * tau
        y = x + yloc_t[:, None] * e0
        for i in range(d - 1):
            y = y + (sy[:, i] * tau)[:, None] * B[:, i, :]
        vol = tau ** d                            # ~ объём I(x,q)
        dx = x[:, 0] - 0.5 * T
        dy = y[:, 0] - 0.5 * T
        acc['c2'].append(vol.mean())
        acc['p'].append((vol * dx * dy).sum() / vol.sum())
        acc['q'].append((vol * (dx * dx + dy * dy)).sum() / vol.sum())
        acc['s'].append((dx * dx).mean())
        print(f'  блок {b+1}/{g.blocks}: c_2 оценка '
              f'{acc["c2"][-1]*(math.pi/24)/((math.pi/24)*T**d):.6f}',
              flush=True)

    def mu_se(k):
        a = np.array(acc[k])
        return a.mean(), a.std(ddof=1) / math.sqrt(len(a))

    c2m, c2e = mu_se('c2')
    print()
    print('=' * 72)
    print('КОНТРОЛЬ ВЫБОРКИ: постоянная c_2 тем же сэмплером')
    print(f'  замерено {c2m:.6f} +- {c2e:.6f}, замкнутая форма {c2:.6f}, '
          f'{abs(c2m-c2)/max(c2e,1e-12):.1f} сигм')
    ok = abs(c2m - c2) < 4 * c2e
    print(f'  -> {"сэмплер верен" if ok else "СЭМПЛЕР ВРЁТ, моментам не верить"}')
    print()
    print('=' * 72)
    print('ГЕОМЕТРИЧЕСКИЕ МОМЕНТЫ РОМБА (в единицах T^2)')
    pm, pe = mu_se('p'); qm, qe = mu_se('q'); sm, se_ = mu_se('s')
    print(f'  s = <delta^2>              = {sm:+.6f} +- {se_:.6f}'
          f'   (аналитически 1/60 = {1/60:+.6f})')
    print(f'  q = <dx^2 + dy^2>          = {qm:+.6f} +- {qe:.6f}')
    print(f'  p = <dx dy>                = {pm:+.6f} +- {pe:.6f}')
    print()
    print('=' * 72)
    print('ДВА НЕЗАВИСИМЫХ ОПРЕДЕЛЕНИЯ lambda = V2CAL')
    l1, e1 = (4.0 / 3.0) * pm, (4.0 / 3.0) * pe
    l2, e2 = -(qm - 2 * sm) / 1.5, math.sqrt(qe ** 2 + 4 * se_ ** 2) / 1.5
    print(f'  из коэффициента при vv:  lambda = (4/3) p      = '
          f'{l1:+.5f} +- {e1:.5f}')
    print(f'  из коэффициента при u:   lambda = -(q-2s)/1.5  = '
          f'{l2:+.5f} +- {e2:.5f}')
    dz = abs(l1 - l2) / math.sqrt(e1 ** 2 + e2 ** 2)
    print(f'  расхождение {dz:.1f} сигм -> '
          f'{"СОГЛАСНЫ" if dz < 3 else "НЕ СОГЛАСНЫ: вывод неполон"}')
    print()
    print('=' * 72)
    print('СРАВНЕНИЕ С ЗАМЕРЕННЫМ')
    MEAS, MERR = -0.0201, 0.0028
    for nm, l, e in (('из vv', l1, e1), ('из u', l2, e2)):
        print(f'  {nm:>7}: {l:+.5f} +- {e:.5f}  против замера '
              f'{MEAS:+.5f} +- {MERR:.5f}   '
              f'{abs(l-MEAS)/math.sqrt(e**2+MERR**2):.1f} сигм')


if __name__ == '__main__':
    main()

"""α из кристалла. Унимодулярная гравитация: Λ/(8πG) сопряжена 4-объёму V:
ΔV·ΔΛ ≳ 4πℓ_p².  У кристалла с дрожью ν на событие и ячейкой ℓ (ρ = ℓ⁻⁴):
ΔV = ℓ²·√(νV).  Тогда ΔΛ = 4πℓ_p²/(ℓ²√(νV)) = 8πα/√V  ⇒  α = ½(ℓ_p/ℓ)²/√ν.
Обратно: ℓ/ℓ_p = (2α√ν)^(−1/2). α — из данных (frozen-doc), ν — из кристалла."""
import math
print('ν: размытый край w=0.1 → √ν=0.42 (ν=0.18); w=0.3 → √ν=0.60 (ν=0.36); хаос: ν = 0.35…0.8; монетка: ν = 1')
print(f'{"α":>6} | ' + ' | '.join(f'ν={n:<4}' for n in (0.18, 0.36, 0.6, 0.8, 1.0)))
for a in (0.02, 0.025, 0.03, 0.035, 0.04):
    print(f'{a:6.3f} | ' + ' | '.join(f'{(2*a*math.sqrt(n))**-0.5:6.2f}' for n in (0.18, 0.36, 0.6, 0.8, 1.0)))

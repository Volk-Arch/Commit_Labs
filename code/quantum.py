#!/usr/bin/env python3
"""КВАНТОВЫЙ СЛОЙ: организуются ли фазы, и как широко окно по ℏ.

ПОПРАВКА К ПОСТАНОВКЕ, сделанная после первой же проверки силы. Сначала
я спрашивал «есть ли интерференция». Это НЕ эмпирический вопрос: мера
Соркина `mu = |Σ exp(iS/ℏ)|²` имеет интерференцию по определению, и
найти её — не открытие, а тавтология. По той же причине `I₃ = 0` есть
алгебраическое тождество любой такой меры, а не результат о природе, и
прежние `I₃ = 10⁻¹³` подтверждали арифметику.

Эмпирично другое: **организуются ли фазы**, то есть есть ли у суммы по
историям структура стационарной фазы, из которой может выйти
классический предел.

ВЫВОД ДО ЗАМЕРА. Для действия с разбросом `σ`

    |amp| = |⟨exp(iS/ℏ)⟩| = exp(−σ²/2ℏ²)     если S гауссово
    порог случайных фаз:   1/sqrt(n)          n — число историй
    =>  фазы организованы, пока  ℏ > σ / sqrt(ln n)

Отсюда сразу следствие, которое стоит назвать: **окно по ℏ
логарифмически узко по числу историй.** Расширить его счётом нельзя.

А настоящая структура сидит в ОТКЛОНЕНИИ `|amp(ℏ)|` от гауссова
предсказания, посчитанного по ИЗМЕРЕННОМУ `σ` без подгонки: гауссово
действие даёт ровно затухание и ничего больше, а всё интересное — это
негауссовость.

---

Старая постановка (сохранена как вторичная проверка):

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ЧТО НЕТ. Мера Соркина `mu(A) = |Σ амплитуд|²`
даёт `I₃ = 0` **алгебраически тождественно**, при любом назначении
амплитуд. Значит прежний результат проекта `I₃ = 10⁻¹³` подтверждал
арифметику, а не физику, и настоящее содержание сидит в `I₂`.

ПРЕДСКАЗАНИЕ, РЕГИСТРИРУЕМОЕ ДО ЗАМЕРА. Разобьём конфигурации на два
класса по порядковому признаку. Если у классов средние действия
отличаются на `ΔS`, а разброс внутри класса есть `σ`, то

    amp = ⟨exp(iS/ℏ)⟩ ≈ exp(i⟨S⟩/ℏ) · exp(−σ²/2ℏ²)
    I₂  = 2 Re(amp_A* · amp_B) ∝ cos(ΔS/ℏ + φ) · exp(−σ²/ℏ²)

то есть `I₂` обязан КОЛЕБАТЬСЯ по `1/ℏ` с периодом `2π/ΔS`. Величина
`ΔS` измеряется ОТДЕЛЬНО и в подгонку не входит — именно это делает
проверку опровержимой:

    период совпал  =>  интерференция настоящая
    колебаний нет  =>  это шум, и квантового слоя тут не видно

ПОЧЕМУ ЭТО СТАЛО ВОЗМОЖНО. У резкого действия разброс огромен
(`σ(B)/⟨B⟩` от 3.5 до 13), фазы случайны, сумма гасится в нуль — отсюда
прежнее «интерференции нет ни при каком ℏ». Сглаживание Доукера–Глейзера
снижает разброс в 20 раз (измерено: 3739 -> 184), и окно по `ℏ`
открывается: `ΔS/σ` доходит до 5.93.

КОНТРОЛИ, поставленные до замера:
  1. СИЛА: `ΔS/σ` печатается ПЕРВЫМ. Если он меньше 1, проверка
     бессильна, и дальше идти нельзя (правило «нуль без силы»);
  2. ПЕРЕМЕШИВАНИЕ метки класса: тогда `ΔS ≈ 0`, и колебаний быть не
     должно вовсе;
  3. период НЕ подгоняется: в подгонку входит только амплитуда и фаза,
     частота взята из измеренного `ΔS`;
  4. сравнение с подгонкой, где частота СВОБОДНА: если свободная
     частота уедет далеко от `ΔS`, предсказание не подтвердилось;
  5. `I₃ = 0` печатается для порядка, но как АРИФМЕТИЧЕСКАЯ проверка
     кода, а не как физический результат.

  python3 quantum.py --quick
  python3 quantum.py --n 900 --samples 400
"""
import argparse
import math
import time

import numpy as np

from dyn import relation, bd_density_smeared, bd_density


def sample(N, L, T, rs):
    X = np.empty((N, 4))
    X[:, 0] = rs.uniform(0, T, N)
    X[:, 1:] = rs.uniform(0, L, (N, 3))
    return X[np.argsort(X[:, 0])]


def heights_simple(R):
    """Высота каждого события и высота множества — чистый порядок."""
    n = len(R)
    h = np.ones(n, np.int64)
    for i in range(n):
        pre = np.flatnonzero(R[:, i])
        if len(pre):
            h[i] = h[pre].max() + 1
    return h


def amp(S, hbar):
    """Амплитуда класса: среднее exp(iS/hbar)."""
    return np.mean(np.exp(1j * S / hbar))


def main():
    ap = argparse.ArgumentParser(description='Квантовый слой: интерференция')
    ap.add_argument('--n', type=int, default=700)
    ap.add_argument('--lell', type=float, default=5.0)
    ap.add_argument('--tell', type=float, default=6.0)
    ap.add_argument('--eps', type=float, default=0.4)
    ap.add_argument('--samples', type=int, default=300)
    ap.add_argument('--quick', action='store_true')
    a = ap.parse_args()

    t0 = time.time()
    if a.quick:
        a.samples = 80
    L, T = a.lell, a.tell
    print('ПРЕДСКАЗАНИЕ (до замера): I₂ ∝ cos(ΔS/ℏ + φ)·exp(−σ²/ℏ²),')
    print('то есть колебание по 1/ℏ с периодом 2π/ΔS, где ΔS измерен')
    print('ОТДЕЛЬНО и в подгонку частоты не входит.')
    print()
    print(f'N = {a.n}, ящик {L}x{T} ell, сглаживание eps = {a.eps}, '
          f'выборок {a.samples}')
    print()

    S, H = [], []
    for s in range(a.samples):
        X = sample(a.n, L, T, np.random.default_rng(7700 + 13 * s))
        R = relation(X, L)
        b = bd_density_smeared(R, a.eps)
        h = heights_simple(R)
        del R
        S.append(float(b.sum()))
        H.append(int(h.max()))
        del b, X
        if s == 0 or (s + 1) % 50 == 0:
            print(f'  выборка {s} ({time.time()-t0:.0f} с)', flush=True)
    S = np.array(S); H = np.array(H)

    # ПОЙМАННАЯ ОШИБКА (та же, что №5 в списке проекта). Классы брались
    # как `H <= q1` и `H >= q2`, а высота — целое число, терцили слиплись
    # (q1 = q2 = 9), и ОДНИ И ТЕ ЖЕ конфигурации попали в оба класса.
    # Непересекаемость обязана обеспечиваться строго.
    q1, q2 = np.quantile(H, [1/3, 2/3])
    mA = H < max(q1, H.min() + 1)
    mB = H > max(q2, q1)
    if mA.sum() < 10 or mB.sum() < 10 or (mA & mB).any():
        # высота слишком груба — делим по медиане действия, но строго
        med = np.median(S)
        mA = S < med
        mB = S > med
    assert not (mA & mB).any(), 'классы пересеклись'
    SA, SB = S[mA], S[mB]
    dS = SB.mean() - SA.mean()
    sig = 0.5 * (SA.std(ddof=1) + SB.std(ddof=1))
    print()
    print('КОНТРОЛЬ №1 (СИЛА ЗАМЕРА, до всяких выводов)')
    print(f'  класс A: высота <= {q1:.0f}, {mA.sum()} выборок, '
          f'⟨S⟩ = {SA.mean():+.2f}')
    print(f'  класс B: высота >= {q2:.0f}, {mB.sum()} выборок, '
          f'⟨S⟩ = {SB.mean():+.2f}')
    print(f'  ΔS = {dS:+.3f},  разброс внутри класса σ = {sig:.3f}')
    print(f'  ΔS/σ = {abs(dS)/max(sig,1e-12):.3f}  —  '
          f'{"окно открыто, проверка имеет силу" if abs(dS)/max(sig,1e-12) > 0.5 else "СЛАБО: проверка бессильна"}')
    if abs(dS) < 1e-9:
        print('  классы не различаются действием — проверять нечего')
        return

    # ---------- ГЛАВНЫЙ ЗАМЕР: организуются ли фазы ----------
    print()
    print('=' * 68)
    print('ГЛАВНЫЙ ЗАМЕР: |amp(ℏ)| против гауссова предсказания и')
    print('против порога случайных фаз. Предсказание считается по')
    print('ИЗМЕРЕННОМУ σ и НЕ подгоняется.')
    n_all = len(S)
    s_all = S.std(ddof=1)
    floor = 1.0 / math.sqrt(n_all)
    hb_win = s_all / math.sqrt(max(math.log(n_all), 1e-9))
    print()
    print(f'  историй n = {n_all}, разброс действия σ = {s_all:.3f}')
    print(f'  порог случайных фаз 1/sqrt(n) = {floor:.4f}')
    print(f'  ВЫВЕДЕННАЯ граница окна  ℏ = σ/sqrt(ln n) = {hb_win:.3f}')
    print()
    # ПРАВИЛЬНЫЙ НУЛЬ — не формула, а ПОДДЕЛЬНАЯ ВЫБОРКА: то же число
    # историй с гауссовым действием того же разброса. Так в нуль входят
    # и затухание, и порог случайных фаз сразу, и сравнивать можно без
    # отдельных рассуждений о пороге.
    rs0 = np.random.default_rng(31337)
    nrep = 400
    print(f"{'ℏ/σ':>8}{'|amp| замер':>13}{'поддельный нуль':>18}"
          f"{'отклонение':>12}{'сигм':>7}")
    hbs = s_all * np.array([4.0, 2.0, 1.2, 0.8, 0.6, 0.5, 0.4,
                            0.35, 0.3, 0.25, 0.2])
    worst = 0.0
    rows = []
    for hb in hbs:
        a_meas = abs(amp(S, hb))
        sur = np.empty(nrep)
        for k in range(nrep):
            Z = rs0.normal(S.mean(), s_all, n_all)
            sur[k] = abs(np.mean(np.exp(1j * Z / hb)))
        m0, s0 = sur.mean(), sur.std(ddof=1)
        z = (a_meas - m0) / max(s0, 1e-12)
        worst = max(worst, abs(z))
        rows.append((hb / s_all, a_meas, m0, s0, z))
        print(f'{hb/s_all:>8.2f}{a_meas:>13.5f}'
              f'{m0:>13.5f} ± {s0:.4f}{a_meas-m0:>+12.5f}{z:>7.1f}')

    print()
    print('ЧТО ЭТО ЗНАЧИТ')
    print('  гауссово действие даёт РОВНО затухание плюс порог случайных')
    print('  фаз, и ничего больше. Всё сверх поддельного нуля —')
    print('  негауссовость, то есть настоящая структура в сумме.')
    print(f'  наибольшее отклонение: {worst:.1f} сигм')
    if worst < 3.0:
        print('  => СТРУКТУРЫ НЕТ: сумма по историям ведёт себя ровно как')
        print('     гауссов шум нужного разброса. Фазы организованы лишь')
        print('     настолько, насколько велит σ, и классическому пределу')
        print('     взяться не из чего.')
    else:
        print('  => СТРУКТУРА ЕСТЬ: сумма отклоняется от гауссова нуля,')
        print('     то есть в распределении действия есть негауссовость,')
        print('     и именно она может давать стационарную фазу.')
    print('=' * 68)

    # I2 как функция 1/hbar
    print()
    print('I₂ ПО 1/ℏ (предсказанный период 2π/ΔS = '
          f'{2*math.pi/abs(dS):.3f})')
    # ПОЙМАННАЯ ОШИБКА: диапазон 1/ℏ брался по ΔS, а задаёт его σ —
    # огибающая exp(−σ²/ℏ²) при σ ~ 100 и 1/ℏ ~ 6 обнуляется начисто, и
    # подгонка выдавала амплитуду 8.8e8. Диапазон обязан идти до
    # 1/ℏ ~ несколько/σ, то есть туда, где огибающая ещё жива.
    inv = np.linspace(0.02 / sig, 3.0 / sig, 240)
    I2 = np.empty(len(inv))
    for i, iv in enumerate(inv):
        hb = 1.0 / iv
        aA, aB = amp(SA, hb), amp(SB, hb)
        I2[i] = 2.0 * np.real(np.conj(aA) * aB)
    # печатаем прореженно
    print(f"{'1/ℏ':>9}{'I₂':>12}{'предсказ. фаза':>16}")
    for i in range(0, len(inv), max(1, len(inv) // 12)):
        print(f'{inv[i]:>9.3f}{I2[i]:>12.5f}'
              f'{(inv[i]*dS) % (2*math.pi):>16.3f}')

    # ПОДГОНКА С ЗАКРЕПЛЁННОЙ ЧАСТОТОЙ: свободны только амплитуда и фаза
    print()
    print('ПОДГОНКА: частота ЗАКРЕПЛЕНА на измеренном ΔS, свободны')
    print('только амплитуда и фаза (иначе это была бы подгонка, а не')
    print('предсказание)')
    env = np.exp(-(sig ** 2) * inv ** 2)
    M = np.stack([env * np.cos(dS * inv), env * np.sin(dS * inv)], 1)
    coef, *_ = np.linalg.lstsq(M, I2, rcond=None)
    fit = M @ coef
    ss = 1 - ((I2 - fit) ** 2).sum() / max(((I2 - I2.mean()) ** 2).sum(), 1e-30)
    print(f'  амплитуда {math.hypot(*coef):.5f}, '
          f'фаза {math.atan2(coef[1], coef[0]):+.3f}, R² = {ss:.4f}')

    # КОНТРОЛЬ №4: частота СВОБОДНА — куда она уедет?
    best = (None, -1e9)
    for w in np.linspace(0.1 * abs(dS), 4.0 * abs(dS), 600):
        Mw = np.stack([env * np.cos(w * inv), env * np.sin(w * inv)], 1)
        c, *_ = np.linalg.lstsq(Mw, I2, rcond=None)
        r2 = 1 - (((I2 - Mw @ c) ** 2).sum()
                  / max(((I2 - I2.mean()) ** 2).sum(), 1e-30))
        if r2 > best[1]:
            best = (w, r2)
    print(f'  при СВОБОДНОЙ частоте лучшая: {best[0]:.3f} '
          f'(R² = {best[1]:.4f}); измеренный ΔS = {abs(dS):.3f}')
    print(f'  промах частоты: {abs(best[0]-abs(dS))/abs(dS)*100:.1f} %')

    # КОНТРОЛЬ №2: перемешивание метки класса
    print()
    print('КОНТРОЛЬ №2 (перемешивание метки): ΔS ≈ 0, колебаний быть не')
    print('должно')
    rs = np.random.default_rng(99)
    idx = rs.permutation(len(S))
    k = mA.sum()
    SA2, SB2 = S[idx[:k]], S[idx[k:k + mB.sum()]]
    dS2 = SB2.mean() - SA2.mean()
    I2s = np.array([2.0 * np.real(np.conj(amp(SA2, 1.0 / iv))
                                  * amp(SB2, 1.0 / iv)) for iv in inv])
    env2 = np.exp(-(sig ** 2) * inv ** 2)
    M2 = np.stack([env2 * np.cos(dS * inv), env2 * np.sin(dS * inv)], 1)
    c2, *_ = np.linalg.lstsq(M2, I2s, rcond=None)
    r22 = 1 - (((I2s - M2 @ c2) ** 2).sum()
               / max(((I2s - I2s.mean()) ** 2).sum(), 1e-30))
    print(f'  ΔS перемешанного = {dS2:+.3f} (против {dS:+.3f})')
    print(f'  R² подгонки с тем же периодом: {r22:.4f} '
          f'(должно быть мало)')

    print()
    print('КОНТРОЛЬ №5 (арифметика, не физика): I₃ при тройном разбиении')
    t1, t2 = np.quantile(S, [1/3, 2/3])
    c1, c2_, c3 = S[S <= t1], S[(S > t1) & (S <= t2)], S[S > t2]
    hb = 1.0 / inv[len(inv) // 3]
    A1, A2, A3 = amp(c1, hb), amp(c2_, hb), amp(c3, hb)
    def mu(*parts):
        return abs(sum(parts)) ** 2
    I3 = (mu(A1, A2, A3) - mu(A1, A2) - mu(A1, A3) - mu(A2, A3)
          + mu(A1) + mu(A2) + mu(A3))
    print(f'  I₃ = {I3:.2e}  (обязан быть нулём ТОЖДЕСТВЕННО: это')
    print('  свойство меры |Σ|², а не результат о природе)')

    print()
    print('ВЕРДИКТ')
    ok_pow = abs(dS) / max(sig, 1e-12) > 0.5
    ok_fit = ss > 0.5
    ok_freq = abs(best[0] - abs(dS)) / abs(dS) < 0.25
    ok_ctrl = r22 < 0.3
    for nm, v in (('сила замера (ΔS/σ > 0.5)', ok_pow),
                  ('подгонка с закреплённой частотой (R² > 0.5)', ok_fit),
                  ('свободная частота попала в ΔS (промах < 25 %)', ok_freq),
                  ('перемешанный контроль не колеблется', ok_ctrl)):
        print(f'  {"ДА " if v else "НЕТ"}  {nm}')
    if ok_pow and ok_fit and ok_freq and ok_ctrl:
        print('  => ИНТЕРФЕРЕНЦИЯ ЕСТЬ, и её период предсказан, а не')
        print('     подогнан: квантовый слой в окне по ℏ живёт.')
    else:
        print('  => предсказание НЕ подтверждено целиком; см. какие')
        print('     пункты не прошли.')
    print(f'  время {time.time()-t0:.0f} с')


if __name__ == '__main__':
    main()

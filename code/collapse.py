#!/usr/bin/env python3
"""ЧТО ИМЕННО ГОНЯЛО ПОКАЗАТЕЛЬ: проверка схлопыванием по двум шкалам.

ЗАДАЧА. Показатель спадания дефицита хода часов ехал от внешней отсечки:
−0.906 / −0.953 / −1.041 / −1.238 (`newton-doc.md`). Систематика ±0.1
записана, но НЕ ОБЪЯСНЕНА, а необъяснённая систематика — это не ошибка
измерения, это непонятая физика.

`sharpen.py` показал, почему: местный показатель в скользящем окне НЕ
выходит на полку, он монотонно крутеет с расстоянием (при N = 8000 от
−0.81 на 2 ell до −1.77 на 5.5 ell). Степенного закона на всём отрезке
нет, и полная подгонка выдаёт «−1» лишь потому, что усредняет плоскую
внутреннюю область с крутой внешней. Красивое «−1» было совпадением
усреднения.

ПОДОЗРЕВАЕМЫХ ДВОЕ, и у каждого СВОЯ ШКАЛА:
  граница мира              — должна зависеть от r / R_мира
  дискретность и размазка   — должна зависеть от r / ell

Их можно развести, потому что при росте N при постоянном T эти шкалы
расходятся В РАЗНЫЕ СТОРОНЫ: ell убывает как N^(-1/4), значит одно и то
же r/ell отвечает всё меньшему r/R. Это та самая проверка, которая
поймала ошибку №7 (там я растил N при постоянном T, думая, что растит
мир, — а это измельчение). Здесь измельчение работает НА МЕНЯ: именно
оно разносит шкалы.

ПРЕДСКАЗАНИЕ, записанное ДО сравнения:
  если внешнее крутение — граница, кривые местного показателя лягут друг
  на друга при совпадающем r/R и разойдутся при совпадающем r/ell;
  если дискретность — наоборот.

Числа взяты из прогонов `sharpen.py` (столбец «с вычитанием базы»):
  python3 sharpen.py --n  8000 --radell 1.21 --seeds 40
  python3 sharpen.py --n 20000 --radell 1.21 --seeds 20
  python3 sharpen.py --n 60000 --radell 1.21 --seeds 10
  python3 collapse.py
"""
import numpy as np

# (N, радиус мира в ell, [(r/ell, местный показатель), ...])
RUNS = [
    (8000, 7.86, [
        (1.96, -0.813), (2.46, -0.819), (2.96, -0.847), (3.46, -0.951),
        (3.96, -1.053), (4.46, -1.406), (4.96, -1.675), (5.46, -1.768),
    ]),
    (20000, 9.89, [
        (1.96, -0.777), (2.46, -0.835), (2.96, -0.913), (3.46, -0.880),
        (3.96, -0.889), (4.46, -0.991), (4.96, -1.114), (5.46, -1.247),
        (5.96, -1.394), (6.46, -1.508), (6.96, -1.711),
    ]),
]


def interp(run, x, by):
    """Показатель при заданном r/ell (by='ell') или r/R (by='R')."""
    N, R, tab = run
    xs = np.array([t[0] if by == 'ell' else t[0] / R for t in tab])
    ys = np.array([t[1] for t in tab])
    if x < xs.min() or x > xs.max():
        return np.nan
    return float(np.interp(x, xs, ys))


def main():
    print(__doc__.split('Числа взяты')[0].rstrip())
    print()
    for N, R, tab in RUNS:
        print(f'  N = {N:>6}: радиус мира {R:.2f} ell, '
              f'{len(tab)} окон от {tab[0][0]} до {tab[-1][0]} ell')
    print()

    a, b = RUNS[0], RUNS[1]
    print('=' * 66)
    print('СРАВНЕНИЕ ПРИ СОВПАДАЮЩЕМ r/R МИРА (гипотеза: граница)')
    print(f"{'r/R':>7}{'N=8000':>10}{'N=20000':>10}{'расхож':>9}"
          f"{'r/ell у них':>16}")
    d1 = []
    for x in (0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70):
        va, vb = interp(a, x, 'R'), interp(b, x, 'R')
        if not (np.isfinite(va) and np.isfinite(vb)):
            continue
        d1.append(abs(va - vb))
        print(f'{x:>7.2f}{va:>10.3f}{vb:>10.3f}{abs(va-vb):>9.3f}'
              f'{x*a[1]:>8.2f}{x*b[1]:>8.2f}')
    print(f'  среднее расхождение: {np.mean(d1):.3f}')
    print()
    print('СРАВНЕНИЕ ПРИ СОВПАДАЮЩЕМ r/ell (гипотеза: дискретность)')
    print(f"{'r/ell':>7}{'N=8000':>10}{'N=20000':>10}{'расхож':>9}"
          f"{'r/R у них':>16}")
    d2 = []
    for x in (2.5, 3.0, 3.5, 4.0, 4.5, 5.0, 5.4):
        va, vb = interp(a, x, 'ell'), interp(b, x, 'ell')
        if not (np.isfinite(va) and np.isfinite(vb)):
            continue
        d2.append(abs(va - vb))
        print(f'{x:>7.2f}{va:>10.3f}{vb:>10.3f}{abs(va-vb):>9.3f}'
              f'{x/a[1]:>8.3f}{x/b[1]:>8.3f}')
    print(f'  среднее расхождение: {np.mean(d2):.3f}')
    print()
    print('=' * 66)
    print(f'  по r/R мира:  {np.mean(d1):.3f}')
    print(f'  по r/ell:     {np.mean(d2):.3f}')
    if np.mean(d1) < np.mean(d2) / 2:
        print('  => кривые ложатся по r/R, расходятся по r/ell:')
        print('     внешнее крутение есть ГРАНИЦА МИРА, не дискретность.')
        print('     Чистая область задаётся условием на r/R, а в ell она')
        print('     РАСТЁТ с N — поэтому показатель и ехал от отсечки.')
    elif np.mean(d2) < np.mean(d1) / 2:
        print('  => кривые ложатся по r/ell: виновата ДИСКРЕТНОСТЬ.')
    else:
        print('  => ни одна шкала не выделена; предсказание не прошло.')


if __name__ == '__main__':
    main()

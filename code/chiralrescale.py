#!/usr/bin/env python3
"""Переживает ли КИРАЛЬНОСТЬ перешкалирование: есть ли у нас структура
не на порядке.

КРИТЕРИЙ АРХИВА (`rescale-doc.md`): прогнать величину через независимое
монотонное перепараметризование каждой шкалы. Выжила — можно обсуждать
физический смысл; не выжила — обсуждать нечего. Так погибли плотность,
разброс шкал (заряд) и расстояние; так выжили размерность, высота,
спектр, действие, калибровочная фаза.

КИРАЛЬНОСТЬ через этот критерий НИКОГДА НЕ ПРОГОНЯЛИ. На бумаге она его
проходить не должна: чётность ранжировки приращений (ds_1..ds_k) не
сохраняется, если каждую шкалу перетянуть СВОЕЙ монотонной функцией —
приращения меняются неравномерно, и их порядок между шкалами может
перескочить.

ЗАЧЕМ ЭТО ВАЖНО. Сегодня измерено, что киральность — единственная наша
фаза, которая интерферирует: показатель 0.961 от истинных шкал против
2.000 от порядковых. Если она же не выживает при перешкалировании, то
интерферирует именно то, что НА ПОРЯДКЕ НЕ ЖИВЁТ.

КОНТРОЛИ:
  порядок            обязан совпасть полностью (0 различий)
  калибровочная фаза обязана выжить (она из порядка)
"""
import sys
import numpy as np

sys.path.insert(0, '/home/claude/code')
from weight import diamond, cone_rel

T, K, SEEDS = 2.0, 4, 3

def parity_mat(S, R):
    """Чётность ранжировки приращений для всех связанных пар."""
    N, k = S.shape
    ii, jj = np.where(R)                       # R[i,j]: j раньше i
    d = S[ii] - S[jj]                          # приращения по шкалам
    o = np.argsort(d, axis=1)
    inv = np.zeros(len(d), int)
    for p in range(k):
        for q in range(p + 1, k):
            inv += (o[:, p] > o[:, q])
    return ii, jj, 1 - 2 * (inv % 2)

print(f'шкал {K}, засевов {SEEDS}')
print('перешкалирование: каждой шкале СВОЯ монотонная функция')
print()
print(f"{'засев':>7}{'пар':>9}{'порядок совпал':>17}"
      f"{'киральность совпала':>21}{'калибр.фаза совпала':>21}")
for t in range(SEEDS):
    rs = np.random.default_rng(5701 + 31 * t)
    X = diamond(T, rs)
    N = len(X)
    R = cone_rel(X)
    u = rs.normal(size=(K, 3))
    u /= np.linalg.norm(u, axis=1, keepdims=True)
    S = X[:, 0:1] - X[:, 1:] @ u.T

    # нормируем каждую шкалу в [0,1), затем перетягиваем своей монотонной
    lo, hi = S.min(0), S.max(0)
    U = (S - lo) / (hi - lo + 1e-12)
    S2 = np.empty_like(U)
    funcs = ['tan', 'exp', 'pow5', 'logit']
    for m in range(K):
        f = funcs[m % 4]
        x = np.clip(U[:, m], 1e-9, 1 - 1e-9)
        if f == 'tan':
            S2[:, m] = np.tan(np.pi * (x - 0.5))
        elif f == 'exp':
            S2[:, m] = np.exp(6 * x)
        elif f == 'pow5':
            S2[:, m] = x ** 5
        else:
            S2[:, m] = np.log(x / (1 - x))

    # порядок из перешкалированных шкал: покомпонентное доминирование
    R1 = np.ones((N, N), bool); R2 = np.ones((N, N), bool)
    for m in range(K):
        R1 &= S[None, :, m] < S[:, None, m]
        R2 &= S2[None, :, m] < S2[:, None, m]
    np.fill_diagonal(R1, False); np.fill_diagonal(R2, False)
    same_order = float((R1 == R2).mean())

    i1, j1, p1 = parity_mat(S, R1)
    i2, j2, p2 = parity_mat(S2, R1)
    same_chir = float((p1 == p2).mean())

    A = R1.astype(np.float32)
    G1 = (A @ A.T) - (A.T @ A)
    A2 = R2.astype(np.float32)
    G2 = (A2 @ A2.T) - (A2.T @ A2)
    same_gauge = float((G1 == G2).mean())

    print(f'{t:>7}{len(p1):>9}{same_order:>17.6f}'
          f'{same_chir:>21.4f}{same_gauge:>21.6f}')

print()
print('  порядок 1.000000 и калибр.фаза 1.000000 — контроли пройдены')
print('  киральность заметно ниже 1 => она НЕ на порядке,')
print('  то есть это структура сверх него')
